#!/usr/bin/env bash
# Regenerate lib/zlib_inflate/inffixed_rs.rs from the PRISTINE inffixed.h.
#
# 544 table entries. Hand-copying them would be the largest transcription in
# this project by an order of magnitude and a permanent liability -- the same
# reasoning that made port/test/lib/ref_sort.c #include the pristine C instead
# of copying it (logs/hooks.md).
#
# It is belt and braces: the differential ALSO compares the generated Rust
# table against the C's lenfix[]/distfix[] entry by entry at run time, so a
# transcription error cannot survive even if this script is never re-run.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../.." && pwd)
src="$root/port/pristine/lib/zlib_inflate/inffixed.h"
dst="$root/port/tree/lib/zlib_inflate/inffixed_rs.rs"

python3 - "$src" "$dst" <<'PY'
import re, sys, pathlib

src, dst = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
text = src.read_text()

def table(name):
    m = re.search(r'static const code %s\[(\d+)\]\s*=\s*\{(.*?)\n\s*\};' % name,
                  text, re.S)
    if not m:
        sys.exit("no %s[] in %s" % (name, src))
    n = int(m.group(1))
    ents = re.findall(r'\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}', m.group(2))
    if len(ents) != n:
        sys.exit("%s: declared %d entries, found %d" % (name, n, len(ents)))
    return n, [tuple(int(x) for x in e) for e in ents]

nl, lenfix = table('lenfix')
nd, distfix = table('distfix')

def emit(name, n, ents):
    out = ["pub(crate) static %s: [Code; %d] = [" % (name, n)]
    for i in range(0, n, 4):
        row = "".join("c(%d,%d,%d)," % e for e in ents[i:i + 4])
        out.append("    " + row)
    out.append("];")
    return "\n".join(out)

body = '''// SPDX-License-Identifier: GPL-2.0
//
// NOT A CRATE. This file is `include!`d by lib/zlib_inflate/inflate_rs.rs and
// has no entry in any Makefile -- the same arrangement lib/list_helpers.rs
// uses, because kbuild compiles every non-rust/ .rs file as its own crate and
// there is no module system to share a type through. Its comments are `//`
// and not `//!`, because an inner doc comment cannot appear part-way through
// a file.
//
// GENERATED by port/test/zlib_inflate/gen-inffixed.sh from
// lib/zlib_inflate/inffixed.h, which is itself "Generated automatically by
// makefixed()". Do not edit.
//
// Two things stop this being the largest silent transcription in the project.
// It is generated rather than copied, and port/test/zlib_inflate/main.c
// compares every one of these %d entries against the C\'s lenfix[] and
// distfix[] on every run -- so a wrong entry is a test failure even if the
// generator is never run again.

/// Shorthand so the tables below fit the kernel\'s 80 columns.
const fn c(op: u8, bits: u8, val: u16) -> Code {
    Code { op, bits, val }
}

/// `lenfix[]`, the fixed literal/length table.
%s

/// `distfix[]`, the fixed distance table.
%s
''' % (nl + nd, emit('LENFIX', nl, lenfix), emit('DISTFIX', nd, distfix))

dst.write_text(body)
print("wrote %s: %d + %d entries" % (dst, nl, nd))
PY
