#!/usr/bin/env python3
"""Generate lib/libtest_zlib_generated.h -- the in-kernel proof vectors.

The kernel vectors are NOT a correctness suite; port/test/zlib_inflate is,
and it runs hundreds of thousands of streams against the pristine C in
seconds. These exist to answer the one question userspace cannot: did the
Rust actually run, in the kernel, on real streams.

So the plaintexts are chosen to be what a mistranslation breaks -- one
repeated byte (the dist == 1 splat), period two (the dist == 2 splat),
period three (the smallest distance that takes the 16-bit copy loop), a
longer period, a low-entropy alphabet that mixes literals with short
matches, and a mixture. libtest.c regenerates each plaintext from the same
rules and compares byte for byte; if the two generators ever disagree the
vector fails, which is a test bug reported as a test failure rather than a
silent pass.

Only the COMPRESSED bytes are emitted here. Embedding the plaintexts too
would triple the header for no extra evidence.
"""
import sys
import zlib

def gen(kind, n):
    if kind == 0:
        return bytes([0x5a]) * n
    if kind == 1:
        return bytes(0xad if (i & 1) else 0xde for i in range(n))
    if kind == 2:
        p = (0x01, 0x02, 0x03)
        return bytes(p[i % 3] for i in range(n))
    if kind == 3:
        p = (0x10, 0x20, 0x30, 0x40, 0x50, 0x60, 0x70)
        return bytes(p[i % 7] for i in range(n))
    if kind == 4:
        out = bytearray(n)
        s = 12345
        for i in range(n):
            s = (s * 1103515245 + 12345) & 0xffffffff
            out[i] = b"ACGT"[(s >> 16) & 3]
        return bytes(out)
    if kind == 5:
        third = n // 3
        return (gen(0, third) + gen(2, third) + gen(4, n - 2 * third))
    raise SystemExit("unknown kind %d" % kind)

# kind, length, zlib windowBits, level, note
VECTORS = [
    (0,  8192,  15, 9, "one repeated byte -- the dist == 1 splat"),
    (1,  8192,  15, 9, "period two -- the dist == 2 splat"),
    (2,  9000,  15, 6, "period three -- smallest dist taking the 16-bit loop"),
    (3, 12000,  15, 6, "period seven"),
    (4, 12000,  15, 9, "four-symbol alphabet -- literals mixed with short matches"),
    (5, 30000,  15, 6, "mixture, decompressed in small output chunks"),
    (5, 30000,  11, 6, "the same, with a 2 KiB window so the window wraps"),
]

def main(path):
    lines = []
    lines.append("/* SPDX-License-Identifier: GPL-2.0 */")
    lines.append("/* GENERATED by port/test/zlib_inflate/gen_kernel_vectors.py.")
    lines.append(" * Do not edit. Regenerate if the vector set changes.")
    lines.append(" */")
    lines.append("")
    names = []
    for idx, (kind, n, wbits, level, note) in enumerate(VECTORS):
        plain = gen(kind, n)
        co = zlib.compressobj(level, zlib.DEFLATED, wbits)
        comp = co.compress(plain) + co.flush()
        name = "lt_zvec%d" % idx
        names.append((name, kind, n, wbits, len(comp), note))
        lines.append("/* %s */" % note)
        lines.append("static const u8 %s[] __initconst = {" % name)
        for off in range(0, len(comp), 12):
            chunk = comp[off:off + 12]
            lines.append("\t" + " ".join("0x%02x," % b for b in chunk))
        lines.append("};")
        lines.append("")
    lines.append("static const struct lt_zvec {")
    lines.append("\tconst u8 *comp;")
    lines.append("\tunsigned int comp_len;")
    lines.append("\tunsigned int plain_len;")
    lines.append("\tint kind;")
    lines.append("\tint wbits;")
    lines.append("\tconst char *note;")
    lines.append("} lt_zvecs[] __initconst = {")
    for name, kind, n, wbits, cl, note in names:
        lines.append('\t{ %s, %d, %d, %d, %d, "%s" },' % (name, cl, n, kind, wbits, note))
    lines.append("};")
    lines.append("")
    with open(path, "w") as f:
        f.write("\n".join(lines))
    total = sum(v[4] for v in names)
    print("%s: %d vectors, %d compressed bytes" % (path, len(names), total))

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "port/tree/lib/libtest_zlib_generated.h")
