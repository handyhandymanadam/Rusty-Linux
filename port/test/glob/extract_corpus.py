#!/usr/bin/env python3
"""Extract lib/globtest.c's test corpus into a C header, mechanically.

The corpus is the kernel's, not ours. Copying it by hand went wrong the first
time it was tried here -- 63 cases transcribed against the tree's 64 -- which
is the notes/PRIOR-ART.md §2 stale-input-set shape in miniature. Deriving it every
run means it cannot drift.
"""
import re
import sys

src = open(sys.argv[1]).read()
m = re.search(r"static char const glob_tests\[\] __initconst =(.*?);\n", src, re.S)
if not m:
    sys.exit("could not find glob_tests[] in " + sys.argv[1])
open(sys.argv[2], "w").write(
    "/* GENERATED by extract_corpus.py from lib/globtest.c. Do not edit. */\n"
    "static char const glob_tests[] =" + m.group(1) + ";\n"
)
