#!/usr/bin/env python3
"""gen_vectors.py: print the HMAC vector table used by test_hmac() in port/tree/lib/libtest.c.
Expected digests come from python3's hmac/hashlib (an implementation independent of the kernel), and the RFC 2202 /
RFC 4231 case 1 and 2 digests are ALSO checked here against the values printed in the RFCs, so a generator bug cannot
silently agree with itself.
Row = { alg, key-kind, key-val, key-len, msg-kind, msg-val, msg-len, msg-string, expected-hex }
 key kinds: 0 CONST(val)  1 SEQ (byte i = i+1)  2 PAT (byte i = (i*7+3) & 255)
 msg kinds: 0 CONST(val)  2 PAT (byte i = (i*13+1) & 255)  3 STR (msg-string)"""
import hashlib, hmac, sys

def fill(kind, val, n, s=None):
    if kind == 0: return bytes([val]) * n
    if kind == 1: return bytes((i + 1) & 255 for i in range(n))
    if kind == 2: return bytes(((i * 7 + 3) & 255) for i in range(n))
    if kind == 12: return bytes(((i * 13 + 1) & 255) for i in range(n))
    if kind == 3: return s.encode()
    raise SystemExit("bad kind")

BS = {'sha3_224': 144, 'sha3_256': 136, 'sha3_384': 104, 'sha3_512': 72, 'md5': 64, 'sha1': 64, 'sha224': 64, 'sha256': 64, 'sha384': 128, 'sha512': 128}
rows = []
def add(alg, kk, kv, kl, mk, mv, ml, ms=""):
    key = fill(kk, kv, kl); msg = fill(mk if mk != 2 else 12, mv, ml, ms)
    d = hmac.new(key, msg, alg).hexdigest()
    rows.append((alg, kk, kv, kl, mk, mv, ml, ms, d))
    return d

# --- RFC 2202 (HMAC-MD5, HMAC-SHA-1)
for alg, n in (('md5', 16), ('sha1', 20)):
    add(alg, 0, 0x0b, n, 3, 0, 8, "Hi There")
    add(alg, 0, 0xaa, n, 0, 0xdd, 50)
    add(alg, 1, 0, 25, 0, 0xcd, 50)
    add(alg, 0, 0x0c, n, 3, 0, 20, "Test With Truncation")
    add(alg, 0, 0xaa, 80, 3, 0, 54, "Test Using Larger Than Block-Size Key - Hash Key First")
    add(alg, 0, 0xaa, 80, 3, 0, 73, "Test Using Larger Than Block-Size Key and Larger Than One Block-Size Data")
# --- RFC 4231 cases 1,3,4,5,6,7 (case 2 has the 4-byte string key "Jefe": see below)
M6 = "Test Using Larger Than Block-Size Key - Hash Key First"
M7 = "This is a test using a larger than block-size key and a larger than block-size data. The key needs to be hashed before being used by the HMAC algorithm."
for alg in ('sha224', 'sha256', 'sha384', 'sha512'):
    add(alg, 0, 0x0b, 20, 3, 0, 8, "Hi There")
    add(alg, 0, 0xaa, 20, 0, 0xdd, 50)
    add(alg, 1, 0, 25, 0, 0xcd, 50)
    add(alg, 0, 0x0c, 20, 3, 0, 20, "Test With Truncation")
    add(alg, 0, 0xaa, 131, 3, 0, len(M6), M6)
    add(alg, 0, 0xaa, 131, 3, 0, len(M7), M7)
# --- RFC 4231-style cases for SHA-3 (no RFC vectors for the generic template over SHA-3; digests from python)
SHA3 = ('sha3_224', 'sha3_256', 'sha3_384', 'sha3_512')
for alg in SHA3:
    add(alg, 0, 0x0b, 20, 3, 0, 8, "Hi There")
    add(alg, 0, 0xaa, 20, 0, 0xdd, 50)
    add(alg, 1, 0, 25, 0, 0xcd, 50)
    add(alg, 0, 0xaa, 131, 3, 0, len(M6), M6)
    add(alg, 0, 0xaa, 131, 3, 0, len(M7), M7)
# --- generated: key lengths around the block size
for alg in ('md5', 'sha1', 'sha224', 'sha256', 'sha384', 'sha512') + SHA3:
    bs = BS[alg]
    for kl in (0, 1, bs - 1, bs, bs + 1, 2 * bs):
        add(alg, 2, 0, kl, 2, 0, 100)
# --- the "Jefe" cases (RFC 2202/4231 case 2: key is the 4-byte string "Jefe"): a separate table in the C.
jefe = {}
for alg in ('md5', 'sha1', 'sha224', 'sha256', 'sha384', 'sha512') + SHA3:
    jefe[alg] = hmac.new(b"Jefe", b"what do ya want for nothing?", alg).hexdigest()

# cross-check against the digests printed in the RFCs
rfc = {('md5', 'Hi There'): '9294727a3638bb1c13f48ef8158bfc9d',
       ('sha1', 'Hi There'): 'b617318655057264e28bc0b6fb378c8ef146be00',
       ('sha256', 'Hi There'): 'b0344c61d8db38535ca8afceaf0bf12b881dc200c9833da726e9376c2e32cff7',
       ('sha512', 'Hi There'): '87aa7cdea5ef619d4ff0b4241a1d6cb02379f4e2ce4ec2787ad0b30545e17cdedaa833b7d6b8a702038b274eaea3f4e4be9d914eeb61f1702e696c203a126854'}
for r in rows:
    if r[3] in (16, 20) and r[7] == 'Hi There' and r[1] == 0 and r[2] == 0x0b and (r[0], 'Hi There') in rfc:
        assert r[8] == rfc[(r[0], 'Hi There')], ("RFC mismatch", r[0])
assert jefe['md5'] == '750c783e6ab0b503eaa86e310a5db738'
assert jefe['sha1'] == 'effcdf6ae5eb2fa2d27416d5f184df9c259a7c79'
assert jefe['sha256'] == '5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843'
assert jefe['sha512'] == '164b7a7bfcf819e2e395fbe73b56e0a387bd64222e831fd610270cd7ea2505549758bf75c05a994a6d034f65f8f0e6fdcaeab1a34d4a6b4b636e070a38bce737'

print("\t/* GENERATED by port/test/hmac/gen_vectors.py (python3 hmac/hashlib; RFC 2202 and RFC 4231 cases) -- do not edit */")
print("\tstatic const struct hmac_vec hv[] __initconst = {")
for (alg, kk, kv, kl, mk, mv, ml, ms, d) in rows:
    print('\t\t{ "hmac(%s)", %d, 0x%02x, %d, %d, 0x%02x, %d, "%s", "%s" },' % (alg.replace('_', '-'), kk, kv, kl, 3 if mk == 3 else (2 if mk == 2 else 0), mv, ml, ms, d))
print("\t};")
print("\tstatic const struct { const char *alg, *want; } hjefe[] __initconst = {")
for alg, d in jefe.items():
    print('\t\t{ "hmac(%s)", "%s" },' % (alg.replace('_', '-'), d))
print("\t};")
