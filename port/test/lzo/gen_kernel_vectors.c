/* Generate lib/libtest_lzo_generated.h -- the in-kernel proof vectors.
 *
 * Compressed with the PRISTINE in-tree encoder, so the blobs the kernel
 * decodes are the ones its own compressor produces. Python has no LZO, which
 * is why this is a C program and not a script like the zlib one.
 *
 * The kernel vectors are not a correctness suite -- port/test/lzo is, and it
 * runs hundreds of thousands of streams. These answer the one question
 * userspace cannot: did the Rust run, in the kernel.
 */
#include <stddef.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <linux/lzo.h>

extern int lzo1x_1_compress(const unsigned char *src, size_t src_len,
			    unsigned char *dst, size_t *dst_len, void *wrkmem);
extern int lzorle1x_1_compress(const unsigned char *src, size_t src_len,
			       unsigned char *dst, size_t *dst_len, void *wrkmem);

/* The SAME rules libtest.c uses to rebuild each plaintext. */
static void gen(int kind, unsigned char *b, unsigned n)
{
	static const unsigned char p3[3] = { 0x01, 0x02, 0x03 };
	static const char acgt[4] = { 'A', 'C', 'G', 'T' };
	unsigned i, third;
	uint32_t s = 12345;

	switch (kind) {
	case 0: memset(b, 0x5a, n); return;
	case 1: for (i = 0; i < n; i++) b[i] = (i & 1) ? 0xad : 0xde; return;
	case 2: for (i = 0; i < n; i++) b[i] = p3[i % 3]; return;
	case 3:
		for (i = 0; i < n; i++) {
			s = s * 1103515245u + 12345u;
			b[i] = (unsigned char)acgt[(s >> 16) & 3];
		}
		return;
	case 4: memset(b, 0, n); return;
	default:
		third = n / 3;
		gen(0, b, third);
		gen(2, b + third, third);
		gen(3, b + 2 * third, n - 2 * third);
		return;
	}
}

/* kind, length, use the RLE encoder, note */
static const struct { int kind; unsigned n; int rle; const char *note; } V[] = {
	{ 0,  8192, 0, "one repeated byte -- long matches at distance one" },
	{ 1,  8192, 0, "period two" },
	{ 2,  9000, 0, "period three" },
	{ 3, 12000, 0, "four-symbol alphabet -- literal runs mixed with matches" },
	{ 4, 16384, 1, "all zeros, RLE encoder -- the bitstream_version 1 zero-run" },
	{ 5, 20000, 0, "mixture" },
	{ 5, 20000, 1, "the same, RLE encoder" },
};
#define NV ((int)(sizeof(V) / sizeof(V[0])))

int main(int argc, char **argv)
{
	const char *path = argc > 1 ? argv[1] : "port/tree/lib/libtest_lzo_generated.h";
	unsigned char *plain, *comp;
	void *wrk;
	FILE *f;
	int i;
	size_t total = 0;

	plain = malloc(1 << 20);
	comp = malloc(lzo1x_worst_compress(1 << 20) + 64);
	wrk = malloc(LZO1X_MEM_COMPRESS);
	f = fopen(path, "w");
	if (!plain || !comp || !wrk || !f)
		return 2;

	fprintf(f, "/* SPDX-License-Identifier: GPL-2.0 */\n");
	fprintf(f, "/* GENERATED by port/test/lzo/gen_kernel_vectors.c.\n");
	fprintf(f, " * Do not edit. Regenerate with port/test/lzo/gen-vectors.sh.\n */\n\n");

	for (i = 0; i < NV; i++) {
		size_t cl = lzo1x_worst_compress(1 << 20) + 64;
		size_t j;

		gen(V[i].kind, plain, V[i].n);
		if ((V[i].rle ? lzorle1x_1_compress : lzo1x_1_compress)
		    (plain, V[i].n, comp, &cl, wrk) != LZO_E_OK)
			return 2;
		fprintf(f, "/* %s */\nstatic const u8 lt_lvec%d[] __initconst = {", V[i].note, i);
		for (j = 0; j < cl; j++)
			fprintf(f, "%s0x%02x,", (j % 12) ? " " : "\n\t", comp[j]);
		fprintf(f, "\n};\n\n");
		total += cl;
	}

	fprintf(f, "static const struct lt_lvec {\n"
		   "\tconst u8 *comp;\n\tunsigned int comp_len;\n"
		   "\tunsigned int plain_len;\n\tint kind;\n\tconst char *note;\n"
		   "} lt_lvecs[] __initconst = {\n");
	for (i = 0; i < NV; i++) {
		size_t cl = lzo1x_worst_compress(1 << 20) + 64;

		gen(V[i].kind, plain, V[i].n);
		(V[i].rle ? lzorle1x_1_compress : lzo1x_1_compress)
			(plain, V[i].n, comp, &cl, wrk);
		fprintf(f, "\t{ lt_lvec%d, %zu, %u, %d, \"%s\" },\n",
			i, cl, V[i].n, V[i].kind, V[i].note);
	}
	fprintf(f, "};\n");
	fclose(f);
	printf("%s: %d vectors, %zu compressed bytes\n", path, NV, total);
	return 0;
}
