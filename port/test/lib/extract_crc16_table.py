#!/usr/bin/env python3
"""Extract lib/crc/crc16.c's table into a C header, from port/pristine/.

The Rust port GENERATES its table from the polynomial with a const fn. That
is only trustworthy if something checks it against the 256 literals the C
actually shipped -- and those literals no longer exist in the kernel tree,
because the tree's copy is our ported file.
"""
import re
import sys

src = open(sys.argv[1]).read()
m = re.search(r"static const u16 crc16_table\[256\] = \{(.*?)\};", src, re.S)
if not m:
    sys.exit("could not find crc16_table[256] in " + sys.argv[1])
open(sys.argv[2], "w").write(
    "/* GENERATED by extract_crc16_table.py from lib/crc/crc16.c. Do not edit. */\n"
    "static const uint16_t ref_crc16_table[256] = {" + m.group(1) + "};\n"
)
