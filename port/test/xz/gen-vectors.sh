#!/usr/bin/env bash
# Regenerate lib/libtest_xz_generated.h.
#
# The streams are made by the REAL xz(1), not by anything in this project.
# That is the point: the expected plaintext then comes from outside the tree
# entirely, so a port and its oracle cannot agree on a wrong answer -- the
# same reasoning as the CRC catalogue check values in logs/hooks.md.
#
# Requires xz >= 5.6 for --riscv.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../.." && pwd)
out=$(mktemp -d); trap 'rm -rf "$out"' EXIT

# The generator rule lives in two places by necessity -- one has to run in
# userspace and one in the kernel. Refuse to run if they have drifted.
sed -n '/LT_XGEN_BEGIN/,/LT_XGEN_END/p' "$here/gen_plain.c" > "$out/a"
sed -n '/LT_XGEN_BEGIN/,/LT_XGEN_END/p' "$root/port/tree/lib/libtest.c" > "$out/b"
if ! diff -q "$out/a" "$out/b" >/dev/null; then
    echo "lt_xgen() has drifted between gen_plain.c and lib/libtest.c:" >&2
    diff "$out/a" "$out/b" >&2 || true
    exit 1
fi

cc -O2 -Wall -Wextra -o "$out/gen" "$here/gen_plain.c"

xzver=$(xz --version | head -1)
echo "using $xzver"

LEN=3067
DICT=64KiB

emit() {
    python3 - "$1" "$2" "$3" "$4" <<'PY'
import sys, pathlib
name, kind, plainlen, path = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), sys.argv[4]
d = pathlib.Path(path).read_bytes()
print("static const u8 lt_x_%s[] __initconst = {" % name)
for i in range(0, len(d), 12):
    print("\t" + " ".join("0x%02x," % b for b in d[i:i + 12]))
print("};")
PY
}

{
    printf '/* SPDX-License-Identifier: GPL-2.0 */\n'
    printf '/*\n'
    printf ' * GENERATED by port/test/xz/gen-vectors.sh -- do not edit.\n'
    printf ' *\n'
    printf ' * One .xz stream per BCJ filter, produced by %s with\n' "$xzver"
    printf ' * --check=crc32 --lzma2=dict=%s. The plaintext is NOT stored: it is\n' "$DICT"
    printf ' * regenerated by lt_xgen() in lib/libtest.c, whose rules gen-vectors.sh\n'
    printf ' * checks against port/test/xz/gen_plain.c on every run.\n'
    printf ' *\n'
    printf ' * The expectation therefore comes from outside this project entirely --\n'
    printf ' * xz(1) applied the forward filter, and the kernel has to reverse it.\n'
    printf ' */\n\n'

    names=""
    for spec in "x86 4 --x86" "powerpc 5 --powerpc" "arm 7 --arm" \
                "armthumb 8 --armthumb" "sparc 9 --sparc" \
                "arm64 10 --arm64" "riscv 11 --riscv"; do
        set -- $spec
        name=$1 kind=$2 flag=$3
        "$out/gen" "$kind" "$LEN" > "$out/plain.$name"
        xz --format=xz --check=crc32 "$flag" "--lzma2=dict=$DICT" \
           -c "$out/plain.$name" > "$out/comp.$name"
        # Prove the stream round-trips before it is written down.
        xz -dc "$out/comp.$name" | cmp -s - "$out/plain.$name" \
            || { echo "xz round-trip failed for $name" >&2; exit 1; }
        emit "$name" "$kind" "$LEN" "$out/comp.$name"
        printf '\n'
        names="$names $name:$kind"
    done

    printf 'struct lt_xvec {\n'
    printf '\tconst u8 *comp;\n'
    printf '\tunsigned int comp_len;\n'
    printf '\tunsigned int plain_len;\n'
    printf '\tint kind;\n'
    printf '\tconst char *note;\n'
    printf '};\n\n'
    printf 'static const struct lt_xvec lt_xvecs[] __initconst = {\n'
    for nk in $names; do
        name=${nk%%:*}; kind=${nk##*:}
        len=$(stat -c%s "$out/comp.$name")
        printf '\t{ lt_x_%s, %u, %u, %s,\n\t  "xz_dec_bcj decoded the %s filter" },\n' \
               "$name" "$len" "$LEN" "$kind" "$name"
    done
    printf '};\n'
} > "$root/port/tree/lib/libtest_xz_generated.h"

echo "wrote port/tree/lib/libtest_xz_generated.h"
wc -l "$root/port/tree/lib/libtest_xz_generated.h"
