#!/usr/bin/env python3
"""gen_vectors.py: print the key and vector tables used by test_rsa_helper() and test_rsa() in lib/libtest.c.
Keys are generated with `openssl genrsa` (shares nothing with the kernel) and parsed with a small DER reader here; every
ciphertext is computed with python integers (c = m^e mod n) AND checked against `openssl pkeyutl -encrypt -pkeyopt
rsa_padding_mode:none`, and every decryption is checked the same way with the private key, so a wrong transcription of either
side fails here, not in the kernel.
usage: python3 gen_vectors.py > table.inc     (new keys each run: the committed table is one run's output)"""
import subprocess, sys, tempfile, os, binascii

def sh(cmd, inp=None):
    return subprocess.run(cmd, input=inp, capture_output=True, check=True).stdout

def der_len(b, i):
    l = b[i]; i += 1
    if l < 0x80: return l, i
    n = l & 0x7f
    return int.from_bytes(b[i:i + n], "big"), i + n

def der_ints(b):
    assert b[0] == 0x30
    ln, i = der_len(b, 1)
    out = []
    end = i + ln
    while i < end:
        assert b[i] == 0x02
        l, j = der_len(b, i + 1)
        out.append(b[j:j + l]); i = j + l
    return out

def enc_len(n):
    if n < 0x80: return bytes([n])
    nb = (n.bit_length() + 7) // 8
    return bytes([0x80 | nb]) + n.to_bytes(nb, "big")

def der_int(raw):
    return b"\x02" + enc_len(len(raw)) + raw

def der_seq(items):
    body = b"".join(items)
    return b"\x30" + enc_len(len(body)) + body

def genkey(bits):
    with tempfile.TemporaryDirectory() as d:
        pem = os.path.join(d, "k.pem")
        sh(["openssl", "genrsa", "-traditional", "-out", pem, str(bits)])
        priv = sh(["openssl", "rsa", "-in", pem, "-traditional", "-outform", "DER"])
        pub = sh(["openssl", "rsa", "-in", pem, "-RSAPublicKey_out", "-outform", "DER"])
        return open(pem, "rb").read(), priv, pub

def h(b): return binascii.hexlify(b).decode()
def be(x, n): return x.to_bytes(n, "big")

keys = []
for bits in (2048, 1024):
    pem, priv, pub = genkey(bits)
    ints = der_ints(priv)
    v, n, e, d, p, q, dp, dq, qinv = [int.from_bytes(x, "big") for x in ints]
    assert v == 0 and n.bit_length() == bits and pow(pow(2, e, n), d, n) == 2
    k = (bits + 7) // 8
    pubints = der_ints(pub)
    assert int.from_bytes(pubints[0], "big") == n and int.from_bytes(pubints[1], "big") == e
    # messages: 2, n-2, and two pseudo-random values below n
    msgs = [2, n - 2, int.from_bytes(bytes((i * 29 + 5) & 0xff for i in range(k)), "big") % n, int.from_bytes(bytes((i * 71 + 13) & 0xff for i in range(k)), "big") % n]
    rows = []
    for m in msgs:
        assert 1 < m < n - 1
        c = pow(m, e, n)
        # cross-check with openssl, raw RSA (no padding), public and private operation
        with tempfile.TemporaryDirectory() as dd:
            privpem = os.path.join(dd, "priv.pem"); open(privpem, "wb").write(pem)
            pubpem = os.path.join(dd, "pub.pem")
            sh(["openssl", "rsa", "-in", privpem, "-pubout", "-out", pubpem])
            oc = sh(["openssl", "pkeyutl", "-encrypt", "-pubin", "-inkey", pubpem, "-pkeyopt", "rsa_padding_mode:none"], be(m, k))
            assert oc == be(c, k), "openssl public op disagrees"
            om = sh(["openssl", "pkeyutl", "-decrypt", "-inkey", privpem, "-pkeyopt", "rsa_padding_mode:none"], be(c, k))
            assert om == be(m, k), "openssl private op disagrees"
        rows.append((be(m, k), be(c, k)))
    keys.append(dict(bits=bits, k=k, n=n, e=e, priv=priv, pub=pub, rows=rows, p=ints[4], pubints=pubints, ints=ints))

K = keys[0]
# crafted keys for rsa_helper / rsa error paths (built from the 2048-bit key's numbers)
ints = K["ints"]
n_raw, e_raw = ints[1], ints[2]
crafted = {}
crafted["pub_truncated"] = K["pub"][:-5]
crafted["pub_e_longer_than_n"] = der_seq([der_int(b"\x00" + b"\xff" * (len(n_raw) - 1)), der_int(b"\x01" + b"\x00" * len(n_raw))])
priv_ints = [der_int(x) for x in ints]
bad_p = list(ints); bad_p[4] = b"\x01" + b"\x00" * len(n_raw)       # p longer than n
crafted["priv_p_longer_than_n"] = der_seq([der_int(x) for x in bad_p])
crafted["pub_n_empty"] = der_seq([b"\x02\x00", der_int(e_raw)])
# a 1100-bit modulus: 18 limbs = 1152 bits (mpi_get_size is limb-granular), parses fine, rsa_check_key_length rejects it (-EINVAL).
pem1100, priv1100, pub1100 = genkey(1100)
n1100 = int.from_bytes(der_ints(pub1100)[0], "big")
assert n1100.bit_length() == 1100 and (n1100.bit_length() + 63) // 64 * 64 not in (512, 1024, 1536, 2048, 3072, 4096)
crafted["pub_1100_bit"] = pub1100

print("/* rsa test data: generated by port/test/rsa/gen_vectors.py (openssl genrsa; python big integers; openssl raw RSA cross-check) */")
for i, K in enumerate(keys):
    print("static const char rsa_k%d_pub[] __initconst = \"%s\";" % (K["bits"], h(K["pub"])))
    print("static const char rsa_k%d_priv[] __initconst = \"%s\";" % (K["bits"], h(K["priv"])))
    print("static const char rsa_k%d_n[] __initconst = \"%s\";" % (K["bits"], h(be(K["n"], K["k"]))))
    print("static const struct rsa_vec rsa_k%d_vecs[] __initconst = {" % K["bits"])
    for m, c in K["rows"]:
        print("\t{ \"%s\",\n\t  \"%s\" }," % (h(m), h(c)))
    print("};")
for name, der in crafted.items():
    print("static const char rsa_%s[] __initconst = \"%s\";" % (name, h(der)))
print("/* sizes: k2048 pub %d priv %d; k1024 pub %d priv %d */" % (len(keys[0]["pub"]), len(keys[0]["priv"]), len(keys[1]["pub"]), len(keys[1]["priv"])), file=sys.stderr)
print("generated: 2 keys x 4 messages, openssl cross-checked; crafted: %s" % ", ".join(f"{k}={len(v)}B" for k, v in crafted.items()), file=sys.stderr)
