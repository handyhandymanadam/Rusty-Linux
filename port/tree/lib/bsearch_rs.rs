//! Generic binary search -- the Rust body behind `lib/bsearch.c`.
//!
//! Ported from `__inline_bsearch()` in `include/linux/bsearch.h`, which is
//! what `lib/bsearch.c`'s exported `bsearch()` is a one-line wrapper around.
//! Copyright (C) 2008-2009 Ksplice, Inc., Tim Abbott.
//!
//! The array must already be sorted under `cmp`. The key need not have the
//! same type as the elements — callers routinely search a table of structs
//! with a bare string key — which is why everything here is `*const c_void`
//! and byte offsets rather than anything typed.
//!
//! Replaces: lib/bsearch.c

use core::ffi::c_void;

/// `cmp_func_t` from `include/linux/types.h`.
type CmpFunc = unsafe extern "C" fn(*const c_void, *const c_void) -> core::ffi::c_int;

// The C types these contracts name. A Rust object has
// no C type graph to resolve them against, so they are
// not duplicates of anything -- omit one and the build
// stops naming the reference it could not resolve.
// Generated by rig/kabi-migrate.py; do not hand-edit.
kernel::kabi_rule!("type_string", "t#__kernel_size_t",
    "typedef_type __kernel_size_t { t#__kernel_ulong_t }");
kernel::kabi_rule!("type_string", "t#__kernel_ulong_t",
    "typedef_type __kernel_ulong_t { base_type unsigned long byte_size(8) encoding(7) }");
kernel::kabi_rule!("type_string", "t#cmp_func_t",
    "typedef_type cmp_func_t { pointer_type { subroutine_type ( formal_parameter pointer_type { const_type { base_type void } } , formal_parameter pointer_type { const_type { base_type void } } ) -> base_type int byte_size(4) encoding(5) } }");
kernel::kabi_rule!("type_string", "t#size_t",
    "typedef_type size_t { t#__kernel_size_t }");

kernel::kabi_export! {
    bsearch,
    license = "",
    namespace = "",
    contract = "subprogram ( formal_parameter pointer_type { const_type { base_type void } } key , formal_parameter pointer_type { const_type { base_type void } } base , formal_parameter t#size_t num , formal_parameter t#size_t size , formal_parameter t#cmp_func_t cmp ) -> pointer_type { base_type void }",
}

/// Body of `bsearch()`.
///
/// # Safety
/// `base` must point at `num` elements of `size` bytes each, sorted in
/// ascending order under `cmp`, and `cmp` must be a valid function pointer
/// that reads only its two arguments. Same contract as the C.
///
/// See `include/linux/bsearch.h` for the C declaration.
#[no_mangle]
pub unsafe extern "C" fn bsearch(
    key: *const c_void,
    base: *const c_void,
    num: usize,
    size: usize,
    cmp: CmpFunc,
) -> *mut c_void {
    let mut base = base as *const u8;
    let mut num = num;

    while num > 0 {
        let pivot = unsafe { base.add((num >> 1) * size) };
        // SAFETY: the caller guarantees `cmp` is callable and that `pivot`
        // is inside the array -- `num >> 1 < num` for every num > 0.
        let result = unsafe { cmp(key, pivot as *const c_void) };

        if result == 0 {
            return pivot as *mut c_void;
        }

        if result > 0 {
            // SAFETY: `pivot + size` is at most one past the last element,
            // which is a valid pointer to form.
            base = unsafe { pivot.add(size) };
            num -= 1;
        }
        num >>= 1;
    }

    core::ptr::null_mut()
}
