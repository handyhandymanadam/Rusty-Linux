//! MMIO block copies -- the Rust behind `lib/iomap_copy.c`.
//!
//! Ported from `lib/iomap_copy.c` (6.18.49), Copyright 2006 PathScale, Inc.
//!
//! Replaces: lib/iomap_copy.c
//!
//! # Two of the four functions here are not built on x86-64
//!
//! `__iowrite32_copy()` and `__iowrite64_copy()` are each wrapped in
//! `#ifndef`, so an architecture that defines its own takes it instead.
//! x86-64 does for the 32-bit one (`arch/x86/lib/iomap_copy_64.S`) and does
//! not for the 64-bit one, which is why `nm` on the C object shows exactly
//! `__ioread32_copy` and `__iowrite64_copy` and nothing else. The `#ifndef`s
//! are reproduced as `#[cfg]`, and the arms x86-64 does not take are marked
//! as untested — see `logs/build-limits.md`.
//!
//! # `__raw_writel` and friends are volatile accesses, not ordinary stores
//!
//! The C's comment is explicit that *"order of access is not guaranteed, nor
//! is a memory barrier performed"*, which is exactly `write_volatile`: the
//! compiler may not elide, duplicate, reorder against other volatile
//! accesses, or merge them, and it emits no fence. On x86 `__raw_writel` is a
//! plain `mov` to a `volatile` lvalue, so this is the same instruction.
//!
//! **What must NOT happen is `copy_nonoverlapping`.** It is the obvious Rust
//! for "copy `count` words", it is faster, and it would let the compiler turn
//! MMIO stores into `rep movsq` or vector stores — which is precisely what
//! `__raw_writel` in a loop exists to prevent on a device register.

use core::ffi::c_void;

/// `__iowrite32_copy()`: kernel memory to MMIO, 32 bits at a time.
///
/// **Not built on x86-64**, which supplies its own in
/// `arch/x86/lib/iomap_copy_64.S`. See the module documentation.
///
/// # Safety
/// `to` must be a valid MMIO mapping writable for `count` 32-bit words and
/// `from` readable for the same; both must be 32-bit aligned.
#[cfg(not(CONFIG_X86_64))]
#[no_mangle]
pub unsafe extern "C" fn __iowrite32_copy(to: *mut c_void, from: *const c_void, count: usize) {
    let dst = to as *mut u32;
    let src = from as *const u32;

    for i in 0..count {
        // SAFETY: `i < count`, and the caller guarantees `count` words on
        // both sides. write_volatile is __raw_writel: no elision, no
        // reordering against other volatile accesses, no merging.
        unsafe { dst.add(i).write_volatile(src.add(i).read()) };
    }
}

