/// Body of `__ioread32_copy()`: MMIO to kernel memory, 32 bits at a time.
///
/// # Safety
/// `from` must be a valid MMIO mapping readable for `count` 32-bit words and
/// `to` writable for the same; both must be 32-bit aligned.
#[no_mangle]
pub unsafe extern "C" fn __ioread32_copy(to: *mut c_void, from: *const c_void, count: usize) {
    let dst = to as *mut u32;
    let src = from as *const u32;

    for i in 0..count {
        // SAFETY: `i < count`; read_volatile is __raw_readl, and the read
        // must not be elided or duplicated -- a device register may have
        // side effects on read.
        unsafe { dst.add(i).write(src.add(i).read_volatile()) };
    }
}

kernel::kabi_export! {
    __iowrite64_copy,
    license = "GPL",
    namespace = "",
    contract = "subprogram ( formal_parameter pointer_type { base_type void } to , formal_parameter pointer_type { const_type { base_type void } } from , formal_parameter t#size_t count ) -> base_type void",
}

/// Body of `__iowrite64_copy()`: kernel memory to MMIO, 64 bits at a time on
/// a 64-bit target, and two 32-bit writes per word otherwise.
///
/// # Safety
/// `to` must be a valid MMIO mapping writable for `count` 64-bit words and
/// `from` readable for the same; both must be 64-bit aligned.
#[no_mangle]
pub unsafe extern "C" fn __iowrite64_copy(to: *mut c_void, from: *const c_void, count: usize) {
    #[cfg(CONFIG_64BIT)]
    {
        let dst = to as *mut u64;
        let src = from as *const u64;

        for i in 0..count {
            // SAFETY: `i < count`; write_volatile is __raw_writeq.
            unsafe { dst.add(i).write_volatile(src.add(i).read()) };
        }
    }
    #[cfg(not(CONFIG_64BIT))]
    // SAFETY: `count` 64-bit words are `count * 2` 32-bit ones, and the
    // caller's alignment guarantee is the stronger of the two. This is the
    // C's own `#else`.
    unsafe {
        __iowrite32_copy(to, from, count * 2)
    }
}
