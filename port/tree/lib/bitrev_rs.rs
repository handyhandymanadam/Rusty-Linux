//! The byte bit-reversal table -- the Rust behind `lib/bitrev.c`.
//!
//! Ported from `lib/bitrev.c` (6.18.49), by Akinobu Mita
//! <akinobu.mita@gmail.com>.
//!
//! # This file is one exported ARRAY, and that is the point of it
//!
//! `lib/bitrev.c` defines no functions. `__bitrev8()`, `__bitrev16()` and
//! `__bitrev32()` are `static inline` in `include/linux/bitrev.h` and every
//! one of them is a lookup in `byte_rev_table`, so the table is the whole
//! module and it is a **data** symbol, not a function.
//!
//! That is the reason to port it early rather than for its own sake:
//! `lib/uuid.c` (`guid_null`, `uuid_null`) and `lib/ctype.c` (`_ctype`) also
//! export data, and until this file existed nothing in this project -- or in
//! the previous attempt, which was searched -- had ever put an exported data
//! symbol's MODVERSIONS fingerprint in a Rust object. It works:
//! `gendwarfksyms` types a `DW_TAG_variable` as readily as a subprogram,
//! `variable array_type[256] { const_type { t#u8 } }`, and the contract below
//! pins that spelling exactly as a function's would be pinned.
//!
//! # The table is COMPUTED, not transcribed
//!
//! The C spells out 256 hexadecimal constants. Copying them into Rust would
//! be 256 chances to make a silent one-character error that no type check can
//! see, and it would be the same error class the previous attempt hit head-on
//! when it hand-copied `vsprintf`'s `decpair[]` table.
//!
//! So the table is built at compile time from the definition of what it is --
//! entry `i` is `i` with its bits reversed -- and the result is asserted
//! against four values read out of the C, chosen at the corners and where a
//! transposed nibble would show. `u8::reverse_bits` is a `const fn`, so the
//! whole thing lands in `.rodata` with no initialiser code.
//!
//! # `CONFIG_HAVE_ARCH_BITREVERSE`
//!
//! The C wraps the entire file in `#ifndef CONFIG_HAVE_ARCH_BITREVERSE` --
//! an architecture with a bit-reverse instruction (arm's `rbit`) defines the
//! three inlines in `asm/bitrev.h` and needs no table. x86-64 has no such
//! instruction and does not set the symbol. The guard is reproduced here so
//! the object is empty on an architecture that does not want it, exactly as
//! the C's is.
//!
//! Replaces: lib/bitrev.c

/// `byte_rev_table[i]` is `i` with its bit order reversed.
///
/// Built from that sentence rather than copied. See the module documentation
/// for why the difference matters.
#[cfg(not(CONFIG_HAVE_ARCH_BITREVERSE))]
const fn byte_rev_table_init() -> [u8; 256] {
    let mut t = [0u8; 256];
    let mut i = 0usize;

    while i < 256 {
        t[i] = (i as u8).reverse_bits();
        i += 1;
    }
    t
}

// Four values read out of lib/bitrev.c, not out of the generator. They are
// the two ends, the first entry whose nibbles differ (a swapped-nibble bug
// is the one a symmetric spot-check misses), and one arbitrary interior
// value. A const assertion, so a wrong table cannot be built at all.
#[cfg(not(CONFIG_HAVE_ARCH_BITREVERSE))]
const _: () = {
    let t = byte_rev_table_init();
    assert!(t[0x00] == 0x00);
    assert!(t[0x01] == 0x80);
    assert!(t[0x2d] == 0xb4);
    assert!(t[0xff] == 0xff);
};

// The C types this contract names. A Rust object has no C type graph to
// resolve them against, so they are not duplicates of anything -- omit one
// and the build stops naming the reference it could not resolve.
// Generated by rig/kabi-pin.sh --capture; do not hand-edit.
#[cfg(not(CONFIG_HAVE_ARCH_BITREVERSE))]
kernel::kabi_rule!("type_string", "t#__u8",
    "typedef_type __u8 { base_type unsigned char byte_size(1) encoding(8) }");
#[cfg(not(CONFIG_HAVE_ARCH_BITREVERSE))]
kernel::kabi_rule!("type_string", "t#u8",
    "typedef_type u8 { t#__u8 }");

// lib/bitrev.c's MODULE_*() metadata, which is real output for a built-in
// object: it lands in .modinfo and kbuild extracts it into the installed
// modules.builtin.modinfo. See kernel::kabi_modinfo.
#[cfg(not(CONFIG_HAVE_ARCH_BITREVERSE))]
kernel::kabi_modinfo! {
    "bitrev",
    file = "lib/bitrev",
    author = "Akinobu Mita <akinobu.mita@gmail.com>",
    description = "Bit ordering reversal functions",
    license = "GPL",
}

#[cfg(not(CONFIG_HAVE_ARCH_BITREVERSE))]
kernel::kabi_export! {
    byte_rev_table,
    license = "GPL",
    namespace = "",
    contract = "variable array_type[256] { const_type { t#u8 } }",
}

/// `const u8 byte_rev_table[256]` from `lib/bitrev.c`.
///
/// Read by `__bitrev8()` and, through it, `__bitrev16()`, `__bitrev32()` and
/// `__bitrev8x4()` in `include/linux/bitrev.h`. Declared there as
/// `extern u8 const byte_rev_table[256]`.
#[cfg(not(CONFIG_HAVE_ARCH_BITREVERSE))]
#[no_mangle]
#[allow(non_upper_case_globals)]
pub static byte_rev_table: [u8; 256] = byte_rev_table_init();
