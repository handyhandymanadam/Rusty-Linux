/// Body of `hex2bin()`: `count` bytes from `2 * count` hex characters.
///
/// **It stops at the first bad character, having already written the bytes
/// before it.** That is upstream's behaviour and callers rely on the return
/// value, not on `dst` being untouched.
///
/// # Safety
/// `dst` must be writable for `count` bytes and `src` readable for
/// `2 * count`. Same contract as the C, whose signature carries no bound on
/// `src` either.
#[no_mangle]
pub unsafe extern "C" fn hex2bin(dst: *mut u8, src: *const c_char, count: usize) -> c_int {
    let mut dst = dst;
    let mut src = src;

    for _ in 0..count {
        // SAFETY: the caller guarantees 2*count readable characters.
        let hi = hex_to_bin(unsafe { *src } as c_uchar);
        // SAFETY: as above.
        src = unsafe { src.add(1) };
        if hi < 0 {
            return -EINVAL;
        }
        // SAFETY: as above.
        let lo = hex_to_bin(unsafe { *src } as c_uchar);
        // SAFETY: as above.
        src = unsafe { src.add(1) };
        if lo < 0 {
            return -EINVAL;
        }
        // SAFETY: the caller guarantees `count` writable bytes.
        unsafe {
            *dst = ((hi << 4) | lo) as u8;
            dst = dst.add(1);
        }
    }
    0
}

