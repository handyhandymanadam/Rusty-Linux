/// Body of `hex_to_bin()`: one hex digit's value, or -1.
///
/// **Transcribed as arithmetic because it IS arithmetic.** The C's own
/// comment explains each step; the short version is that
/// `(ch - '9' - 1) & ('0' - 1 - ch)` is negative exactly when `ch` is a
/// decimal digit, `>> 8` turns that sign into a 0xffffff mask, and the same
/// trick run on `ch & 0xdf` (which folds lower case to upper) handles A-F.
/// No branch, no table, nothing whose timing depends on the digit -- which is
/// the point, because this is on the path that loads cryptographic keys.
///
/// The C does this in `int`, with the intermediates wrapping through `int`
/// and `unsigned`. `wrapping_*` and explicit casts reproduce that exactly;
/// the kernel builds Rust with `-Coverflow-checks=y`, so a plain `-` here
/// would panic on the very first non-digit.
#[no_mangle]
pub extern "C" fn hex_to_bin(ch: c_uchar) -> c_int {
    let ch = ch as c_int;
    let cu = ch & 0xdf;

    // (ch - '9' - 1) & ('0' - 1 - ch), as unsigned, >> 8.
    let dmask = (((ch - 0x39 - 1) & (0x30 - 1 - ch)) as u32 >> 8) as c_int;
    let umask = (((cu - 0x46 - 1) & (0x41 - 1 - cu)) as u32 >> 8) as c_int;

    (-1i32)
        .wrapping_add((ch - 0x30 + 1) & dmask)
        .wrapping_add((cu - 0x41 + 11) & umask)
}

