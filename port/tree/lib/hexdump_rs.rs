//! Hex dumping -- the Rust behind `lib/hexdump.c`.
//!
//! Ported from `lib/hexdump.c` (6.18.49).
//!
//! Replaces: lib/hexdump.c
//!
//! # `hex_to_bin` is branchless ON PURPOSE and this port keeps it that way
//!
//! Its comment in the C says why: *"This function is used to load
//! cryptographic keys, so it is coded in such a way that there are no
//! conditions or memory accesses that depend on data."* The obvious Rust --
//! `match ch { b'0'..=b'9' => ..., _ => -1 }` -- reads better, produces the
//! same answers, and is a **timing side channel on key material**. So the
//! arithmetic is transcribed as arithmetic, and the emitted code was compared
//! against the C's. Same shape, no branches. `lib/crypto/memneq.c` is the
//! same lesson and `logs/hooks.md` carries both.
//!
//! # `snprintf` and `_printk` are called, not reimplemented
//!
//! `hex_dump_to_buffer()` formats through `snprintf()` for the 2-, 4- and
//! 8-byte grouping paths, and `print_hex_dump()` goes to `_printk()`. Both are
//! C variadics and both are called as such here. Reimplementing kernel
//! `%16.16llx` or `%p` in Rust would be reimplementing `lib/vsprintf.c`, which
//! is its own module, has not been ported, and has the highest fan-in in the
//! tree (915 caller files) -- SCOPE.md §1 says it goes last.

use core::ffi::{c_char, c_int, c_uchar, c_void};

/// `-EINVAL`.
const EINVAL: c_int = 22;

/// `DUMP_PREFIX_ADDRESS` from `include/linux/printk.h`.
const DUMP_PREFIX_ADDRESS: c_int = 1;
/// `DUMP_PREFIX_OFFSET`.
const DUMP_PREFIX_OFFSET: c_int = 2;

/// `_P|_U|_L|_D|_SP` -- the mask `isprint()` applies.
const ISPRINT_MASK: u8 = 0x10 | 0x01 | 0x02 | 0x04 | 0x80;

extern "C" {
    /// `lib/ctype.c`, which is now `lib/ctype_rs.rs`. Indexed by
    /// `__ismask()`; see `include/linux/ctype.h`.
    static _ctype: [u8; 256];
    /// `lib/vsprintf.c`.
    fn snprintf(buf: *mut c_char, size: usize, fmt: *const c_char, ...) -> c_int;
    /// `kernel/printk/printk.c`. `printk()` is a macro over this; the wrapper
    /// it adds, `__printk_index_emit()`, is a no-op unless
    /// `CONFIG_PRINTK_INDEX` is set. See `logs/build-limits.md`.
    fn _printk(fmt: *const c_char, ...) -> c_int;
}

/// `isascii(ch) && isprint(ch)`, the test `hex_dump_to_buffer()` applies to
/// each byte of its ASCII column.
#[inline]
fn is_ascii_printable(ch: u8) -> bool {
    // SAFETY: `_ctype` is a 256-entry table with static lifetime and `ch`
    // indexes it exactly, which is what `__ismask()` does in the C.
    ch <= 0x7f && (unsafe { _ctype[ch as usize] } & ISPRINT_MASK) != 0
}

