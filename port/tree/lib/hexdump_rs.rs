/// Body of `bin2hex()`: `2 * count` lower-case hex characters, returning the
/// end of what was written. **No NUL is appended**, which is why it returns a
/// pointer rather than a length.
///
/// # Safety
/// `src` must be readable for `count` bytes and `dst` writable for
/// `2 * count`.
#[no_mangle]
pub unsafe extern "C" fn bin2hex(dst: *mut c_char, src: *const c_void, count: usize) -> *mut c_char {
    let mut dst = dst;
    let mut src = src as *const u8;

    for _ in 0..count {
        // SAFETY: the caller guarantees `count` readable bytes and 2*count
        // writable ones; this is hex_byte_pack() from include/linux/hex.h.
        unsafe {
            let byte = *src;
            src = src.add(1);
            *dst = hex_asc[((byte & 0xf0) >> 4) as usize];
            *dst.add(1) = hex_asc[(byte & 0x0f) as usize];
            dst = dst.add(2);
        }
    }
    dst
}

