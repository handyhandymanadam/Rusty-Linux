/// Body of `print_hex_dump()`: the whole buffer, one line per row, to the log.
///
/// # Safety
/// `buf` must be readable for `len` bytes; `level` and `prefix_str` must be
/// NUL-terminated. Same contract as the C.
#[no_mangle]
pub unsafe extern "C" fn print_hex_dump(
    level: *const c_char,
    prefix_str: *const c_char,
    prefix_type: c_int,
    rowsize: c_int,
    groupsize: c_int,
    buf: *const c_void,
    len: usize,
    ascii: bool,
) {
    let ptr = buf as *const u8;
    let mut rowsize = rowsize;

    if rowsize != 16 && rowsize != 32 {
        rowsize = 16;
    }

    // `unsigned char linebuf[32 * 3 + 2 + 32 + 1]` in the C: the widest line
    // is 32 groups of "xx " plus the ASCII column plus the NUL.
    let mut linebuf = [0u8; 32 * 3 + 2 + 32 + 1];
    let mut remaining = len as isize;
    let mut i = 0usize;

    while i < len {
        let linelen = core::cmp::min(remaining, rowsize as isize) as usize;
        remaining -= rowsize as isize;

        // SAFETY: `i < len`, and `linelen` is clamped to what remains, so the
        // read is inside the caller's buffer. `linebuf` is ours and its
        // length is passed honestly.
        unsafe {
            hex_dump_to_buffer(
                ptr.add(i).cast(),
                linelen,
                rowsize,
                groupsize,
                linebuf.as_mut_ptr().cast(),
                linebuf.len(),
                ascii,
            );
            let line = linebuf.as_ptr() as *const c_char;
            match prefix_type {
                DUMP_PREFIX_ADDRESS => {
                    _printk(c"%s%s%p: %s\n".as_ptr(), level, prefix_str, ptr.add(i), line);
                }
                DUMP_PREFIX_OFFSET => {
                    _printk(c"%s%s%.8x: %s\n".as_ptr(), level, prefix_str, i as u32, line);
                }
                _ => {
                    _printk(c"%s%s%s\n".as_ptr(), level, prefix_str, line);
                }
            }
        }

        i += rowsize as usize;
    }
}
