/// Body of `hex_dump_to_buffer()`: one line of `xx xx xx  ascii`.
///
/// **The return value is snprintf's convention, not strlcpy's**: on overflow
/// it is what WOULD have been written, so a caller can size a buffer from it.
/// The two overflow labels in the C differ in whether anything was written at
/// all, and both are reproduced -- `overflow2` NUL-terminates, `overflow1`
/// does not, because it is reached before `linebuf` is touched.
///
/// # Safety
/// `buf` must be readable for `len` bytes and `linebuf` writable for
/// `linebuflen`. Same contract as the C.
#[no_mangle]
pub unsafe extern "C" fn hex_dump_to_buffer(
    buf: *const c_void,
    len: usize,
    rowsize: c_int,
    groupsize: c_int,
    linebuf: *mut c_char,
    linebuflen: usize,
    ascii: bool,
) -> c_int {
    let ptr = buf as *const u8;
    let mut rowsize = rowsize;
    let mut groupsize = groupsize;
    let mut len = len;

    if rowsize != 16 && rowsize != 32 {
        rowsize = 16;
    }
    // Limit to one line at a time.
    if len > rowsize as usize {
        len = rowsize as usize;
    }
    // `is_power_of_2()` is `n != 0 && (n & (n - 1)) == 0` on an UNSIGNED
    // value; groupsize is a signed int, so a negative one is not a power of
    // two and falls back to 1, exactly as in the C.
    if !(groupsize > 0 && (groupsize & (groupsize - 1)) == 0) || groupsize > 8 {
        groupsize = 1;
    }
    // No mixed size output.
    if len % groupsize as usize != 0 {
        groupsize = 1;
    }

    let ngroups = (len / groupsize as usize) as c_int;
    let ascii_column = rowsize * 2 + rowsize / groupsize + 1;

    // The value both overflow paths return.
    let overflow1 = || -> c_int {
        if ascii {
            ascii_column + len as c_int
        } else {
            (groupsize * 2 + 1) * ngroups - 1
        }
    };

    if linebuflen == 0 {
        return overflow1();
    }

    let mut lx: usize = 0;

    if len != 0 {
        if groupsize > 1 {
            // The 2-, 4- and 8-byte paths differ only in width and in the
            // unaligned load, so they are one loop here rather than three.
            // The format strings are byte-identical to the C's.
            for j in 0..ngroups as usize {
                let sep: *const c_char = if j != 0 { c" ".as_ptr() } else { c"".as_ptr() };
                // SAFETY: `j < ngroups` and `ngroups * groupsize == len`, so
                // the load is inside the `len` bytes the caller guaranteed;
                // `read_unaligned` is `get_unaligned()`. `lx < linebuflen` is
                // maintained by the check below, so the destination is in
                // bounds for `linebuflen - lx`.
                let ret = unsafe {
                    let at = ptr.add(j * groupsize as usize);
                    let dst = linebuf.add(lx);
                    let cap = linebuflen - lx;
                    match groupsize {
                        8 => snprintf(dst, cap, c"%s%16.16llx".as_ptr(), sep,
                                      (at as *const u64).read_unaligned()),
                        4 => snprintf(dst, cap, c"%s%8.8x".as_ptr(), sep,
                                      (at as *const u32).read_unaligned()),
                        _ => snprintf(dst, cap, c"%s%4.4x".as_ptr(), sep,
                                      (at as *const u16).read_unaligned() as u32),
                    }
                };
                if ret as usize >= linebuflen - lx {
                    return overflow1();
                }
                lx += ret as usize;
            }
        } else {
            for j in 0..len {
                // SAFETY: `j < len` and `lx + 2 <= linebuflen` is checked
                // before every write, so both pointers are in bounds.
                unsafe {
                    if linebuflen < lx + 2 {
                        return overflow2(linebuf, lx, ascii, ascii_column, len,
                                         groupsize, ngroups);
                    }
                    let ch = *ptr.add(j);
                    *linebuf.add(lx) = hex_asc[((ch & 0xf0) >> 4) as usize];
                    lx += 1;
                    if linebuflen < lx + 2 {
                        return overflow2(linebuf, lx, ascii, ascii_column, len,
                                         groupsize, ngroups);
                    }
                    *linebuf.add(lx) = hex_asc[(ch & 0x0f) as usize];
                    lx += 1;
                    if linebuflen < lx + 2 {
                        return overflow2(linebuf, lx, ascii, ascii_column, len,
                                         groupsize, ngroups);
                    }
                    *linebuf.add(lx) = b' ' as c_char;
                    lx += 1;
                }
            }
            // Drop the trailing space. `if (j)` in the C, and `j == len` there.
            if len != 0 {
                lx -= 1;
            }
        }

        if ascii {
            while (lx as c_int) < ascii_column {
                if linebuflen < lx + 2 {
                    // SAFETY: nothing has been written past `lx`, and
                    // overflow2 writes exactly one NUL there.
                    return unsafe {
                        overflow2(linebuf, lx, ascii, ascii_column, len,
                                  groupsize, ngroups)
                    };
                }
                // SAFETY: `lx + 2 <= linebuflen`, so `lx` is in bounds.
                unsafe { *linebuf.add(lx) = b' ' as c_char };
                lx += 1;
            }
            for j in 0..len {
                if linebuflen < lx + 2 {
                    // SAFETY: as above.
                    return unsafe {
                        overflow2(linebuf, lx, ascii, ascii_column, len,
                                  groupsize, ngroups)
                    };
                }
                // SAFETY: `j < len` and `lx + 2 <= linebuflen`.
                unsafe {
                    let ch = *ptr.add(j);
                    *linebuf.add(lx) = if is_ascii_printable(ch) {
                        ch as c_char
                    } else {
                        b'.' as c_char
                    };
                }
                lx += 1;
            }
        }
    }

    // `nil:` -- always NUL-terminated.
    // SAFETY: every path above leaves `lx < linebuflen`.
    unsafe { *linebuf.add(lx) = 0 };
    lx as c_int
}

/// The C's `overflow2:` label: NUL-terminate where we stopped, then return
/// the same value `overflow1:` would have.
///
/// # Safety
/// `linebuf` must be writable at `lx`, which every caller has just checked.
#[allow(clippy::too_many_arguments)]
#[inline]
unsafe fn overflow2(
    linebuf: *mut c_char,
    lx: usize,
    ascii: bool,
    ascii_column: c_int,
    len: usize,
    groupsize: c_int,
    ngroups: c_int,
) -> c_int {
    // SAFETY: the caller has checked `linebuflen >= lx + 2`.
    unsafe { *linebuf.add(lx) = 0 };
    if ascii {
        ascii_column + len as c_int
    } else {
        (groupsize * 2 + 1) * ngroups - 1
    }
}

