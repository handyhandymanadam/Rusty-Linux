/// Body of `guid_parse()`. 0, or `-EINVAL` if the text is not a UUID string.
///
/// # Safety
/// `uuid` must satisfy [`uuid_is_valid`]'s contract; `u` must be a valid,
/// writable `guid_t`.
#[no_mangle]
pub unsafe extern "C" fn guid_parse(uuid: *const c_char, u: *mut GuidT) -> c_int {
    // SAFETY: the caller's contract, passed straight through.
    unsafe { uuid_parse_common(uuid, (*u).b.as_mut_ptr(), &guid_index) }
}

