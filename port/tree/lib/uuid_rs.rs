/// Body of `generate_random_uuid()`: sixteen random bytes stamped as an
/// RFC 4122 version-4, DCE-variant UUID.
///
/// # Safety
/// `uuid` must be writable for 16 bytes. Same contract as the C, whose
/// parameter is spelled `unsigned char uuid[16]` and decays to a pointer.
#[no_mangle]
pub unsafe extern "C" fn generate_random_uuid(uuid: *mut c_uchar) {
    // SAFETY: the caller guarantees 16 writable bytes.
    let b = unsafe {
        get_random_bytes(uuid.cast(), UUID_SIZE);
        core::slice::from_raw_parts_mut(uuid, UUID_SIZE)
    };
    // Version 4 -- truly random generation.
    b[6] = (b[6] & 0x0f) | 0x40;
    // Variant DCE.
    b[8] = (b[8] & 0x3f) | 0x80;
}

