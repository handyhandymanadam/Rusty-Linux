/// Body of `generate_random_guid()`.
///
/// **The version nibble is at byte 7, not byte 6.** That is the whole
/// difference from [`generate_random_uuid`], and it is not a typo in either
/// place: a GUID stores its first three fields little-endian, so the field
/// that holds the version sits at the other end of its two-byte run.
///
/// # Safety
/// `guid` must be writable for 16 bytes.
#[no_mangle]
pub unsafe extern "C" fn generate_random_guid(guid: *mut c_uchar) {
    // SAFETY: the caller guarantees 16 writable bytes.
    let b = unsafe {
        get_random_bytes(guid.cast(), UUID_SIZE);
        core::slice::from_raw_parts_mut(guid, UUID_SIZE)
    };
    // Version 4 -- truly random generation.
    b[7] = (b[7] & 0x0f) | 0x40;
    // Variant DCE.
    b[8] = (b[8] & 0x3f) | 0x80;
}

/// `__uuid_gen_common()`: random bytes plus the variant nibble. The version
/// nibble is the caller's, because it sits in a different byte for each.
///
/// # Safety
/// `b` must be writable for 16 bytes.
#[inline]
unsafe fn uuid_gen_common(b: *mut c_uchar) -> &'static mut [c_uchar] {
    // SAFETY: the caller guarantees 16 writable bytes, and the returned
    // slice is used only by the caller, which owns them.
    let s = unsafe {
        get_random_bytes(b.cast(), UUID_SIZE);
        core::slice::from_raw_parts_mut(b, UUID_SIZE)
    };
    // Reversion 0b10.
    s[8] = (s[8] & 0x3f) | 0x80;
    s
}

