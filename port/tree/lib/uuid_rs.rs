/// Body of `uuid_is_valid()`: is this 36 characters of
/// `xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx`?
///
/// **It reads 36 bytes unconditionally.** The C does too -- its signature
/// carries no length, so a shorter string is the caller's bug, and the loop
/// only stops early on a character that is neither a hex digit nor a hyphen
/// in the right place. A NUL terminator is neither, so a correctly
/// NUL-terminated shorter string does stop it; an unterminated buffer does
/// not. That is upstream's contract and this does not tighten it.
///
/// # Safety
/// `uuid` must be readable up to and including its first character that is
/// not a hex digit, and not more than 36 characters.
#[no_mangle]
pub unsafe extern "C" fn uuid_is_valid(uuid: *const c_char) -> bool {
    for i in 0..UUID_STRING_LEN {
        // SAFETY: `i` is below 36 and the caller guarantees the string is
        // readable that far or stops us earlier with a non-hex character.
        let c = unsafe { *uuid.add(i) } as u8;

        if i == 8 || i == 13 || i == 18 || i == 23 {
            if c != b'-' {
                return false;
            }
        } else if !c.is_ascii_hexdigit() {
            return false;
        }
    }
    true
}

/// `__uuid_parse()`: the shared text-to-binary conversion, told which
/// permutation to use.
///
/// # Safety
/// `uuid` must satisfy [`uuid_is_valid`]'s contract and `b` must be writable
/// for 16 bytes.
#[inline]
unsafe fn uuid_parse_common(uuid: *const c_char, b: *mut c_uchar, ei: &[c_uchar; UUID_SIZE]) -> c_int {
    // SAFETY: the caller's contract, and this is what validates it.
    if !unsafe { uuid_is_valid(uuid) } {
        return -EINVAL;
    }

    for i in 0..UUID_SIZE {
        // SAFETY: uuid_is_valid() has just read all 36 characters, so
        // SI[i] and SI[i] + 1 are both in bounds and both hex digits.
        let (hi, lo) = unsafe {
            (
                hex_to_bin(*uuid.add(SI[i]) as c_uchar),
                hex_to_bin(*uuid.add(SI[i] + 1) as c_uchar),
            )
        };
        // SAFETY: ei[i] is one of 0..16 by construction of both tables, and
        // the caller guarantees 16 writable bytes.
        unsafe { *b.add(ei[i] as usize) = ((hi << 4) | lo) as c_uchar };
    }
    0
}

