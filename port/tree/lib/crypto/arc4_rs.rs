/// Body of `arc4_crypt()`.
///
/// # Safety
/// `ctx` must be valid and writable, `in` readable for `len` bytes and `out`
/// writable for `len` bytes. `in` and `out` may alias, which callers rely on
/// for in-place encryption.
///
/// See `include/crypto/arc4.h` for the C declaration.
#[no_mangle]
pub unsafe extern "C" fn arc4_crypt(
    ctx: *mut Arc4Ctx,
    out: *mut u8,
    input: *const u8,
    len: c_uint,
) {
    let len = len as usize;

    if len == 0 {
        return;
    }

    // SAFETY: the caller's contract. `in` and `out` are kept as raw pointers
    // rather than slices precisely because they are allowed to alias --
    // in-place encryption is the normal case -- and two overlapping slices
    // would be an aliasing claim that is not true.
    let ctx = unsafe { &mut *ctx };
    let mut x = ctx.x;
    let mut y = ctx.y;
    let mut i = 0usize;

    let mut a = ctx.s[x as usize];

    y = (y.wrapping_add(a)) & 0xff;
    let mut b = ctx.s[y as usize];

    // The C's software pipeline: read the next entries before writing the
    // current ones, so the loop has no load-after-store stall. Kept as it is.
    loop {
        ctx.s[y as usize] = a;
        a = (a.wrapping_add(b)) & 0xff;
        ctx.s[x as usize] = b;
        x = (x.wrapping_add(1)) & 0xff;

        let ta = ctx.s[x as usize];
        let ty = (y.wrapping_add(ta)) & 0xff;
        let tb = ctx.s[ty as usize];

        // SAFETY: `i < len`, and the caller guarantees `len` bytes readable
        // at `input` and writable at `out`.
        unsafe {
            *out.add(i) = *input.add(i) ^ ctx.s[a as usize] as u8;
        }
        i += 1;
        if i == len {
            break;
        }

        y = ty;
        a = ta;
        b = tb;
    }

    ctx.x = x;
    ctx.y = y;
}
