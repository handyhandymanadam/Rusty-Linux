/// Body of `arc4_setkey()`. Always returns 0.
///
/// # Safety
/// `ctx` must be valid and writable, `in_key` readable for `key_len` bytes,
/// and `key_len` non-zero. Same contract as the C, whose `k` index would
/// divide by nothing but would never advance on a zero-length key.
///
/// See `include/crypto/arc4.h` for the C declaration.
#[no_mangle]
pub unsafe extern "C" fn arc4_setkey(
    ctx: *mut Arc4Ctx,
    in_key: *const u8,
    key_len: c_uint,
) -> c_int {
    // SAFETY: the caller guarantees `ctx` is valid, writable and uniquely
    // borrowed, and that `key_len` bytes are readable at `in_key`.
    let ctx = unsafe { &mut *ctx };
    // `(NULL, 0)` is legal C and `from_raw_parts` forbids a null pointer.
    let key: &[u8] = if key_len == 0 {
        &[]
    } else {
        unsafe { core::slice::from_raw_parts(in_key, key_len as usize) }
    };

    ctx.x = 1;
    ctx.y = 0;

    for (i, s) in ctx.s.iter_mut().enumerate() {
        *s = i as u32;
    }

    let mut j: u32 = 0;
    let mut k: usize = 0;

    for i in 0..256usize {
        let a = ctx.s[i];

        j = (j.wrapping_add(key[k] as u32).wrapping_add(a)) & 0xff;
        ctx.s[i] = ctx.s[j as usize];
        ctx.s[j as usize] = a;
        k = k.wrapping_add(1);
        if k >= key.len() {
            k = 0;
        }
    }

    0
}

