//! The LZO1X-1 compressor: the fast (unchecked) and safe (bounds-checked)
//! entry points, and `lzorle1x_1_compress[_safe]`'s zero-run variant of
//! each.
//!
//! Ported from `lib/lzo/lzo1x_compress.c` and `lib/lzo/lzo1x_compress_safe.c`
//! (6.18.49), which carry `Copyright (C) 1996-2012 Markus F.X.J. Oberhumer`
//! and kernel changes by Nitin Gupta and Richard Purdie.
//!
//! # One file becomes one crate, not two
//!
//! In the C, `lzo1x_compress_safe.c` is two lines that `#define` `LZO_SAFE`/
//! `HAVE_OP` and then `#include "lzo1x_compress.c"` wholesale, compiling the
//! same body twice under the preprocessor -- once with `NEED_OP` a no-op
//! (`lzo1x_1_compress`/`lzorle1x_1_compress`, callers must size `dst` via
//! `lzo1x_worst_compress()`) and once with it a real bounds check
//! (`lzo1x_1_compress_safe`/`lzorle1x_1_compress_safe`). A `const SAFE: bool`
//! generic parameter is the same technique in Rust: [`do_compress`] and
//! [`generic_compress`] are written once and monomorphized twice, so
//! `need_op!` compiles to nothing at all in the `SAFE = false` instantiation
//! -- exactly as `HAVE_OP(x)` being a literal `1` makes the C's `NEED_OP`
//! dead code there -- rather than existing as two copies that could drift.
//!
//! # This one has no C entry symbol at all
//!
//! All four public functions are `EXPORT_SYMBOL_GPL`'d, so each has a
//! MODVERSIONS CRC -- but unlike `lzo1x_decompress_safe.c`, nothing here has
//! to stay C: no pre-boot decompressor ever *compresses* anything, so there
//! is no `#ifdef STATIC` body forcing a C file to survive. Each function
//! carries its own `kernel::kabi_export!` pin (contracts generated by
//! `rig/kabi-migrate.py` against `port/pristine/`, never hand-typed) and the
//! `lib/union_find` shape applies: no C thunk, no C file at all in the
//! `CONFIG_RUST=y` arm.
//!
//! # Deliberate divergences, recorded so nobody fixes them back
//!
//! 1. **Only the 64-bit unaligned-access fast paths are ported**, for both
//!    the zero-run scan and the match-length extension. The C's `#if
//!    defined(CONFIG_HAVE_EFFICIENT_UNALIGNED_ACCESS) && defined(LZO_USE_CTZ64
//!    /LZO_FAST_64BIT_MEMORY_ACCESS)` branches are exactly what `lzodefs.h`
//!    turns on for `CONFIG_X86_64` (the only architecture this project
//!    builds), so the alternate 32-bit-CTZ and byte-at-a-time branches never
//!    compile here regardless -- SCOPE.md §3a's deferral rule, not a
//!    behavioural shortcut: both scans only ever decide "how many zero/equal
//!    bytes came next", and the 64-bit path answers that identically, just
//!    faster.
//! 2. **`wrapping_mul`/`wrapping_sub` where the C relies on unsigned
//!    wraparound** (the hash multiply; the zero-run-length `(offset << 8) -
//!    offset` trick, `MAX_255_COUNT`-bounded the same way
//!    `lzo1x_decompress_safe_rs.rs` already documents). Pointer arithmetic
//!    uses plain `.add()`/`.offset()`: every advance is kept inside the
//!    caller's buffers by `NEED_OP` in the `SAFE` instantiation, and by the
//!    `SAFE = false` instantiation's own documented contract (the caller
//!    must have sized `dst` via `lzo1x_worst_compress()`) otherwise --
//!    exactly the C's own two contracts, not a new one.
//!
//! Replaces: lib/lzo/lzo1x_compress.c, lib/lzo/lzo1x_compress_safe.c

#![allow(non_snake_case)]

use core::ffi::{c_int, c_uchar, c_void};

/// `LZO_E_OK`, `include/linux/lzo.h`.
const LZO_E_OK: c_int = 0;
/// `LZO_E_OUTPUT_OVERRUN`, `include/linux/lzo.h`.
const LZO_E_OUTPUT_OVERRUN: c_int = -5;

/// `LZO_VERSION`, `lib/lzo/lzodefs.h` -- lzo-rle's bitstream version.
const LZO_VERSION: u8 = 1;

/// `D_BITS`, `lib/lzo/lzodefs.h`.
const D_BITS: u32 = 13;
/// `D_SIZE`, `1u << D_BITS`.
const D_SIZE: usize = 1 << D_BITS;
/// `D_MASK`, `D_SIZE - 1`.
const D_MASK: u32 = (D_SIZE - 1) as u32;

/// `lzo_dict_t`, `lib/lzo/lzodefs.h` -- `unsigned short`.
type LzoDictT = u16;

/// `M2_MAX_LEN`.
const M2_MAX_LEN: usize = 8;
/// `M2_MAX_OFFSET`.
const M2_MAX_OFFSET: usize = 0x0800;
/// `M3_MAX_LEN`.
const M3_MAX_LEN: usize = 33;
/// `M3_MAX_OFFSET`.
const M3_MAX_OFFSET: usize = 0x4000;
/// `M4_MAX_LEN`.
const M4_MAX_LEN: usize = 9;
/// `M4_MAX_OFFSET_V0`.
const M4_MAX_OFFSET_V0: usize = 0xbfff;
/// `M4_MAX_OFFSET_V1`.
const M4_MAX_OFFSET_V1: usize = 0xbffe;
/// `M3_MARKER`.
const M3_MARKER: u8 = 32;
/// `M4_MARKER`.
const M4_MARKER: u8 = 16;

/// `MIN_ZERO_RUN_LENGTH`.
const MIN_ZERO_RUN_LENGTH: usize = 4;
/// `MAX_ZERO_RUN_LENGTH`, `2047 + MIN_ZERO_RUN_LENGTH`.
const MAX_ZERO_RUN_LENGTH: usize = 2047 + MIN_ZERO_RUN_LENGTH;

/// `LZO1X_1_MEM_COMPRESS`, `include/linux/lzo.h` -- `8192 *
/// sizeof(unsigned short)`, i.e. `D_SIZE * size_of::<LzoDictT>()`.
const LZO1X_1_MEM_COMPRESS: usize = D_SIZE * core::mem::size_of::<LzoDictT>();

/// `lzo1x_1_do_compress()` / its `_safe` twin, unified by `SAFE`. `noinline`
/// in the C for code-size reasons that do not apply here; the `#[inline
/// (never)]` is kept anyway so a panic-symbol or disassembly diff attributes
/// cleanly to one function per instantiation rather than a merged copy.
///
/// # Safety
/// `in_ .. in_ + in_len` must be readable. `wrkmem` must be writable for
/// `LZO1X_1_MEM_COMPRESS` bytes. `*out` must be a valid write cursor; if
/// `SAFE`, `op_end` bounds it and is never written past; if `!SAFE`, the
/// caller must have sized the buffer behind `*out` via
/// `lzo1x_worst_compress(in_len)` (the C's own contract for the non-`_safe`
/// entry points) since no check here will catch an undersized one.
/// `*tp` and `*state_offset` must be live and, on any call after the first
/// for a given output stream, hold what the previous call left there.
#[inline(never)]
unsafe fn do_compress<const SAFE: bool>(
    in_: *const c_uchar,
    in_len: usize,
    out: *mut *mut c_uchar,
    op_end: *mut c_uchar,
    tp: *mut usize,
    wrkmem: *mut c_void,
    state_offset: *mut i8,
    bitstream_version: u8,
) -> c_int {
    // SAFETY: class B (boundary). The caller's contract above.
    unsafe {
        let dict = wrkmem as *mut LzoDictT;
        let mut ti = *tp;

        let mut op = *out;
        let mut ip = in_;
        let mut ii = ip;
        let in_end = in_.add(in_len);
        let ip_end = in_.add(in_len - 20);
        ip = ip.add(if ti < 4 { 4 - ti } else { 0 });

        macro_rules! need_op {
            ($x:expr) => {
                if SAFE && (op_end as usize).wrapping_sub(op as usize) < ($x) as usize {
                    return LZO_E_OUTPUT_OVERRUN;
                }
            };
        }

        /// The C's `literal:`/`next:` labels: both are inside the `for(;;)`,
        /// jumped to only from within it (`goto literal` on a hash miss,
        /// `goto next` after finishing an instruction) -- unlike
        /// `lzo1x_decompress_safe_rs.rs`'s `Entry`, nothing outside this
        /// loop ever jumps in, so two states are enough.
        enum Entry {
            Literal,
            Next,
        }
        let mut entry = Entry::Literal;

        'outer: loop {
            let m_pos: *const c_uchar;
            let mut m_len: usize;
            let mut m_off: usize;
            let mut t: usize;
            let mut run_length: usize = 0;

            match entry {
                Entry::Literal => {
                    // `ip += 1 + ((ip - ii) >> 5);`
                    ip = ip.add(1 + ((ip.offset_from(ii) as usize) >> 5));
                    entry = Entry::Next;
                    continue 'outer;
                }
                Entry::Next => {}
            }

            if ip >= ip_end {
                break;
            }
            let dv = u32::from_le_bytes([*ip, *ip.add(1), *ip.add(2), *ip.add(3)]);

            if dv == 0 && bitstream_version != 0 {
                let mut ir = ip.add(4);
                let limit = if ip_end < ip.add(MAX_ZERO_RUN_LENGTH + 1) {
                    ip_end
                } else {
                    ip.add(MAX_ZERO_RUN_LENGTH + 1)
                };
                // 64-bit unaligned scan -- see the module doc's divergence
                // note 1.
                while ir.add(32) <= limit {
                    let mut dv64 = (ir as *const u64).read_unaligned();
                    dv64 |= (ir.add(8) as *const u64).read_unaligned();
                    dv64 |= (ir.add(16) as *const u64).read_unaligned();
                    dv64 |= (ir.add(24) as *const u64).read_unaligned();
                    if dv64 != 0 {
                        break;
                    }
                    ir = ir.add(32);
                }
                while ir.add(8) <= limit {
                    let dv64 = (ir as *const u64).read_unaligned();
                    if dv64 != 0 {
                        ir = ir.add((dv64.trailing_zeros() >> 3) as usize);
                        break;
                    }
                    ir = ir.add(8);
                }
                while ir < limit && *ir == 0 {
                    ir = ir.add(1);
                }
                run_length = ir.offset_from(ip) as usize;
                if run_length > MAX_ZERO_RUN_LENGTH {
                    run_length = MAX_ZERO_RUN_LENGTH;
                }
                m_pos = core::ptr::null();
            } else {
                // `(dv * 0x1824429d) >> (32 - D_BITS)) & D_MASK` -- the
                // multiply overflows u32 by design (a hash), so
                // wrapping_mul is faithful, not defensive.
                t = ((dv.wrapping_mul(0x1824429d)) >> (32 - D_BITS)) as usize & D_MASK as usize;
                m_pos = in_.add(*dict.add(t) as usize);
                *dict.add(t) = ip.offset_from(in_) as LzoDictT;
                let m_dv = u32::from_le_bytes([*m_pos, *m_pos.add(1), *m_pos.add(2), *m_pos.add(3)]);
                if dv != m_dv {
                    entry = Entry::Literal;
                    continue 'outer;
                }
            }

            ii = ii.sub(ti);
            ti = 0;
            t = ip.offset_from(ii) as usize;
            if t != 0 {
                if t <= 3 {
                    *op.offset(*state_offset as isize) |= t as u8;
                    need_op!(4);
                    (op as *mut u32).write_unaligned((ii as *const u32).read_unaligned());
                    op = op.add(t);
                } else if t <= 16 {
                    need_op!(17);
                    *op = (t - 3) as u8;
                    op = op.add(1);
                    (op as *mut u64).write_unaligned((ii as *const u64).read_unaligned());
                    (op.add(8) as *mut u64).write_unaligned((ii.add(8) as *const u64).read_unaligned());
                    op = op.add(t);
                } else {
                    if t <= 18 {
                        need_op!(1);
                        *op = (t - 3) as u8;
                        op = op.add(1);
                    } else {
                        let mut tt = t - 18;
                        need_op!(1);
                        *op = 0;
                        op = op.add(1);
                        while tt > 255 {
                            tt -= 255;
                            need_op!(1);
                            *op = 0;
                            op = op.add(1);
                        }
                        need_op!(1);
                        *op = tt as u8;
                        op = op.add(1);
                    }
                    need_op!(t);
                    loop {
                        (op as *mut u64).write_unaligned((ii as *const u64).read_unaligned());
                        (op.add(8) as *mut u64).write_unaligned((ii.add(8) as *const u64).read_unaligned());
                        op = op.add(16);
                        ii = ii.add(16);
                        t -= 16;
                        if t < 16 {
                            break;
                        }
                    }
                    if t > 0 {
                        loop {
                            *op = *ii;
                            op = op.add(1);
                            ii = ii.add(1);
                            t -= 1;
                            if t == 0 {
                                break;
                            }
                        }
                    }
                }
            }

            if run_length != 0 {
                ip = ip.add(run_length);
                // The scan above starts at `ir = ip + 4` (past the 4 zero
                // bytes `dv == 0` already confirmed) before extending
                // further, so `run_length >= MIN_ZERO_RUN_LENGTH` always --
                // structurally bounded by the scan's own starting point, not
                // merely unproven by the compiler. `size_t` in the C, so
                // wrapping_sub is faithful either way. Found by the
                // CONFIG_RUST_OVERFLOW_CHECKS panic-symbol sweep,
                // 2026-09-06.
                debug_assert!(run_length >= MIN_ZERO_RUN_LENGTH);
                run_length = run_length.wrapping_sub(MIN_ZERO_RUN_LENGTH);
                need_op!(4);
                let word = ((run_length as u32) << 21) | 0xfffc18 | (run_length as u32 & 0x7);
                (op as *mut u32).write_unaligned(word.to_le());
                op = op.add(4);
                *state_offset = -3;
                ii = ip;
                entry = Entry::Next;
                continue 'outer;
            }

            m_len = 4;
            {
                // The C's `do { ... if (ip+m_len >= ip_end) goto
                // m_len_done; } while (v == 0);` -- the `goto` skips the
                // final `m_len += ctzll(v)/8` adjustment below
                // UNCONDITIONALLY whenever `ip_end` is reached, even if `v`
                // is ALSO nonzero at that exact point. A first version of
                // this port used `v != 0 || ip+m_len < ip_end` to decide
                // whether to apply the adjustment post-loop, which applies
                // it wrongly on that simultaneous case (`v != 0` alone made
                // the `||` true) -- a real divergence, not just a missed
                // edge case, caught by the differential harness
                // (port/test/lzo_compress) at scale, not by inspection.
                // `hit_end` names the C's `goto` explicitly instead.
                let mut v = (ip.add(m_len) as *const u64).read_unaligned()
                    ^ (m_pos.add(m_len) as *const u64).read_unaligned();
                let mut hit_end = false;
                if v == 0 {
                    loop {
                        // `m_len` only ever grows by 8 while walking forward
                        // through `in_len`-bounded buffers (`ip_end` stops
                        // it), never remotely close to `usize::MAX`; `size_t`
                        // in the C, so wrapping_add is faithful regardless.
                        // Found by the CONFIG_RUST_OVERFLOW_CHECKS
                        // panic-symbol sweep, 2026-09-06.
                        m_len = m_len.wrapping_add(8);
                        v = (ip.add(m_len) as *const u64).read_unaligned()
                            ^ (m_pos.add(m_len) as *const u64).read_unaligned();
                        if ip.add(m_len) >= ip_end {
                            hit_end = true;
                            break;
                        }
                        if v != 0 {
                            break;
                        }
                    }
                }
                if !hit_end {
                    // `trailing_zeros() >> 3` is 0..=8; same reasoning as
                    // above.
                    m_len = m_len.wrapping_add((v.trailing_zeros() >> 3) as usize);
                }
            }

            m_off = ip.offset_from(m_pos) as usize;
            ip = ip.add(m_len);
            if m_len <= M2_MAX_LEN && m_off <= M2_MAX_OFFSET {
                // `m_off` is a real match distance (`ip.offset_from(m_pos)`,
                // `m_pos` a strictly earlier position), so this can't
                // underflow in a valid match; `size_t` in the C, wrapping_sub
                // is faithful either way. Found by the
                // CONFIG_RUST_OVERFLOW_CHECKS panic-symbol sweep,
                // 2026-09-06.
                m_off = m_off.wrapping_sub(1);
                need_op!(2);
// `m_len` starts at 4 (set once, above, common to all three
                // branches) and only ever grows, so it is always >= 4
                // here -- structurally bounded, not merely unproven;
                // `size_t` in the C, wrapping_sub is faithful either way.
                // Found by the CONFIG_RUST_OVERFLOW_CHECKS panic-symbol
                // sweep, 2026-09-06.
                debug_assert!(m_len >= 4);
                *op = (((m_len.wrapping_sub(1)) << 5) | ((m_off & 7) << 2)) as u8;
                op = op.add(1);
                *op = (m_off >> 3) as u8;
                op = op.add(1);
            } else if m_off <= M3_MAX_OFFSET {
                // `m_off` is a real match distance (`ip.offset_from(m_pos)`,
                // `m_pos` a strictly earlier position), so this can't
                // underflow in a valid match; `size_t` in the C, wrapping_sub
                // is faithful either way. Found by the
                // CONFIG_RUST_OVERFLOW_CHECKS panic-symbol sweep,
                // 2026-09-06.
                m_off = m_off.wrapping_sub(1);
                need_op!(1);
                if m_len <= M3_MAX_LEN {
// `m_len` starts at 4 (set once, above, common to all three
                // branches) and only ever grows, so it is always >= 4
                // here -- structurally bounded, not merely unproven;
                // `size_t` in the C, wrapping_sub is faithful either way.
                // Found by the CONFIG_RUST_OVERFLOW_CHECKS panic-symbol
                // sweep, 2026-09-06.
                debug_assert!(m_len >= 4);
                    *op = M3_MARKER | (m_len.wrapping_sub(2)) as u8;
                    op = op.add(1);
                } else {
                    m_len -= M3_MAX_LEN;
                    *op = M3_MARKER;
                    op = op.add(1);
                    while m_len > 255 {
                        m_len -= 255;
                        need_op!(1);
                        *op = 0;
                        op = op.add(1);
                    }
                    need_op!(1);
                    *op = m_len as u8;
                    op = op.add(1);
                }
                need_op!(2);
                *op = (m_off << 2) as u8;
                op = op.add(1);
                *op = (m_off >> 6) as u8;
                op = op.add(1);
            } else {
                m_off -= 0x4000;
                need_op!(1);
                if m_len <= M4_MAX_LEN {
// `m_len` starts at 4 (set once, above, common to all three
                // branches) and only ever grows, so it is always >= 4
                // here -- structurally bounded, not merely unproven;
                // `size_t` in the C, wrapping_sub is faithful either way.
                // Found by the CONFIG_RUST_OVERFLOW_CHECKS panic-symbol
                // sweep, 2026-09-06.
                debug_assert!(m_len >= 4);
                    *op = M4_MARKER | (((m_off >> 11) & 8) as u8) | (m_len.wrapping_sub(2)) as u8;
                    op = op.add(1);
                } else {
                    if (m_off & 0x403f) == 0x403f
                        && (261..=264).contains(&m_len)
                        && bitstream_version != 0
                    {
                        // Ambiguous-output guard, transcribed verbatim --
                        // see the C's own comment.
                        ip = ip.sub(m_len - 260);
                        m_len = 260;
                    }
                    m_len -= M4_MAX_LEN;
                    *op = M4_MARKER | (((m_off >> 11) & 8) as u8);
                    op = op.add(1);
                    while m_len > 255 {
                        need_op!(1);
                        m_len -= 255;
                        *op = 0;
                        op = op.add(1);
                    }
                    need_op!(1);
                    *op = m_len as u8;
                    op = op.add(1);
                }
                need_op!(2);
                *op = (m_off << 2) as u8;
                op = op.add(1);
                *op = (m_off >> 6) as u8;
                op = op.add(1);
            }
            *state_offset = -2;
            ii = ip;
            entry = Entry::Next;
        }

        *out = op;
        *tp = in_end.offset_from(ii.sub(ti)) as usize;
        LZO_E_OK
    }
}

/// `lzogeneric1x_1_compress()` / its `_safe` twin, unified by `SAFE`.
///
/// # Safety
/// `in_ .. in_ + in_len` must be readable, `*out_len` a live `usize`, and
/// `wrkmem` writable for `LZO1X_1_MEM_COMPRESS` bytes. If `SAFE`, `out ..
/// out + *out_len` bounds every write; if `!SAFE`, the caller must have
/// sized `out` via `lzo1x_worst_compress(in_len)` -- same two contracts as
/// [`do_compress`].
unsafe fn generic_compress<const SAFE: bool>(
    in_: *const c_uchar,
    in_len: usize,
    out: *mut c_uchar,
    out_len: *mut usize,
    wrkmem: *mut c_void,
    bitstream_version: u8,
) -> c_int {
    // SAFETY: class B (boundary). The caller's contract above.
    unsafe {
        let op_end = out.add(*out_len);
        let mut op = out;
        let mut ip = in_;
        let mut l = in_len;
        let mut t: usize = 0;
        let mut state_offset: i8 = -2;

        macro_rules! need_op {
            ($x:expr) => {
                if SAFE && (op_end as usize).wrapping_sub(op as usize) < ($x) as usize {
                    return LZO_E_OUTPUT_OVERRUN;
                }
            };
        }

        // LZO v0 never writes 17 as its first byte (except for zero-length
        // input); used to version the bitstream.
        let m4_max_offset: usize;
        if bitstream_version > 0 {
            *op = 17;
            op = op.add(1);
            *op = bitstream_version;
            op = op.add(1);
            m4_max_offset = M4_MAX_OFFSET_V1;
        } else {
            m4_max_offset = M4_MAX_OFFSET_V0;
        }
        let data_start = op;

        while l > 20 {
            let ll = l.min(m4_max_offset + 1);
            let ll_end = (ip as usize).wrapping_add(ll);
            // `t` is a small pending-literal count and `ll <= m4_max_offset
            // + 1` (~48KiB); nowhere near `usize::MAX`, but `uintptr_t`/
            // `size_t` in the C, so wrapping_add is faithful either way.
            // Found by the CONFIG_RUST_OVERFLOW_CHECKS panic-symbol sweep,
            // 2026-09-06.
            if ll_end.wrapping_add((t.wrapping_add(ll)) >> 5) <= ll_end {
                break;
            }
            core::ptr::write_bytes(wrkmem as *mut u8, 0, D_SIZE * core::mem::size_of::<LzoDictT>());
            let err =
                do_compress::<SAFE>(ip, ll, &mut op, op_end, &mut t, wrkmem, &mut state_offset, bitstream_version);
            if err != LZO_E_OK {
                return err;
            }
            ip = ip.add(ll);
            l -= ll;
        }
        // `t` (pending literal count) and `l` (remaining input) are both
        // real-allocation-bounded, nowhere near `usize::MAX`; `size_t` in
        // the C, so wrapping_add is faithful either way. Found by the
        // CONFIG_RUST_OVERFLOW_CHECKS panic-symbol sweep, 2026-09-06.
        t = t.wrapping_add(l);

        if t > 0 {
            // `t` is a suffix-length of `in_len` not yet consumed, so
            // `t <= in_len` by the algorithm's own invariant -- structurally
            // bounded, not merely unproven; `size_t` in the C either way.
            debug_assert!(t <= in_len);
            let ii_off = in_len.wrapping_sub(t);
            let mut ii = in_.add(ii_off);

            if op == data_start && t <= 238 {
                need_op!(1);
                *op = (17 + t) as u8;
                op = op.add(1);
            } else if t <= 3 {
                *op.offset(state_offset as isize) |= t as u8;
            } else if t <= 18 {
                need_op!(1);
                *op = (t - 3) as u8;
                op = op.add(1);
            } else {
                let mut tt = t - 18;
                need_op!(1);
                *op = 0;
                op = op.add(1);
                while tt > 255 {
                    tt -= 255;
                    need_op!(1);
                    *op = 0;
                    op = op.add(1);
                }
                need_op!(1);
                *op = tt as u8;
                op = op.add(1);
            }
            need_op!(t);
            if t >= 16 {
                loop {
                    (op as *mut u64).write_unaligned((ii as *const u64).read_unaligned());
                    (op.add(8) as *mut u64).write_unaligned((ii.add(8) as *const u64).read_unaligned());
                    op = op.add(16);
                    ii = ii.add(16);
                    t -= 16;
                    if t < 16 {
                        break;
                    }
                }
            }
            if t > 0 {
                loop {
                    *op = *ii;
                    op = op.add(1);
                    ii = ii.add(1);
                    t -= 1;
                    if t == 0 {
                        break;
                    }
                }
            }
        }

        need_op!(3);
        *op = M4_MARKER | 1;
        op = op.add(1);
        *op = 0;
        op = op.add(1);
        *op = 0;
        op = op.add(1);

        *out_len = op.offset_from(out) as usize;
        LZO_E_OK
    }
}

