/// Body of `errseq_set()`: record `err`, returning the PREVIOUS value.
///
/// `err` must be between -1 and `-MAX_ERRNO`; zero is refused because it
/// would clear a previous error rather than record one. **The refusal is a
/// `WARN` that names the offending value**, and it is reproduced with
/// `kernel::kabi_warn!` rather than dropped -- a silent return here would
/// turn a caller's bug into a lost writeback error.
///
/// # Safety
/// `eseq` must be a valid, aligned `errseq_t` that other CPUs may be
/// updating concurrently.
#[no_mangle]
pub unsafe extern "C" fn errseq_set(eseq: *mut Errseq, err: c_int) -> Errseq {
    // SAFETY: the caller guarantees a valid errseq_t.
    let a = unsafe { &*atomic(eseq) };
    let mut old = a.load(Ordering::Relaxed);

    if kernel::kabi_warn!(err == 0 || (err as u32).wrapping_neg() > MAX_ERRNO, "err = %d\n", err) {
        return old;
    }

    let cur;
    loop {
        // Clear out error bits and set new error.
        let mut new = (old & !(ERRNO_MASK | ERRSEQ_SEEN)) | (err as u32).wrapping_neg();

        // Only increment if someone has looked at it.
        if old & ERRSEQ_SEEN != 0 {
            new = new.wrapping_add(ERRSEQ_CTR_INC);
        }

        // If there would be no change, then call it done.
        if new == old {
            cur = new;
            break;
        }

        match a.compare_exchange(old, new, Ordering::SeqCst, Ordering::SeqCst) {
            // We did the swap.
            Ok(_) => {
                cur = old;
                break;
            }
            Err(seen) => {
                // Someone else beat us to it for the same value: success too.
                if seen == new {
                    cur = seen;
                    break;
                }
                // Raced with an update, try again.
                old = seen;
            }
        }
    }
    cur
}

kernel::kabi_export! {
    errseq_sample,
    license = "",
    namespace = "",
    contract = "subprogram ( formal_parameter pointer_type { t#errseq_t } eseq ) -> t#errseq_t",
}

/// Body of `errseq_sample()`: the value a new subscriber should start from.
///
/// **An unseen error samples as 0, not as itself.** That is what makes the
/// next `errseq_check_and_advance()` report it: a subscriber that starts life
/// while an error is pending is told about it, and one that starts after
/// somebody has already looked is not.
///
/// # Safety
/// `eseq` must be a valid, aligned `errseq_t`.
#[no_mangle]
pub unsafe extern "C" fn errseq_sample(eseq: *mut Errseq) -> Errseq {
    // SAFETY: the caller guarantees a valid errseq_t. READ_ONCE is a single
    // non-tearing read with no ordering, which is a relaxed atomic load.
    let old = unsafe { (*atomic(eseq)).load(Ordering::Relaxed) };

    if old & ERRSEQ_SEEN == 0 {
        0
    } else {
        old
    }
}

kernel::kabi_export! {
    errseq_check,
    license = "",
    namespace = "",
    contract = "subprogram ( formal_parameter pointer_type { t#errseq_t } eseq , formal_parameter t#errseq_t since ) -> base_type int byte_size(4) encoding(5)",
}

/// Body of `errseq_check()`: has anything happened since `since`?
///
/// Does **not** advance `since` and does not set `ERRSEQ_SEEN`, so it is safe
/// to call without the lock that protects the caller's sample. That is the
/// point of it: callers do this first, lockless, and only take the lock when
/// it says yes.
///
/// # Safety
/// `eseq` must be a valid, aligned `errseq_t`.
#[no_mangle]
pub unsafe extern "C" fn errseq_check(eseq: *mut Errseq, since: Errseq) -> c_int {
    // SAFETY: the caller guarantees a valid errseq_t.
    let cur = unsafe { (*atomic(eseq)).load(Ordering::Relaxed) };

    if cur == since {
        return 0;
    }
    -((cur & ERRNO_MASK) as c_int)
}

kernel::kabi_export! {
    errseq_check_and_advance,
    license = "",
    namespace = "",
    contract = "subprogram ( formal_parameter pointer_type { t#errseq_t } eseq , formal_parameter pointer_type { t#errseq_t } since ) -> base_type int byte_size(4) encoding(5)",
}

/// Body of `errseq_check_and_advance()`: report a new error once, and move
/// the caller's sample forward.
///
/// **The `cmpxchg` result is deliberately ignored.** If it fails, either a
/// writer changed the value or another reader set the same flag; both are
/// fine, and the C says so in a comment. What matters is that `*since` is
/// advanced to the value this caller decided on, so the same error is not
/// reported to it twice.
///
/// # Safety
/// `eseq` must be a valid, aligned `errseq_t`; `since` must be a valid
/// `errseq_t` **that only this caller is using** -- no locking is provided
/// for it, which the C documents.
#[no_mangle]
pub unsafe extern "C" fn errseq_check_and_advance(eseq: *mut Errseq, since: *mut Errseq) -> c_int {
    // SAFETY: the caller guarantees both pointers are valid.
    let a = unsafe { &*atomic(eseq) };
    let old = a.load(Ordering::Relaxed);
    // SAFETY: `since` is the caller's private sample.
    let seen = unsafe { *since };

    if old == seen {
        return 0;
    }

    let new = old | ERRSEQ_SEEN;
    if new != old {
        // The outcome does not matter; see the doc comment.
        let _ = a.compare_exchange(old, new, Ordering::SeqCst, Ordering::SeqCst);
    }
    // SAFETY: as above.
    unsafe { *since = new };
    -((new & ERRNO_MASK) as c_int)
}
