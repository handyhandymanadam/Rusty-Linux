//! Sampled error records -- the Rust behind `lib/errseq.c`.
//!
//! Ported from `lib/errseq.c` (6.18.49).
//!
//! Replaces: lib/errseq.c
//!
//! # What an `errseq_t` is
//!
//! One `u32` that records *an error happened* in a way any number of
//! independent subscribers can each notice exactly once. The low bits hold a
//! negated errno, one bit above them says "somebody has looked at this since
//! it was last set", and the rest is a counter. `fs/` uses it for writeback
//! errors: every open file samples the value, and each one is told about a
//! writeback failure once, without a lock and without a per-file record.
//!
//! | bits | meaning |
//! |---|---|
//! | `0 .. ERRSEQ_SHIFT` | `-err`, at most `MAX_ERRNO` |
//! | `ERRSEQ_SHIFT` | `ERRSEQ_SEEN` |
//! | above | counter, incremented only when the value had been seen |
//!
//! # The counter increment is conditional, and that is the design
//!
//! `errseq_set()` bumps the counter **only if `ERRSEQ_SEEN` is set**. With so
//! few counter bits, incrementing on every error would wrap quickly and two
//! distinct errors could collide on one value; not incrementing while nobody
//! has looked costs nothing, because a subscriber that has not sampled will
//! see the new error anyway. Dropping that condition is a translation error
//! that no single-threaded test can distinguish.
//!
//! # `cmpxchg` here is a full barrier and the retry is not a loop of loads
//!
//! `errseq_set()`'s loop calls `cmpxchg()`, whose kernel semantics are a full
//! barrier on both success and failure, and takes the *returned* old value as
//! the next candidate rather than re-reading. `compare_exchange` with
//! `SeqCst` on both orderings is the same instruction and returns the same
//! observed value in its `Err`.

use core::ffi::c_int;
use core::sync::atomic::{AtomicU32, Ordering};

/// `errseq_t` -- `include/linux/errseq.h`.
type Errseq = u32;

/// `MAX_ERRNO` from `include/linux/err.h`.
const MAX_ERRNO: u32 = 4095;
/// `ERRSEQ_SHIFT` -- `ilog2(MAX_ERRNO) + 1`, i.e. 12.
const ERRSEQ_SHIFT: u32 = 12;
/// `ERRSEQ_SEEN` -- the has-been-sampled flag.
const ERRSEQ_SEEN: Errseq = 1 << ERRSEQ_SHIFT;
/// `ERRNO_MASK` -- the bits the errno occupies.
const ERRNO_MASK: Errseq = ERRSEQ_SEEN - 1;
/// `ERRSEQ_CTR_INC` -- the lowest bit of the counter.
const ERRSEQ_CTR_INC: Errseq = 1 << (ERRSEQ_SHIFT + 1);

// ilog2(4095) is 11, so ERRSEQ_SHIFT is 12. Asserted rather than trusted:
// the C computes it from MAX_ERRNO and this file writes it down, so if
// MAX_ERRNO ever changes the build must stop rather than silently shifting
// the error field.
const _: () = assert!(ERRSEQ_SHIFT == MAX_ERRNO.ilog2() + 1);

/// `eseq` as the atomic the C's `cmpxchg()` treats it as.
///
/// # Safety
/// `eseq` must be a valid, aligned `errseq_t`.
#[inline]
unsafe fn atomic(eseq: *mut Errseq) -> *const AtomicU32 {
    // SAFETY: AtomicU32 has u32's size, alignment and representation, which
    // is the same aliasing the C relies on applying cmpxchg() to a plain u32.
    eseq as *const AtomicU32
}

