//! The VGA 8x16 console font -- the Rust behind `lib/fonts/font_8x16.c`.
//!
//! Pure data, no logic: the pristine C is a 4096-byte glyph bitmap array
//! (256 characters x 16 bytes each, 8 pixels per row) plus one exported
//! `struct font_desc` descriptor. Ported by transcription is the wrong
//! word for what happened here -- the byte array below was extracted
//! directly out of the pristine C's own hex literals by a script, not
//! typed by hand, matching this project's standing rule against
//! hand-copying large constant tables (see lib/ctype.c's own module doc:
//! the previous porting attempt hit exactly this class of bug
//! hand-copying vsprintf's `decpair[]`). port/test/fonts/ cross-checks
//! every byte, plus struct field offsets, against the pristine C directly.
//!
//! # The one real ABI detail: `struct font_data`'s hidden header
//!
//! `include/linux/font.h` declares:
//! ```c
//! struct font_data {
//!     unsigned int extra[FONT_EXTRA_WORDS];  // 4 words = 16 bytes
//!     const unsigned char data[];
//! } __packed;
//! ```
//! and `REFCOUNT`/`FNTSIZE`/`FNTCHARCNT`/`FNTSUM` (same header) read that
//! `extra[]` header via NEGATIVE offsets from a `font_desc.data` pointer
//! that has already been advanced PAST it -- `font_desc.data` in the
//! pristine C is `fontdata_8x16.data`, i.e. the address right after the
//! 16-byte `extra` header, not the start of the `font_data` object.
//! Grepped this kernel version for real callers of those four macros:
//! none (looks vestigial). Preserved anyway, since it costs nothing and
//! it's the real contract the header declares -- `FontData` below keeps
//! the same 16-byte `extra` header immediately before the glyph bytes,
//! and `FONT_VGA_8X16.data` points at `FONTDATA_8X16.data`, matching the
//! pristine layout exactly.

use core::ffi::{c_char, c_int, c_uint, c_void};

/// `FONTDATAMAX`, pristine C.
const FONTDATAMAX: usize = 4096;

/// `struct font_data`, `include/linux/font.h`. `data` is a fixed
/// `[u8; FONTDATAMAX]` here rather than a C flexible array member --
/// this file's own single instantiation is always exactly that size,
/// and a fixed array gives an ordinary, safely-indexable Rust type
/// with the identical byte layout (`#[repr(C)]` places it right after
/// `extra`, same as the C's flexible-array-member convention).
#[repr(C)]
struct FontData {
    extra: [u32; 4],
    data: [u8; FONTDATAMAX],
}

/// `struct font_desc`, `include/linux/font.h`.
#[repr(C)]
pub struct FontDesc {
    idx: c_int,
    name: *const c_char,
    width: c_uint,
    height: c_uint,
    charcount: c_uint,
    data: *const c_void,
    pref: c_int,
}

// SAFETY: `FontDesc` is read-only kernel data (every field either a
// plain integer or a pointer to other read-only static data); sharing
// it across threads is safe. Required because it contains raw
// pointers, which are `!Sync` by default.
unsafe impl Sync for FontDesc {}

/// `VGA8x16_IDX`, `include/linux/font.h`.
const VGA8X16_IDX: c_int = 1;

