//! `mac_pton()` -- parse "xx:xx:xx:xx:xx:xx" into six bytes.
//!
//! Ported from `lib/net_utils.c` (6.18.49).
//!
//! The C reaches for `strnlen`, `isxdigit` and `hex_to_bin`; none of those
//! is doing anything a byte comparison cannot, and going through them means
//! the input is walked three times. Here it is walked once, and the digit
//! test and the digit value come from the same match.
//!
//! Replaces: lib/net_utils.c

/// `ETH_ALEN` from `include/uapi/linux/if_ether.h`.
const ETH_ALEN: usize = 6;
/// `MAC_ADDR_STR_LEN` from `include/linux/if_ether.h`: `3 * ETH_ALEN - 1`.
#[allow(dead_code)]
const MAC_ADDR_STR_LEN: usize = 3 * ETH_ALEN - 1;

/// Value of one hex digit, or `None` if it is not one.
#[inline]
fn hex_val(c: u8) -> Option<u8> {
    match c {
        b'0'..=b'9' => Some(c - b'0'),
        b'a'..=b'f' => Some(c - b'a' + 10),
        b'A'..=b'F' => Some(c - b'A' + 10),
        _ => None,
    }
}

// The C types these contracts name. A Rust object has
// no C type graph to resolve them against, so they are
// not duplicates of anything -- omit one and the build
// stops naming the reference it could not resolve.
// Generated by rig/kabi-migrate.py; do not hand-edit.
kernel::kabi_rule!("type_string", "t#__u8",
    "typedef_type __u8 { base_type unsigned char byte_size(1) encoding(8) }");
kernel::kabi_rule!("type_string", "t#bool",
    "typedef_type bool { base_type _Bool byte_size(1) encoding(2) }");
kernel::kabi_rule!("type_string", "t#u8",
    "typedef_type u8 { t#__u8 }");

kernel::kabi_export! {
    mac_pton,
    license = "",
    namespace = "",
    contract = "subprogram ( formal_parameter pointer_type { const_type { base_type char byte_size(1) encoding(8) } } s , formal_parameter pointer_type { t#u8 } mac ) -> t#bool",
}

/// Body of `mac_pton()`.
///
/// # Safety
/// `s` must be a NUL-terminated string and `mac` writable for `ETH_ALEN`
/// bytes. Same contract as the C.
///
/// See `include/linux/etherdevice.h` for the C declaration.
#[no_mangle]
pub unsafe extern "C" fn mac_pton(s: *const core::ffi::c_char, mac: *mut u8) -> bool {
    let s = s as *const u8;
    let mut parsed = [0u8; ETH_ALEN];

    for (i, slot) in parsed.iter_mut().enumerate() {
        // SAFETY: the caller guarantees a NUL-terminated string. Every read
        // below is at an index the loop has already found non-NUL, or is the
        // first byte of the next group, so no read goes past the terminator:
        // a NUL returns false from hex_val or fails the ':' test, and the
        // function returns before advancing.
        let hi = unsafe { *s.add(i * 3) };
        let Some(hi) = hex_val(hi) else { return false };
        let lo = unsafe { *s.add(i * 3 + 1) };
        let Some(lo) = hex_val(lo) else { return false };

        if i != ETH_ALEN - 1 && unsafe { *s.add(i * 3 + 2) } != b':' {
            return false;
        }
        *slot = (hi << 4) | lo;
    }

    // The C's leading `strnlen(s, MAC_ADDR_STR_LEN) < MAC_ADDR_STR_LEN`
    // check is subsumed rather than dropped: reaching here means all
    // MAC_ADDR_STR_LEN bytes were hex digits or colons in the right places,
    // so none of them can have been the terminator.

    // "Don't dirty result unless string is valid MAC" -- the C's comment,
    // and the reason nothing above writes through `mac`.
    // SAFETY: the caller guarantees `mac` is writable for ETH_ALEN bytes.
    unsafe { core::ptr::copy_nonoverlapping(parsed.as_ptr(), mac, ETH_ALEN) };
    true
}
