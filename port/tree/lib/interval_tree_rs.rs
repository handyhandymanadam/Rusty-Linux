/// `rb_insert_augmented_cached()` folded into `rb_insert_augmented()`.
///
/// # Safety
/// `node` must be freshly linked into `root` by [`rb_link_node`], and
/// `root` must be valid.
#[inline(always)]
unsafe fn rb_insert_augmented_cached(node: *mut IntervalTreeRbNode, root: *mut IntervalTreeRbRootCached, newleft: bool) {
    // SAFETY: caller guarantees `node` and `root` are valid.
    unsafe {
        if newleft {
            (*root).rb_leftmost = node;
        }
        __rb_insert_augmented(node, ptr::addr_of_mut!((*root).rb_root), augment_rotate);
    }
}

/// `__rb_erase_augmented()`, specialised to this file's callbacks.
///
/// Returns the node the caller must hand to `__rb_erase_color()`, or null
/// if no colour rebalance is needed. Transcribed case for case from
/// `include/linux/rbtree_augmented.h`; the three cases and their diagrams
/// are the C's own.
///
/// # Safety
/// `node` must be currently linked into `root`, and `root` must be valid.
#[inline(always)]
unsafe fn erase_augmented(node: *mut IntervalTreeRbNode, root: *mut IntervalTreeRbRoot) -> *mut IntervalTreeRbNode {
    // SAFETY: caller guarantees `node` is linked into `root`.
    unsafe {
        let child = (*node).rb_right;
        let mut tmp = (*node).rb_left;
        let parent: *mut IntervalTreeRbNode;
        let rebalance: *mut IntervalTreeRbNode;

        if tmp.is_null() {
            // Case 1: node to erase has no more than 1 child (easy!)
            //
            // Note that if there is one child it must be red due to 5)
            // and node must be black due to 4). We adjust colors locally
            // so as to bypass __rb_erase_color() later on.
            let pc = (*node).rb_parent_color;
            parent = pc_parent(pc);
            rb_change_child(node, child, parent, root);
            if !child.is_null() {
                (*child).rb_parent_color = pc;
                rebalance = ptr::null_mut();
            } else {
                rebalance = if pc_is_black(pc) { parent } else { ptr::null_mut() };
            }
            tmp = parent;
        } else if child.is_null() {
            // Still case 1, but this time the child is node->rb_left
            let pc = (*node).rb_parent_color;
            (*tmp).rb_parent_color = pc;
            parent = pc_parent(pc);
            rb_change_child(node, tmp, parent, root);
            rebalance = ptr::null_mut();
            tmp = parent;
        } else {
            let mut successor = child;
            let child2: *mut IntervalTreeRbNode;

            tmp = (*child).rb_left;
            if tmp.is_null() {
                // Case 2: node's successor is its right child
                //
                //    (n)          (s)
                //    / \          / \
                //  (x) (s)  ->  (x) (c)
                //        \
                //        (c)
                parent = successor;
                child2 = (*successor).rb_right;

                augment_copy(node, successor);
            } else {
                // Case 3: node's successor is leftmost under node's right
                // child subtree
                //
                //    (n)          (s)
                //    / \          / \
                //  (x) (y)  ->  (x) (y)
                //      /            /
                //    (p)          (p)
                //    /            /
                //  (s)          (c)
                //    \
                //    (c)
                // The C's
                //     do { parent = successor; successor = tmp;
                //          tmp = tmp->rb_left; } while (tmp);
                // written as Rust's only do-while shape. `parent` is the
                // value `successor` held one step before the loop ended.
                let mut last_parent: *mut IntervalTreeRbNode;
                loop {
                    last_parent = successor;
                    successor = tmp;
                    tmp = (*tmp).rb_left;
                    if tmp.is_null() {
                        break;
                    }
                }
                parent = last_parent;
                child2 = (*successor).rb_right;
                ptr::addr_of_mut!((*parent).rb_left).write_volatile(child2);
                ptr::addr_of_mut!((*successor).rb_right).write_volatile(child);
                rb_set_parent(child, successor);

                augment_copy(node, successor);
                augment_propagate(parent, successor);
            }

            tmp = (*node).rb_left;
            ptr::addr_of_mut!((*successor).rb_left).write_volatile(tmp);
            rb_set_parent(tmp, successor);

            let pc2 = (*node).rb_parent_color;
            tmp = pc_parent(pc2);
            rb_change_child(node, successor, tmp, root);

            if !child2.is_null() {
                rb_set_parent_color(child2, parent, 1 /* RB_BLACK */);
                rebalance = ptr::null_mut();
            } else {
                rebalance = if rb_is_black(successor) { parent } else { ptr::null_mut() };
            }
            (*successor).rb_parent_color = pc2;
            tmp = successor;
        }

        augment_propagate(tmp, ptr::null_mut());
        rebalance
    }
}

/// `rb_erase_augmented_cached()` folded into `rb_erase_augmented()`.
///
/// # Safety
/// `node` must be currently linked into `root`, and `root` must be valid.
#[inline(always)]
unsafe fn rb_erase_augmented_cached(node: *mut IntervalTreeRbNode, root: *mut IntervalTreeRbRootCached) {
    // SAFETY: caller guarantees `node` is linked into `root`.
    unsafe {
        if (*root).rb_leftmost == node {
            (*root).rb_leftmost = rb_next(node);
        }
        let rebalance = erase_augmented(node, ptr::addr_of_mut!((*root).rb_root));
        if !rebalance.is_null() {
            __rb_erase_color(rebalance, ptr::addr_of_mut!((*root).rb_root), augment_rotate);
        }
    }
}

