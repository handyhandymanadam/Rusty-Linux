/// `interval_tree_iter_next()`: the next node after `node` intersecting
/// `[start, last]`, or `NULL`.
///
/// # Safety
/// `node` must be a node currently linked into an interval tree, and must
/// itself intersect `[start, last]` -- i.e. it must be a value a previous
/// [`interval_tree_iter_first`] or `interval_tree_iter_next` returned for
/// the same query.
#[no_mangle]
pub unsafe extern "C" fn interval_tree_iter_next(
    mut node: *mut IntervalTreeNode,
    start: usize,
    last: usize,
) -> *mut IntervalTreeNode {
    // SAFETY: caller guarantees `node` is linked and matches the query.
    unsafe {
        let mut rb = (*node).rb.rb_right;

        loop {
            // Loop invariants:
            //   Cond1: ITSTART(node) <= last
            //   rb == node->rb.rb_right
            //
            // First, search right subtree if suitable
            if !rb.is_null() {
                let right = rb.cast::<IntervalTreeNode>();
                if start <= (*right).subtree_last {
                    return subtree_search(right, start, last);
                }
            }

            // Move up the tree until we come from a node's left child
            loop {
                rb = rb_parent(ptr::addr_of!((*node).rb));
                if rb.is_null() {
                    return ptr::null_mut();
                }
                let prev: *mut IntervalTreeRbNode = ptr::addr_of_mut!((*node).rb);
                node = rb.cast::<IntervalTreeNode>();
                rb = (*node).rb.rb_right;
                if prev != rb {
                    break;
                }
            }

            // Check if the node intersects [start;last]
            if last < (*node).start {
                // !Cond1
                return ptr::null_mut();
            } else if start <= (*node).last {
                // Cond2
                return node;
            }
        }
    }
}

