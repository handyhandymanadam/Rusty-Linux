/// `interval_tree_span_iter_advance()`: move the iteration to `new_index`.
///
/// The returned used/hole is updated to start at `new_index`. This is
/// faster than calling [`interval_tree_span_iter_first`] as it can avoid
/// full searches in several cases where the iterator is already set.
///
/// # Safety
/// `iter` and `itree` must be valid, and `iter` must have been initialised
/// by [`interval_tree_span_iter_first`].
#[cfg(CONFIG_INTERVAL_TREE_SPAN_ITER)]
#[no_mangle]
pub unsafe extern "C" fn interval_tree_span_iter_advance(
    iter: *mut IntervalTreeSpanIter,
    itree: *mut IntervalTreeRbRootCached,
    new_index: usize,
) {
    // SAFETY: caller guarantees `iter` and `itree` are valid.
    unsafe {
        if (*iter).is_hole == -1 {
            return;
        }

        (*iter).first_index = new_index;
        if new_index > (*iter).last_index {
            (*iter).is_hole = -1;
            return;
        }

        // Rely on the union aliasing hole/used
        if (*iter).start.start_hole <= new_index && new_index <= (*iter).last.last_hole {
            (*iter).start.start_hole = new_index;
            return;
        }
        // DELIBERATE WRAP, and the only one in this file. The union may be
        // holding `last_used` rather than `last_hole`, and a used span can
        // legitimately end at `ULONG_MAX` -- at which point the C's
        // `iter->last_hole + 1` wraps to 0 and compares against
        // `new_index`. Reproduced with `wrapping_add` so the port keeps the
        // C's answer instead of panicking under
        // `CONFIG_RUST_OVERFLOW_CHECKS=y`. Reaching it needs `new_index`
        // BELOW the current span's start, which "advance" implies no caller
        // does and `drivers/iommu/iommufd/` does not; recorded rather than
        // guarded, per logs/floor.md's ruling of 2026-09-04.
        if new_index == (*iter).last.last_hole.wrapping_add(1) {
            interval_tree_span_iter_next(iter);
        } else {
            interval_tree_span_iter_first(iter, itree, new_index, (*iter).last_index);
        }
    }
}
