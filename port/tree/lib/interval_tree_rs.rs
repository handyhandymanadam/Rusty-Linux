/// `interval_tree_iter_first()`: the leftmost node intersecting
/// `[start, last]`, or `NULL`.
///
/// # Safety
/// `root` must be valid.
#[no_mangle]
pub unsafe extern "C" fn interval_tree_iter_first(
    root: *mut IntervalTreeRbRootCached,
    start: usize,
    last: usize,
) -> *mut IntervalTreeNode {
    // SAFETY: caller guarantees `root` is valid.
    unsafe {
        if (*root).rb_root.rb_node.is_null() {
            return ptr::null_mut();
        }

        // Fastpath range intersection/overlap between A: [a0, a1] and
        // B: [b0, b1] is given by:
        //
        //         a0 <= b1 && b0 <= a1
        //
        //  ... where A holds the lock range and B holds the smallest
        // 'start' and largest 'last' in the tree. For the later, we rely on
        // the root node, which by augmented interval tree property, holds
        // the largest value in its last-in-subtree. This allows mitigating
        // some of the tree walk overhead for non-intersecting ranges,
        // maintained and consulted in O(1).
        let node = (*root).rb_root.rb_node.cast::<IntervalTreeNode>();
        if (*node).subtree_last < start {
            return ptr::null_mut();
        }

        let leftmost = (*root).rb_leftmost.cast::<IntervalTreeNode>();
        if (*leftmost).start > last {
            return ptr::null_mut();
        }

        subtree_search(node, start, last)
    }
}

