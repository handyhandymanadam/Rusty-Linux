/// `interval_tree_insert()`: link `node` into `root`.
///
/// The C is `INTERVAL_TREE_DEFINE`'s `ITPREFIX ## _insert`. Note what the
/// descent does on the way down: it raises every parent's
/// `__subtree_last` to `last` as it passes, so by the time the node is
/// linked the augmented values above it are already correct and only
/// rotations need the callbacks.
///
/// # Safety
/// `node` and `root` must be valid, and `node` must not already be linked
/// into any interval tree.
#[no_mangle]
pub unsafe extern "C" fn interval_tree_insert(
    node: *mut IntervalTreeNode,
    root: *mut IntervalTreeRbRootCached,
) {
    // SAFETY: caller guarantees `node` and `root` are valid.
    unsafe {
        let mut link = ptr::addr_of_mut!((*root).rb_root.rb_node);
        let mut rb_parent_node: *mut IntervalTreeRbNode = ptr::null_mut();
        let start = (*node).start;
        let last = (*node).last;
        let mut leftmost = true;

        while !(*link).is_null() {
            rb_parent_node = *link;
            let parent = rb_parent_node.cast::<IntervalTreeNode>();
            if (*parent).subtree_last < last {
                (*parent).subtree_last = last;
            }
            if start < (*parent).start {
                link = ptr::addr_of_mut!((*parent).rb.rb_left);
            } else {
                link = ptr::addr_of_mut!((*parent).rb.rb_right);
                leftmost = false;
            }
        }

        (*node).subtree_last = last;
        rb_link_node(ptr::addr_of_mut!((*node).rb), rb_parent_node, link);
        rb_insert_augmented_cached(ptr::addr_of_mut!((*node).rb), root, leftmost);
    }
}

