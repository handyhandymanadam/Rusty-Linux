/// `rb_parent()`. The low two bits of `__rb_parent_color` carry the colour.
///
/// # Safety
/// `rb` must be valid.
#[inline(always)]
unsafe fn rb_parent(rb: *const IntervalTreeRbNode) -> *mut IntervalTreeRbNode {
    // SAFETY: caller guarantees `rb` is valid.
    unsafe { ((*rb).rb_parent_color & !3) as *mut IntervalTreeRbNode }
}

/// `rb_color()` -- `RB_RED` is 0, `RB_BLACK` is 1.
///
/// # Safety
/// `rb` must be valid.
#[inline(always)]
unsafe fn rb_color(rb: *const IntervalTreeRbNode) -> usize {
    // SAFETY: caller guarantees `rb` is valid.
    unsafe { (*rb).rb_parent_color & 1 }
}

/// `rb_is_black()`.
///
/// # Safety
/// `rb` must be valid.
#[inline(always)]
unsafe fn rb_is_black(rb: *const IntervalTreeRbNode) -> bool {
    // SAFETY: caller guarantees `rb` is valid.
    unsafe { rb_color(rb) == 1 }
}

/// `__rb_is_black()`, taking the raw `__rb_parent_color` word rather than
/// the node -- the C needs this form in [`erase_augmented`], where the word
/// has already been saved and the node is about to be unlinked.
#[inline(always)]
fn pc_is_black(pc: usize) -> bool {
    pc & 1 == 1
}

/// `__rb_parent()`, the same, over a saved `__rb_parent_color` word.
#[inline(always)]
fn pc_parent(pc: usize) -> *mut IntervalTreeRbNode {
    (pc & !3) as *mut IntervalTreeRbNode
}

/// `rb_set_parent()`: keep the colour, replace the parent.
///
/// # Safety
/// `rb` must be valid; `p` may be null.
#[inline(always)]
unsafe fn rb_set_parent(rb: *mut IntervalTreeRbNode, p: *mut IntervalTreeRbNode) {
    // SAFETY: caller guarantees `rb` is valid.
    unsafe { (*rb).rb_parent_color = rb_color(rb) + p as usize };
}

/// `rb_set_parent_color()`: set both at once.
///
/// # Safety
/// `rb` must be valid; `p` may be null. `color` must be 0 or 1.
#[inline(always)]
unsafe fn rb_set_parent_color(rb: *mut IntervalTreeRbNode, p: *mut IntervalTreeRbNode, color: usize) {
    // SAFETY: caller guarantees `rb` is valid.
    unsafe { (*rb).rb_parent_color = p as usize + color };
}

/// `__rb_change_child()`: point `parent`'s link at `new` where it pointed
/// at `old`, or the root's link if there is no parent.
///
/// Both stores are `WRITE_ONCE()` in the C and `write_volatile` here. See
/// the module doc comment: this is the ordering GOALS.md §5 protects.
///
/// # Safety
/// `root` must be valid. `parent`, if non-null, must be valid.
#[inline(always)]
unsafe fn rb_change_child(
    old: *mut IntervalTreeRbNode,
    new: *mut IntervalTreeRbNode,
    parent: *mut IntervalTreeRbNode,
    root: *mut IntervalTreeRbRoot,
) {
    // SAFETY: caller guarantees `parent` (if non-null) and `root` are valid.
    unsafe {
        if !parent.is_null() {
            if (*parent).rb_left == old {
                ptr::addr_of_mut!((*parent).rb_left).write_volatile(new);
            } else {
                ptr::addr_of_mut!((*parent).rb_right).write_volatile(new);
            }
        } else {
            ptr::addr_of_mut!((*root).rb_node).write_volatile(new);
        }
    }
}

/// `rb_link_node()`: attach `node` under `parent` at `rb_link`.
///
/// # Safety
/// `node` and `rb_link` must be valid; `parent` may be null, which is the
/// tree-was-empty case and a valid parent value.
#[inline(always)]
unsafe fn rb_link_node(node: *mut IntervalTreeRbNode, parent: *mut IntervalTreeRbNode, rb_link: *mut *mut IntervalTreeRbNode) {
    // SAFETY: caller guarantees `node` and `rb_link` are valid.
    unsafe {
        (*node).rb_parent_color = parent as usize;
        (*node).rb_left = ptr::null_mut();
        (*node).rb_right = ptr::null_mut();
        *rb_link = node;
    }
}

// ---------------------------------------------------------------------------
// `RB_DECLARE_CALLBACKS_MAX` -- the augment callbacks.
//
// Instantiated in the C as
//     RB_DECLARE_CALLBACKS_MAX(static, interval_tree_augment,
//                              struct interval_tree_node, rb,
//                              unsigned long, __subtree_last, LAST)
// where LAST(n) is `n->last`.
// ---------------------------------------------------------------------------

/// `interval_tree_augment_compute_max()`.
///
/// Recomputes this node's `__subtree_last` as the maximum of its own
/// `last` and its two children's `__subtree_last`. Returns `true` -- only
/// when `exit` is set -- if the value was already correct, which is what
/// lets [`augment_propagate`] stop climbing early.
///
/// # Safety
/// `node` must be valid and its child links must be valid or null.
#[inline(always)]
unsafe fn augment_compute_max(node: *mut IntervalTreeNode, exit: bool) -> bool {
    // SAFETY: caller guarantees `node` and its links are valid.
    unsafe {
        let mut max = (*node).last;

        let left = (*node).rb.rb_left;
        if !left.is_null() {
            let child = left.cast::<IntervalTreeNode>();
            if (*child).subtree_last > max {
                max = (*child).subtree_last;
            }
        }

        let right = (*node).rb.rb_right;
        if !right.is_null() {
            let child = right.cast::<IntervalTreeNode>();
            if (*child).subtree_last > max {
                max = (*child).subtree_last;
            }
        }

        if exit && (*node).subtree_last == max {
            return true;
        }
        (*node).subtree_last = max;
        false
    }
}

/// `interval_tree_augment_propagate()`: recompute up the parent chain from
/// `rb` until `stop`, or until a node's value did not change.
///
/// # Safety
/// `rb` may be null (`__rb_erase_augmented` passes a null `parent` for a
/// tree that just became empty), in which case this does nothing -- the
/// C's `while (rb != stop)` with `rb == stop == NULL` behaves identically.
/// Otherwise `rb` must be valid and reachable from `stop`.
#[inline(always)]
unsafe fn augment_propagate(mut rb: *mut IntervalTreeRbNode, stop: *mut IntervalTreeRbNode) {
    // SAFETY: caller guarantees the chain from `rb` to `stop` is valid.
    unsafe {
        while rb != stop {
            let node = rb.cast::<IntervalTreeNode>();
            if augment_compute_max(node, true) {
                break;
            }
            rb = rb_parent(ptr::addr_of!((*node).rb));
        }
    }
}

/// `interval_tree_augment_copy()`: `new` takes over `old`'s subtree value.
///
/// # Safety
/// Both must be valid `rb` fields of `IntervalTreeNode`s.
#[inline(always)]
unsafe fn augment_copy(rb_old: *mut IntervalTreeRbNode, rb_new: *mut IntervalTreeRbNode) {
    // SAFETY: caller guarantees both are valid, at offset 0 of their node.
    unsafe {
        let old = rb_old.cast::<IntervalTreeNode>();
        let new = rb_new.cast::<IntervalTreeNode>();
        (*new).subtree_last = (*old).subtree_last;
    }
}

/// `interval_tree_augment_rotate()`: after a rotation, `new` inherits the
/// subtree value that `old` had, and `old` recomputes its own.
///
/// This is the one callback that stays a real function pointer: it is
/// handed to `__rb_insert_augmented()` and `__rb_erase_color()`, which are
/// out-of-line C.
///
/// # Safety
/// Both must be valid `rb` fields of `IntervalTreeNode`s. Called by
/// `lib/rbtree.c` during rebalancing.
unsafe extern "C" fn augment_rotate(rb_old: *mut IntervalTreeRbNode, rb_new: *mut IntervalTreeRbNode) {
    // SAFETY: `lib/rbtree.c` passes two nodes of the tree being rebalanced,
    // both of which are `IntervalTreeNode`s by construction of this file.
    unsafe {
        let old = rb_old.cast::<IntervalTreeNode>();
        let new = rb_new.cast::<IntervalTreeNode>();
        (*new).subtree_last = (*old).subtree_last;
        augment_compute_max(old, false);
    }
}

