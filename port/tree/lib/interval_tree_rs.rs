//! Interval trees -- the Rust behind `lib/interval_tree.c`.
//!
//! Replaces: lib/interval_tree.c
//!
//! An interval tree is an augmented red-black tree of `[start, last]`
//! closed intervals, ordered by `start`, where every node additionally
//! carries `__subtree_last` -- the largest `last` anywhere in the subtree
//! rooted at it. That one extra scalar is what turns "find an interval
//! overlapping `[start, last]`" from a full walk into an O(log n) descent,
//! because a subtree whose `__subtree_last` is below the query's `start`
//! cannot contain a match and is skipped whole.
//!
//! # Where the code being ported actually lives
//!
//! `lib/interval_tree.c` is 155 lines and roughly a third of them are the
//! span iterator. The four classic entry points -- `interval_tree_insert`,
//! `_remove`, `_iter_first`, `_iter_next` -- do not appear in that file as
//! code at all. They are generated by one macro invocation:
//!
//! ```text
//! INTERVAL_TREE_DEFINE(struct interval_tree_node, rb, unsigned long,
//!                      __subtree_last, START, LAST,, interval_tree)
//! ```
//!
//! so the source being ported is really three files:
//!
//! | file | what it contributes |
//! |---|---|
//! | `lib/interval_tree.c` | the macro invocation, and the whole span iterator |
//! | `include/linux/interval_tree_generic.h` | `INTERVAL_TREE_DEFINE` -- insert, remove, `subtree_search`, `iter_first`, `iter_next` |
//! | `include/linux/rbtree_augmented.h` | `RB_DECLARE_CALLBACKS_MAX` -- the augment callbacks; and `rb_insert_augmented_cached` / `rb_erase_augmented_cached` / `__rb_erase_augmented` |
//!
//! All three are transcribed below, in that order, with each C construct
//! named at the Rust that replaces it.
//!
//! # Calling into `lib/rbtree.c`, not reproducing it
//!
//! Exactly three of the rbtree primitives this file needs are real,
//! exported, out-of-line `lib/rbtree.c` functions:
//! `__rb_insert_augmented()`, `__rb_erase_color()` and `rb_next()`. They
//! are called through `extern "C"`, unchanged, and `lib/rbtree.c` is not
//! ported.
//!
//! **Everything else the C uses is `static inline` or
//! `static __always_inline` in a header -- text with no linkable symbol --
//! so this file reproduces it.** Measured rather than assumed: building
//! `port/pristine/lib/interval_tree.c` in the harness and running `nm -g`
//! on the object leaves exactly `__rb_erase_color`, `__rb_insert_augmented`
//! and `rb_next` undefined and nothing else. The reproduced set is
//! `rb_entry`, `rb_parent`, `rb_link_node`, `rb_insert_augmented`,
//! `rb_insert_augmented_cached`, `rb_erase_augmented`,
//! `rb_erase_augmented_cached`, `__rb_erase_augmented`,
//! `__rb_change_child`, `rb_set_parent`, `rb_set_parent_color`, `rb_color`
//! and `rb_is_black`.
//!
//! This is the same arrangement `timerqueue_rs.rs` reached for the plain
//! rbtree, one level up: `__rb_erase_augmented()` is the augmented
//! counterpart of `rb_erase()`, and it is `static __always_inline` in the
//! header precisely so the callbacks devirtualise at each call site.
//!
//! # `struct rb_augment_callbacks` becomes three direct calls, not a vtable
//!
//! The C builds a `static const struct rb_augment_callbacks
//! interval_tree_augment` holding three function pointers, and passes its
//! address to `rb_insert_augmented_cached()` and
//! `rb_erase_augmented_cached()`. Both are `__always_inline` over a
//! `const` object, so the C compiler devirtualises every call: the struct
//! exists in the source, not in the emitted code.
//!
//! Here the two callers are reproduced in this file with exactly one
//! callback set, so `propagate` and `copy` are ordinary direct calls to
//! [`augment_propagate`] and [`augment_copy`]. `rotate` is the one that
//! cannot be: `__rb_insert_augmented()` and `__rb_erase_color()` are real
//! C functions taking a `void (*)(struct rb_node *, struct rb_node *)`, so
//! [`augment_rotate`] stays a genuine `extern "C"` function pointer,
//! exactly as it is in the C.
//!
//! Nothing outside this file can observe the difference -- the callbacks
//! are `static` in the C and have no symbol -- so GOALS.md §5's three
//! questions all answer no.
//!
//! # `WRITE_ONCE` is reproduced as a volatile store, deliberately
//!
//! `__rb_change_child()` publishes a child pointer with `WRITE_ONCE()`,
//! and that is not decoration: the kernel's rbtree is walked by lockless
//! RCU readers, and GOALS.md §5 names *the order in which writes become
//! visible* as one of the three things a port may not change -- the one it
//! says will bite. Every such store below is a `write_volatile`, which is
//! what `WRITE_ONCE` compiles to. No differential test can see this, so it
//! is written down rather than measured.
//!
//! # Two places this file is deliberately as unsafe as the C
//!
//! **1. [`subtree_search`] dereferences a pointer it has not checked for
//! null.** The C does the same, at
//! `interval_tree_generic.h`'s `node = rb_entry(node->ITRB.rb_right, ...)`
//! followed by `continue`, and it is correct in both languages for the
//! same non-obvious reason: the loop invariant is
//! `start <= node->__subtree_last`, so *some* node in this subtree has
//! `last >= start`. Reaching that line means it is neither this node
//! (`start > node->last`) nor anything in the left subtree (checked
//! immediately above), so it must be in the right subtree -- which
//! therefore exists. Adding a check would be a port that is *safer than
//! the C*, which `logs/floor.md` records as Adam's ruling of 2026-09-04:
//! hold at faithful, revisit in the verification phase.
//!
//! **2. `rb_entry()` on a null pointer is reproduced as a null cast.**
//! `rb` is the first member of `struct interval_tree_node`, so
//! `container_of` subtracts zero and `rb_entry(NULL)` is `NULL` rather
//! than undefined. Every such site below is a plain `.cast()` for that
//! reason, and the offset-zero fact is asserted at compile time (the
//! `const _: () = assert!(offset_of!(...) == 0)` under the type
//! definitions) so a future field reorder cannot make the casts silently
//! wrong.
//!
//! # Where the arithmetic can wrap, and where it provably cannot
//!
//! The C's endpoints are `unsigned long`, so its `+ 1` and `- 1` wrap by
//! definition; the kernel builds this file's Rust with
//! `CONFIG_RUST_OVERFLOW_CHECKS=y`, which turns a wrap into a panic. Every
//! such site was checked individually rather than blanket-`wrapping_*`'d,
//! because a plain `+` that provably cannot overflow is a live assertion
//! and blanket wrapping throws it away:
//!
//! | site | why |
//! |---|---|
//! | `span_iter_next_gap`'s `+ 1` | the site runs, the OVERFLOW cannot: `\|\|` short-circuits on `nodes[0]->last >= cur->start`, which is true whenever `last` is `ULONG_MAX` |
//! | `span_iter_first`/`_next`'s `start - 1` | guarded by `start > first_index` / by there being a hole, so `start >= 1` |
//! | `span_iter_next`'s `last + 1` | `nodes[0]->last` is strictly below `last_index` or below `nodes[1]->start` on both paths |
//! | `interval_tree_span_iter_advance`'s `last_hole + 1` | **CAN wrap, and is spelled `wrapping_add`.** See its own comment |
//!
//! # No locking, and no allocation
//!
//! Neither is in the original. Every node is caller-owned and embedded in
//! the caller's own structure; this file allocates nothing, frees nothing
//! and takes no lock, so `logs/allocation.md`'s standing exception does
//! not arise and there is no retained C.

// `is_hole` is an `int`, and it exists only in the span iterator.
#[cfg(CONFIG_INTERVAL_TREE_SPAN_ITER)]
