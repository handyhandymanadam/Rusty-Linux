/// Mirrors `struct rb_node` (`include/linux/rbtree_types.h`).
///
/// Field order and offsets are the compiled C's own, captured by
/// `rig/kabi-pin.sh --capture` for `lib/timerqueue.c` and reused verbatim
/// here rather than re-transcribed from the header; `rig/layout-check.sh`
/// checks the claim against the built kernel's DWARF.
#[repr(C)]
pub struct IntervalTreeRbNode {
    rb_parent_color: usize,
    rb_right: *mut IntervalTreeRbNode,
    rb_left: *mut IntervalTreeRbNode,
}

/// Mirrors `struct rb_root`.
#[repr(C)]
pub struct IntervalTreeRbRoot {
    rb_node: *mut IntervalTreeRbNode,
}

/// Mirrors `struct rb_root_cached` -- an `rb_root` plus the cached
/// leftmost (lowest `start`) node, which is what makes
/// [`interval_tree_iter_first`]'s O(1) rejection test possible.
#[repr(C)]
pub struct IntervalTreeRbRootCached {
    rb_root: IntervalTreeRbRoot,
    rb_leftmost: *mut IntervalTreeRbNode,
}

/// Mirrors `struct interval_tree_node` (`include/linux/interval_tree.h`).
///
/// `rb` is at offset 0. That is not incidental: it is what makes every
/// `rb_entry()` in the C a no-op, and every `.cast()` below correct.
#[repr(C)]
pub struct IntervalTreeNode {
    rb: IntervalTreeRbNode,
    /// Start of interval.
    start: usize,
    /// Last location *in* interval -- inclusive, not one past the end.
    last: usize,
    /// The largest `last` anywhere in the subtree rooted at this node.
    subtree_last: usize,
}

// Compile-time restatement of the offset-zero fact every `.cast()` in this
// file rests on -- the thing `container_of` would otherwise have subtracted.
// A future field reorder becomes a build failure rather than a silently
// wrong cast.
const _: () = assert!(core::mem::offset_of!(IntervalTreeNode, rb) == 0);

