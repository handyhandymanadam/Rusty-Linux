/// `interval_tree_span_iter_first()`: begin an iteration over
/// `[first_index, last_index]`.
///
/// # Safety
/// `iter` and `itree` must be valid.
#[cfg(CONFIG_INTERVAL_TREE_SPAN_ITER)]
#[no_mangle]
pub unsafe extern "C" fn interval_tree_span_iter_first(
    iter: *mut IntervalTreeSpanIter,
    itree: *mut IntervalTreeRbRootCached,
    first_index: usize,
    last_index: usize,
) {
    // SAFETY: caller guarantees `iter` and `itree` are valid.
    unsafe {
        (*iter).first_index = first_index;
        (*iter).last_index = last_index;
        (*iter).nodes[0] = ptr::null_mut();
        (*iter).nodes[1] = interval_tree_iter_first(itree, first_index, last_index);
        if (*iter).nodes[1].is_null() {
            // No nodes intersect the span, whole span is hole
            (*iter).start.start_hole = first_index;
            (*iter).last.last_hole = last_index;
            (*iter).is_hole = 1;
            return;
        }
        if (*(*iter).nodes[1]).start > first_index {
            // Leading hole on first iteration
            (*iter).start.start_hole = first_index;
            (*iter).last.last_hole = (*(*iter).nodes[1]).start - 1;
            (*iter).is_hole = 1;
            span_iter_next_gap(iter);
            return;
        }

        // Starting inside a used
        (*iter).start.start_used = first_index;
        (*iter).is_hole = 0;
        span_iter_next_gap(iter);
        (*iter).last.last_used = (*(*iter).nodes[0]).last;
        if (*iter).last.last_used >= last_index {
            (*iter).last.last_used = last_index;
            (*iter).nodes[0] = ptr::null_mut();
            (*iter).nodes[1] = ptr::null_mut();
        }
    }
}

