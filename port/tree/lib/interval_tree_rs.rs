/// `interval_tree_subtree_search()`: the leftmost node in the subtree at
/// `node` whose interval intersects `[start, last]`.
///
/// # Safety
/// `node` must be valid and must satisfy the loop invariant
/// `start <= node->__subtree_last` -- i.e. the subtree is known to contain
/// a node satisfying Cond2. **This function dereferences an unchecked
/// pointer on the strength of that invariant**, exactly as the C does; see
/// the module doc comment.
unsafe fn subtree_search(
    mut node: *mut IntervalTreeNode,
    start: usize,
    last: usize,
) -> *mut IntervalTreeNode {
    // SAFETY: caller guarantees the invariant above.
    unsafe {
        loop {
            // Loop invariant: start <= node->__subtree_last
            // (Cond2 is satisfied by one of the subtree nodes)
            let left = (*node).rb.rb_left;
            if !left.is_null() {
                let left = left.cast::<IntervalTreeNode>();
                if start <= (*left).subtree_last {
                    // Some nodes in left subtree satisfy Cond2. Iterate to
                    // find the leftmost such node N. If it also satisfies
                    // Cond1, that's the match we are looking for.
                    // Otherwise, there is no matching interval as nodes to
                    // the right of N can't satisfy Cond1 either.
                    node = left;
                    continue;
                }
            }
            if (*node).start <= last {
                // Cond1
                if start <= (*node).last {
                    // Cond2 -- node is leftmost match
                    return node;
                }
                // See the module doc comment: `rb_right` is non-null here
                // by the loop invariant, and the C does not check it
                // either.
                node = (*node).rb.rb_right.cast::<IntervalTreeNode>();
                continue;
            }
            return ptr::null_mut(); // No match
        }
    }
}

