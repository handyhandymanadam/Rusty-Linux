/// `interval_tree_span_iter_next()`: advance to the next span, toggling
/// between hole and used. Sets `is_hole` to -1 when the iteration is done.
///
/// # Safety
/// `iter` must be valid and must have been initialised by
/// [`interval_tree_span_iter_first`].
#[cfg(CONFIG_INTERVAL_TREE_SPAN_ITER)]
#[no_mangle]
pub unsafe extern "C" fn interval_tree_span_iter_next(iter: *mut IntervalTreeSpanIter) {
    // SAFETY: caller guarantees `iter` is valid and initialised.
    unsafe {
        if (*iter).nodes[0].is_null() && (*iter).nodes[1].is_null() {
            (*iter).is_hole = -1;
            return;
        }

        if (*iter).is_hole != 0 {
            (*iter).start.start_used = (*iter).last.last_hole + 1;
            (*iter).last.last_used = (*(*iter).nodes[0]).last;
            if (*iter).last.last_used >= (*iter).last_index {
                (*iter).last.last_used = (*iter).last_index;
                (*iter).nodes[0] = ptr::null_mut();
                (*iter).nodes[1] = ptr::null_mut();
            }
            (*iter).is_hole = 0;
            return;
        }

        if (*iter).nodes[1].is_null() {
            // Trailing hole
            (*iter).start.start_hole = (*(*iter).nodes[0]).last + 1;
            (*iter).last.last_hole = (*iter).last_index;
            (*iter).nodes[0] = ptr::null_mut();
            (*iter).is_hole = 1;
            return;
        }

        // must have both nodes[0] and [1], interior hole
        (*iter).start.start_hole = (*(*iter).nodes[0]).last + 1;
        (*iter).last.last_hole = (*(*iter).nodes[1]).start - 1;
        (*iter).is_hole = 1;
        span_iter_next_gap(iter);
    }
}

