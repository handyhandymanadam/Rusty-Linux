/// The C's first anonymous union in `struct interval_tree_span_iter`.
///
/// Rust has no anonymous struct-embedded unions, so the two member names
/// are kept and the union is given a name. Both members are
/// `unsigned long`, so reading either after writing the other is
/// well-defined -- which the C relies on by name in
/// [`interval_tree_span_iter_advance`]: *"Rely on the union aliasing
/// hole/used"*.
#[cfg(CONFIG_INTERVAL_TREE_SPAN_ITER)]
#[repr(C)]
pub union SpanStart {
    /// Start of an interval for a hole when `is_hole == 1`.
    pub start_hole: usize,
    /// Start of a used interval when `is_hole == 0`.
    pub start_used: usize,
}

/// The C's second anonymous union. See [`SpanStart`].
#[cfg(CONFIG_INTERVAL_TREE_SPAN_ITER)]
#[repr(C)]
pub union SpanLast {
    /// Inclusive end of an interval for a hole when `is_hole == 1`.
    pub last_hole: usize,
    /// Inclusive end of a used interval when `is_hole == 0`.
    pub last_used: usize,
}

/// Mirrors `struct interval_tree_span_iter`
/// (`include/linux/interval_tree.h`).
///
/// The iterator travels over spans, classifying each as a hole (no nodes
/// intersect) or used (fully covered by nodes), toggling between the two
/// until the requested range is covered. It is greedy: consecutive and
/// adjacent nodes are consolidated into one used span.
#[cfg(CONFIG_INTERVAL_TREE_SPAN_ITER)]
#[repr(C)]
pub struct IntervalTreeSpanIter {
    /// private: `nodes[0]` is the node whose `last` ends the current used
    /// span; `nodes[1]` is the first node of the next used span, or null.
    nodes: [*mut IntervalTreeNode; 2],
    first_index: usize,
    last_index: usize,
    /// public: `start_hole` / `start_used`.
    pub start: SpanStart,
    /// public: `last_hole` / `last_used`.
    pub last: SpanLast,
    /// public: 0 == used, 1 == is_hole, -1 == done iteration.
    pub is_hole: c_int,
}

/// `interval_tree_span_iter_next_gap()`.
///
/// Roll `nodes[1]` into `nodes[0]` by advancing `nodes[1]` to the end of a
/// contiguous span of nodes. This makes `nodes[0]->last` the end of that
/// contiguous used span of indexes that started at the original
/// `nodes[1]->start`.
///
/// If there is an interior hole, `nodes[1]` is now the first node starting
/// the next used span. A hole span is between `nodes[0]->last` and
/// `nodes[1]->start`.
///
/// If there is a tailing hole, `nodes[1]` is now NULL. A hole span is
/// between `nodes[0]->last` and `last_index`.
///
/// If the contiguous used range span to `last_index`, `nodes[1]` is set to
/// NULL.
///
/// # Safety
/// `state` must be valid and `state->nodes[1]` must be non-null.
#[cfg(CONFIG_INTERVAL_TREE_SPAN_ITER)]
unsafe fn span_iter_next_gap(state: *mut IntervalTreeSpanIter) {
    // SAFETY: caller guarantees `state` is valid with a non-null nodes[1].
    unsafe {
        let mut cur = (*state).nodes[1];

        (*state).nodes[0] = cur;
        loop {
            if (*cur).last > (*(*state).nodes[0]).last {
                (*state).nodes[0] = cur;
            }
            cur = interval_tree_iter_next(cur, (*state).first_index, (*state).last_index);
            if cur.is_null() {
                break;
            }
            let n0_last = (*(*state).nodes[0]).last;
            if !(n0_last >= (*cur).start || n0_last + 1 == (*cur).start) {
                break;
            }
        }
        (*state).nodes[1] = cur;
    }
}

