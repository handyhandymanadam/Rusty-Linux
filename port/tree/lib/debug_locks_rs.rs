//! The global lock-debugging switch -- the Rust behind `lib/debug_locks.c`.
//!
//! Ported from `lib/debug_locks.c` (6.18.49), started by Ingo Molnar,
//! Copyright (C) 2006 Red Hat, Inc.
//!
//! Replaces: lib/debug_locks.c
//!
//! # Two exported variables that C code writes
//!
//! `debug_locks` is not read-only data with a helper beside it: the whole
//! point is that **anything that detects a locking bug turns it off**, and it
//! does so through `__debug_locks_off()`, a `static __always_inline` in
//! `include/linux/debug_locks.h` that is `xchg(&debug_locks, 0)`. That inline
//! lives in C, is compiled into dozens of C translation units, and writes
//! this variable directly.
//!
//! So the Rust definition must be something a C `xchg()` may operate on
//! concurrently. `AtomicI32` is: it has the size, alignment and ABI of `int`,
//! and its `swap` compiles to the same `xchg` instruction. Declaring it as a
//! plain `i32` and taking `&mut` to it would be the version that is wrong --
//! it would let LLVM assume no other writer.
//!
//! `__read_mostly` is reproduced with `#[link_section]`, because it is a
//! placement decision the C made deliberately: both variables are read on
//! every lock operation in a debug kernel and written approximately once.

use core::ffi::c_int;
use core::sync::atomic::{AtomicI32, Ordering};

extern "C" {
    /// `kernel/printk/printk.c`. Raises the console log level so the
    /// backtrace that follows is actually printed.
    fn console_verbose();
}

// The C types these contracts name -- none; both are plain `int`.
// Generated by rig/kabi-pin.sh --capture; do not hand-edit.

kernel::kabi_export! {
    debug_locks,
    license = "GPL",
    namespace = "",
    contract = "variable base_type int byte_size(4) encoding(5)",
}

/// `int debug_locks __read_mostly = 1`.
///
/// Turned off by `__debug_locks_off()` in `include/linux/debug_locks.h` the
/// first time any lock debugging facility reports a bug, so that the cascade
/// of follow-on failures does not fill the log.
#[no_mangle]
#[allow(non_upper_case_globals)]
#[link_section = ".data..read_mostly"]
pub static debug_locks: AtomicI32 = AtomicI32::new(1);

kernel::kabi_export! {
    debug_locks_silent,
    license = "GPL",
    namespace = "",
    contract = "variable base_type int byte_size(4) encoding(5)",
}

/// `int debug_locks_silent __read_mostly`.
///
/// Set by the locking self-test suite to get a silent failure: the bug is
/// still detected and still turns `debug_locks` off, but nothing reaches the
/// console.
#[no_mangle]
#[allow(non_upper_case_globals)]
#[link_section = ".data..read_mostly"]
pub static debug_locks_silent: AtomicI32 = AtomicI32::new(0);

kernel::kabi_export! {
    debug_locks_off,
    license = "GPL",
    namespace = "",
    contract = "subprogram ( ) -> base_type int byte_size(4) encoding(5)",
}

/// Body of `debug_locks_off()`: turn all lock debugging off, and say whether
/// this call was the one that did it AND the console should hear about it.
///
/// **It returns 1 only when it both won the race and is not silenced.** That
/// asymmetry is the contract callers rely on -- they print a report if and
/// only if they get 1 -- and collapsing it to "did I win the race" would give
/// the locking self-test suite the console output it exists to suppress.
///
/// `xchg` is `swap` with `SeqCst`: the C's `xchg()` is a full barrier on
/// every architecture, and on x86 both compile to `xchg`, which is
/// unconditionally locked.
#[no_mangle]
pub extern "C" fn debug_locks_off() -> c_int {
    if debug_locks.load(Ordering::Relaxed) != 0 && debug_locks.swap(0, Ordering::SeqCst) != 0 {
        if debug_locks_silent.load(Ordering::Relaxed) == 0 {
            // SAFETY: console_verbose() takes no arguments, touches only the
            // console log level, and is callable from any context -- the C
            // calls it from here for exactly this reason.
            unsafe { console_verbose() };
            return 1;
        }
    }
    0
}
