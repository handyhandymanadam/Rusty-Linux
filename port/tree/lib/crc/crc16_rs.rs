/// Body of `crc16()`. Returns the CRC of `p[..len]`, continuing from `crc`.
///
/// # Safety
/// `p` must be readable for `len` bytes. Same contract as the C.
///
/// See `include/linux/crc16.h` for the C declaration.
#[no_mangle]
pub unsafe extern "C" fn crc16(crc: u16, p: *const u8, len: usize) -> u16 {
    if len == 0 {
        return crc;
    }

    // SAFETY: the caller guarantees `len` readable bytes at `p`. The slice
    // is read-only and does not outlive this call.
    let buf = unsafe { core::slice::from_raw_parts(p, len) };
    let mut crc = crc;

    for &b in buf {
        crc = (crc >> 8) ^ TABLE[((crc & 0xff) ^ b as u16) as usize];
    }
    crc
}
