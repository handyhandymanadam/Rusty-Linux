//! CRC-16 (poly 0x8005, reflected) -- the Rust body behind `lib/crc/crc16.c`.
//!
//! Ported from `lib/crc/crc16.c` (6.18.49).
//!
//! # The table is derived, not transcribed
//!
//! The C carries 256 literal `u16`s. Copying them into Rust would be 256
//! chances to make a typo that no reviewer would ever spot, and the whole
//! point of a table this regular is that it is generated. [`build_table`]
//! is a `const fn`, so the table is computed at compile time and lands in
//! `.rodata` exactly as the C's does -- no initialiser runs at boot.
//!
//! The three GOALS.md §5 questions: nothing outside can observe how a
//! constant table got its values; no layout or interface changes; nothing
//! else has to change. All three no.
//!
//! The differential test checks all 256 entries by CRC-ing every single byte
//! against the original C table, which is read out of `port/pristine/`. A
//! generated table that disagreed anywhere would fail there, so this is not
//! taken on trust.
//!
//! Replaces: lib/crc/crc16.c

/// Reversed form of the CRC-16 polynomial `0x8005` (x^16 + x^15 + x^2 + 1).
const POLY: u16 = 0xA001;

/// Build the 256-entry table at compile time.
const fn build_table() -> [u16; 256] {
    let mut table = [0u16; 256];
    let mut i = 0;

    while i < 256 {
        let mut c = i as u16;
        let mut bit = 0;

        while bit < 8 {
            c = if c & 1 != 0 { (c >> 1) ^ POLY } else { c >> 1 };
            bit += 1;
        }
        table[i] = c;
        i += 1;
    }
    table
}

/// CRC table for the CRC-16.
static TABLE: [u16; 256] = build_table();

