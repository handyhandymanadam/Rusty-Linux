//! An integer based power function.
//!
//! Ported from `lib/math/int_pow.c` (6.18.49). Same square-and-multiply, and
//! the same wrapping semantics: the C multiplies `u64`s and lets them wrap,
//! which is the defined behaviour callers get today, so the Rust must wrap
//! too. `u64::pow` panics on overflow in a checked build and is therefore
//! **not** what this function is.
//!
//! Replaces: lib/math/int_pow.c

use core::ffi::c_uint;

// The C types these contracts name. A Rust object has
// no C type graph to resolve them against, so they are
// not duplicates of anything -- omit one and the build
// stops naming the reference it could not resolve.
// Generated by rig/kabi-migrate.py; do not hand-edit.
kernel::kabi_rule!("type_string", "t#__u64",
    "typedef_type __u64 { base_type unsigned long long byte_size(8) encoding(7) }");
kernel::kabi_rule!("type_string", "t#u64",
    "typedef_type u64 { t#__u64 }");

kernel::kabi_export! {
    int_pow,
    license = "GPL",
    namespace = "",
    contract = "subprogram ( formal_parameter t#u64 base , formal_parameter base_type unsigned int byte_size(4) encoding(7) exp ) -> t#u64",
}

/// Computes `base` raised to the power `exp`, wrapping on overflow.
///
/// See `include/linux/math.h` for the C declaration this matches.
#[no_mangle]
pub extern "C" fn int_pow(base: u64, exp: c_uint) -> u64 {
    let mut base = base;
    let mut exp = exp;
    let mut result: u64 = 1;

    while exp != 0 {
        if exp & 1 != 0 {
            result = result.wrapping_mul(base);
        }
        exp >>= 1;
        base = base.wrapping_mul(base);
    }

    result
}
