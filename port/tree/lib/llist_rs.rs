/// Body of `llist_del_first_this()`: remove `this` if it is the newest node.
///
/// Unlike [`llist_del_first`], **many callers may run this concurrently**, as
/// long as each passes a different `this` -- only one of them can match the
/// head, so only one can win.
///
/// # Safety
/// `head` and `this` must be valid.
#[no_mangle]
pub unsafe extern "C" fn llist_del_first_this(head: *mut LlistHead, this: *mut LlistNode) -> bool {
    // SAFETY: the caller guarantees a valid head. The C's comment on this
    // acquire is that it orders against the try_cmpxchg in llist_del_first().
    let first = unsafe { &*first_of(head) };
    let mut entry = first.load(Ordering::Acquire);

    loop {
        if !ptr::eq(entry, this) {
            return false;
        }
        // SAFETY: `entry == this`, which the caller guarantees is valid.
        let next = unsafe { ptr::read_volatile(ptr::addr_of!((*entry).next)) };

        match first.compare_exchange(entry, next, Ordering::SeqCst, Ordering::SeqCst) {
            Ok(_) => return true,
            Err(actual) => entry = actual,
        }
    }
}

