//! Lock-less NULL-terminated single linked list -- the Rust behind
//! `lib/llist.c`.
//!
//! Ported from `lib/llist.c` (6.18.49), Copyright 2010,2011 Intel Corp.,
//! author Huang Ying <ying.huang@intel.com>.
//!
//! Replaces: lib/llist.c
//!
//! # THE MEMORY ORDERING IS THE MODULE
//!
//! Three small functions, and two of them are a compare-and-swap loop whose
//! correctness is entirely in the ordering. **No test in this project can see
//! a mistake here.** A relaxed load where the C has an acquire produces the
//! same answers on x86-64 -- which orders loads against loads in hardware --
//! and would be a real bug on arm64 or powerpc. So the mapping is written
//! down rather than assumed:
//!
//! | C | Rust | why |
//! |---|---|---|
//! | `smp_load_acquire(&head->first)` | `load(Acquire)` | the entry read after it must not be hoisted above it |
//! | `READ_ONCE(entry->next)` | `load(Relaxed)` on the node | a single non-tearing read, no ordering of its own |
//! | `try_cmpxchg(&head->first, &entry, next)` | `compare_exchange(.., SeqCst, SeqCst)` | the kernel's `cmpxchg()` is a **full barrier**, success or failure |
//!
//! The failure ordering is `SeqCst` and not `Relaxed` deliberately: the C's
//! `try_cmpxchg()` executes `lock cmpxchg` whether or not it succeeds, so the
//! barrier is there on the failing path too, and the retry re-reads under it.
//!
//! # The one-consumer rule is upstream's, and it is not a Rust concern
//!
//! `llist_del_first()`'s comment says only one deleter may run at a time
//! against any number of adders, because otherwise ABA on `head->first` is
//! reachable. Rust's type system does not express that and this port does not
//! try to: the constraint is on the caller, it is documented on the C, and
//! inventing a lock here would change the data structure.

use core::ptr;
use core::sync::atomic::{AtomicPtr, Ordering};

/// Mirrors `struct llist_node` (`include/linux/llist.h`).
#[repr(C)]
pub struct LlistNode {
    /// The next node, or null.
    pub next: *mut LlistNode,
}

/// Mirrors `struct llist_head` (`include/linux/llist.h`).
#[repr(C)]
pub struct LlistHead {
    /// The newest node, or null.
    pub first: *mut LlistNode,
}

/// `&head->first` as the atomic it is operated on as.
///
/// # Safety
/// `head` must be a valid `llist_head`.
#[inline]
unsafe fn first_of(head: *mut LlistHead) -> *const AtomicPtr<LlistNode> {
    // SAFETY: AtomicPtr<T> has the size, alignment and representation of
    // *mut T, so a pointer to the field is a pointer to the atomic. This is
    // the same aliasing the C relies on when it applies cmpxchg() to a plain
    // `struct llist_node *`.
    unsafe { ptr::addr_of!((*head).first) as *const AtomicPtr<LlistNode> }
}

// The C types these contracts name. A Rust object has no C type graph to
// resolve them against, so they are not duplicates of anything.
// Generated by rig/kabi-pin.sh --capture; do not hand-edit.
kernel::kabi_rule!("type_string", "s#llist_head",
    "structure_type llist_head { member pointer_type { s#llist_node } first data_member_location(0) } byte_size(8)");
kernel::kabi_rule!("type_string", "s#llist_node",
    "structure_type llist_node { member pointer_type { s#llist_node } next data_member_location(0) } byte_size(8)");
kernel::kabi_rule!("type_string", "t#bool",
    "typedef_type bool { base_type _Bool byte_size(1) encoding(2) }");

