/// Body of `llist_del_first()`: remove and return the newest node, or null.
///
/// # Safety
/// `head` must be a valid `llist_head`, and **at most one caller may be
/// deleting from it at a time** -- see the module documentation. Any number
/// of concurrent `llist_add()`s are fine.
#[no_mangle]
pub unsafe extern "C" fn llist_del_first(head: *mut LlistHead) -> *mut LlistNode {
    // SAFETY: the caller guarantees a valid head.
    let first = unsafe { &*first_of(head) };
    let mut entry = first.load(Ordering::Acquire);

    loop {
        if entry.is_null() {
            return ptr::null_mut();
        }
        // SAFETY: `entry` is a node this list owns, published by an
        // llist_add() whose release pairs with the acquire above.
        let next = unsafe { ptr::read_volatile(ptr::addr_of!((*entry).next)) };

        match first.compare_exchange(entry, next, Ordering::SeqCst, Ordering::SeqCst) {
            Ok(_) => return entry,
            Err(actual) => entry = actual,
        }
    }
}

