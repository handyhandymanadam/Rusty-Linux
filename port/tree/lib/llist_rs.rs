/// Body of `llist_reverse_order()`: reverse a chain that has already been
/// detached, returning the new head.
///
/// **No atomics here, and that is not an oversight.** The chain this is
/// handed came out of `llist_del_all()`, so it is private to the caller;
/// upstream uses plain loads and stores for the same reason.
///
/// # Safety
/// `head` must be null or a valid, NULL-terminated chain that no other CPU
/// can reach.
#[no_mangle]
pub unsafe extern "C" fn llist_reverse_order(head: *mut LlistNode) -> *mut LlistNode {
    let mut head = head;
    let mut new_head: *mut LlistNode = ptr::null_mut();

    while !head.is_null() {
        let tmp = head;
        // SAFETY: the caller guarantees a valid, NULL-terminated chain that
        // nothing else is touching.
        unsafe {
            head = (*tmp).next;
            (*tmp).next = new_head;
        }
        new_head = tmp;
    }
    new_head
}
