/// Body of `minmax_running_max()`.
///
/// # Safety
/// `m` must be non-null and point at an initialised [`Minmax`]. Same
/// contract as the C.
///
/// See `include/linux/win_minmax.h` for the C declaration.
#[no_mangle]
pub unsafe extern "C" fn minmax_running_max(
    m: *mut Minmax,
    win: u32,
    t: u32,
    meas: u32,
) -> u32 {
    // SAFETY: the caller guarantees `m` is a valid, initialised, uniquely
    // borrowed `struct minmax` for the duration of this call.
    running(unsafe { &mut *m }, win, t, meas, |a, b| a >= b)
}

