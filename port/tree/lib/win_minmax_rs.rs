/// Body of `minmax_running_min()`.
///
/// # Safety
/// `m` must be non-null and point at an initialised [`Minmax`]. Same
/// contract as the C.
///
/// See `include/linux/win_minmax.h` for the C declaration.
#[no_mangle]
pub unsafe extern "C" fn minmax_running_min(
    m: *mut Minmax,
    win: u32,
    t: u32,
    meas: u32,
) -> u32 {
    // SAFETY: as above.
    running(unsafe { &mut *m }, win, t, meas, |a, b| a <= b)
}
