//! Windowed min/max tracker -- the Rust bodies behind `lib/win_minmax.c`.
//!
//! Ported from `lib/win_minmax.c` (6.18.49). Kathleen Nichols' algorithm for
//! tracking the minimum (or maximum) of a data stream over a fixed time
//! window in constant space and constant time. It keeps the best, 2nd best
//! and 3rd best, maintaining the invariant that the n'th best was measured
//! no earlier than the (n-1)'th, and keeping the three widely separated in
//! the window so the worst-case error is bounded when the data rises
//! monotonically.
//!
//! # Layout is the caller's
//!
//! `struct minmax` is embedded in callers' structures — `tcp_sock` among
//! them — and read through `minmax_get()`, a `static inline` in
//! `include/linux/win_minmax.h`. GOALS.md §5 puts it out of bounds: the
//! `#[repr(C)]` mirrors below match that header field for field.
//!
//! # One body, not two
//!
//! The C's `minmax_running_max` and `minmax_running_min` are the same
//! forty lines with `>=` and `<=` swapped. Here they are one generic
//! function instantiated twice. Rust monomorphises, so each entry point
//! still compiles to its own straight-line code with the comparison
//! inlined — the duplication goes away without a branch replacing it.
//!
//! All three §5 questions are no: the values, the writes and their order are
//! identical, nothing's layout moves, and no caller changes.
//!
//! Replaces: lib/win_minmax.c

/// Mirrors `struct minmax_sample` in `include/linux/win_minmax.h`.
#[repr(C)]
#[derive(Clone, Copy)]
pub struct MinmaxSample {
    /// Time the measurement was taken.
    pub t: u32,
    /// Value measured.
    pub v: u32,
}

/// Mirrors `struct minmax` in `include/linux/win_minmax.h`.
#[repr(C)]
pub struct Minmax {
    /// Best, second best and third best samples.
    pub s: [MinmaxSample; 3],
}

/// `minmax_reset()` from `include/linux/win_minmax.h`, which is a
/// `static inline` there and so has to be written out here.
#[inline]
fn reset(m: &mut Minmax, t: u32, meas: u32) -> u32 {
    let val = MinmaxSample { t, v: meas };

    m.s[2] = val;
    m.s[1] = val;
    m.s[0] = val;
    m.s[0].v
}

/// As time advances, update the 1st, 2nd and 3rd choices.
fn subwin_update(m: &mut Minmax, win: u32, val: &MinmaxSample) -> u32 {
    // Wrapping, like the C: these are timestamps and the difference is
    // meant to wrap. `val.t - m.s[0].t` on u32 in C is modular arithmetic,
    // and the kernel builds Rust with overflow checks on, so a plain `-`
    // here would panic the moment the clock wrapped.
    let dt = val.t.wrapping_sub(m.s[0].t);

    if dt > win {
        // A whole window with no new value: promote 2nd to 1st and 3rd to
        // 2nd. This may need doing twice, since the 2nd choice may also
        // have fallen out of the window -- on entry only the 3rd was known
        // to be inside it.
        m.s[0] = m.s[1];
        m.s[1] = m.s[2];
        m.s[2] = *val;
        if val.t.wrapping_sub(m.s[0].t) > win {
            m.s[0] = m.s[1];
            m.s[1] = m.s[2];
            m.s[2] = *val;
        }
    } else if m.s[1].t == m.s[0].t && dt > win / 4 {
        // A quarter of the window with no new value: take a 2nd choice
        // from the 2nd quarter.
        m.s[1] = *val;
        m.s[2] = *val;
    } else if m.s[2].t == m.s[1].t && dt > win / 2 {
        // Half the window with no new value: take a 3rd choice from the
        // second half.
        m.s[2] = *val;
    }
    m.s[0].v
}

/// The shared body. `better(a, b)` is true when `a` should displace `b`.
#[inline]
fn running<F: Fn(u32, u32) -> bool>(
    m: &mut Minmax,
    win: u32,
    t: u32,
    meas: u32,
    better: F,
) -> u32 {
    let val = MinmaxSample { t, v: meas };

    // A new best, or nothing left in the window: forget everything earlier.
    // The new best is better than the whole window by definition and is the
    // most recent, so there is nothing to keep.
    if better(val.v, m.s[0].v) || val.t.wrapping_sub(m.s[2].t) > win {
        return reset(m, t, meas);
    }

    if better(val.v, m.s[1].v) {
        m.s[1] = val;
        m.s[2] = val;
    } else if better(val.v, m.s[2].v) {
        m.s[2] = val;
    }

    subwin_update(m, win, &val)
}

// The C types these contracts name. A Rust object has
// no C type graph to resolve them against, so they are
// not duplicates of anything -- omit one and the build
// stops naming the reference it could not resolve.
// Generated by rig/kabi-migrate.py; do not hand-edit.
kernel::kabi_rule!("type_string", "s#minmax",
    "structure_type minmax { member array_type[3] { s#minmax_sample } s data_member_location(0) } byte_size(24)");
kernel::kabi_rule!("type_string", "s#minmax_sample",
    "structure_type minmax_sample { member t#u32 t data_member_location(0) , member t#u32 v data_member_location(4) } byte_size(8)");
kernel::kabi_rule!("type_string", "t#__u32",
    "typedef_type __u32 { base_type unsigned int byte_size(4) encoding(7) }");
kernel::kabi_rule!("type_string", "t#u32",
    "typedef_type u32 { t#__u32 }");

