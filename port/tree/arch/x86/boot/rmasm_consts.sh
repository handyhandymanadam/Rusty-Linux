# rmasm_consts.sh ZOFFSET.H VOFFSET.H -- print the Rust `const`s header_rs.rs needs from the two generated headers
# (zoffset.h: `#define ZO_<sym> 0x<addr>` from the compressed stub, voffset.h: `#define VO_<sym> _AC(0x<addr>,UL)`).
# A symbol the configuration does not have (efi_pe_entry without EFI_STUB, _sbat without EFI_SBAT, ...) is emitted as
# the sentinel ABSENT, which header_rs.rs asserts against wherever the configuration needs the symbol.
# RUSTY-LINUX REALMODE-ASM (Phase C2). One implementation, used by arch/x86/boot/Makefile and rig/rmasm/check.sh.
zo=$1; vo=$2
echo '// generated by rmasm_consts.sh from zoffset.h / voffset.h; do not edit'
echo 'pub const ABSENT: u64 = 0xdead_beef_dead_beef;'
for n in _data _edata _ehead _end input_data kernel_info startup_32 efi_pe_entry efi32_pe_entry \
         efi32_stub_entry efi64_stub_entry _sbat _esbat z_input_len z_output_len; do
	v=$(sed -n "s/^#define ZO_$n \(0x[0-9a-fA-F]*\)\$/\1/p" "$zo")
	[ "$(printf '%s\n' "$v" | grep -c .)" -le 1 ] || { echo "rmasm_consts.sh: ZO_$n defined twice" >&2; exit 1; }
	echo "pub const ZO_$n: u64 = ${v:-ABSENT};"
done
for n in _end _text; do
	v=$(sed -n "s/^#define VO_$n _AC(\(0x[0-9a-fA-F]*\),UL)\$/\1/p" "$vo")
	[ -n "$v" ] || { echo "rmasm_consts.sh: VO_$n missing in $vo" >&2; exit 1; }
	echo "pub const VO_$n: u64 = $v;"
done
