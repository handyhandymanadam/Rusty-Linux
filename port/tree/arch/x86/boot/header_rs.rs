const fn parse_num(s: &str) -> u64 {
    let b = s.as_bytes();
    assert!(!b.is_empty()); // an unset/empty build value must not become 0 silently
    let (mut i, mut n, mut base) = (0, 0u64, 10u64);
    if b.len() > 2 && b[0] == b'0' && (b[1] == b'x' || b[1] == b'X') {
        i = 2;
        base = 16;
    }
    while i < b.len() {
        let c = b[i];
        let d = if c >= b'0' && c <= b'9' {
            c - b'0'
        } else if c >= b'a' && c <= b'f' {
            c - b'a' + 10
        } else {
            assert!(c >= b'A' && c <= b'F');
            c - b'A' + 10
        };
        assert!((d as u64) < base);
        n = n * base + d as u64;
        i += 1;
    }
    n
}

/// `-DSVGA_MODE=<NORMAL_VGA|EXTENDED_VGA|ASK_VGA|number>` of arch/x86/boot/Makefile (`SVGA_MODE :=`); header.S defaults to ASK_VGA.
const fn svga_mode(s: &str) -> u64 {
    let b = s.as_bytes();
    if b.is_empty() {
        return ASK_VGA;
    }
    if eq(b, b"NORMAL_VGA") {
        NORMAL_VGA
    } else if eq(b, b"EXTENDED_VGA") {
        EXTENDED_VGA
    } else if eq(b, b"ASK_VGA") {
        ASK_VGA
    } else {
        parse_num(s)
    }
}
const fn eq(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    let mut i = 0;
    while i < a.len() {
        if a[i] != b[i] {
            return false;
        }
        i += 1;
    }
    true
}

