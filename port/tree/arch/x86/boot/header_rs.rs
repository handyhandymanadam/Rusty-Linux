//! Rust replacement for arch/x86/boot/header.S (RMASM, Phase C2): the bzImage's real-mode header. Everything the
//! boot loaders and the setup linker script consume: the MS-DOS/PE header of the EFI stub (`.bstext`, CONFIG_EFI_STUB),
//! the setup header `hdr` at 0x1f1 .. (section `.header`), `_start` at 0x200, `start_of_setup`/`die` in `.entrytext`,
//! the `No setup signature found` string in `.initdata`, plus the symbols setup.ld and the C setup code use
//! (`sentinel`, `hdr`, `_start`, `realmode_swtch`, `die`, `pecompat_fstart` ...).
//! 16-bit (`.code16`) `global_asm!`; the text is the .S verbatim (AT&T, comments kept). Mechanical expansions only:
//!   * `#ifdef CONFIG_*` / `#else` / `#endif` -> `.if {CONFIG_*}` / `.else` / `.endif`, the operand 1 or 0 from the
//!     `--cfg` flags the Makefile derives from the .config (the text keeps the .S's order); `#ifndef CONFIG_X86_32` -> `.if ... == 0`;
//!   * backslash-continued lines joined (the assembler has no cpp line splicing);
//!   * header constants (linux/pe.h, asm/bootparam.h, asm/boot.h, boot.h, uapi/asm/boot.h) are `const` operands, each
//!     checked against the headers by rig/rmasm/consts.sh (consts_check.py); `ROOT_RDONLY` and the SVGA_MODE default are cpp
//!     `#ifndef` defaults (SVGA_MODE comes from the Makefile's `-DSVGA_MODE=...` as env RMASM_SVGA_MODE);
//!   * ZO_* (zoffset.h) and VO_* (voffset.h) are produced by rmasm_consts.sh (same sed for the Makefile and the rig); the
//!     cpp arithmetic on them (`ZO_z_extra_bytes` .. `INIT_SIZE`) is the `const fn`s below, in the same order and with the
//!     same operators; `xloadflags` (`XLF0..XLF56`) likewise; the `__handover_offset` macro's `#ifdef`s are `.if`s inside it.
//! The object is the contract: rig/rmasm/check.sh compares it with the .S object (sections, `llvm-objdump -D -r`
//! -M i8086 and default, symbols, relocations, bytes) over config variants; setup.elf, setup.bin and bzImage are byte-identical
//! with `boot_rmasm_rust=`. A wrong byte here is an unbootable image, which is why nothing is trusted but that comparison.
//! TEST-GAP: (1) Boot loaders other than QEMU `-kernel` (GRUB, syslinux, kexec-tools, EFI firmware reading the PE header):
//! the PE/COFF arms (`.bstext`, `.compat`, `.sbat`) are checked by object identity only; the OVMF boot of build-efi reads
//! the PE header (so that arm is exercised once), the `.compat` (EFI_MIXED) and `.sbat` (EFI_SBAT) arms are not wired
//! (they keep header.S, like boot_rust_ok) and are object-compared only. (2) CONFIG_X86_32 arms: not wired (the Makefile
//! enables this file only for CONFIG_X86_64); object-compared in two `x86_32` variants (the .S is assembled with CONFIG_X86_32 forced on),
//! which also pins `MIN_KERNEL_ALIGN_LG2 = 12 + 1` for 32-bit; no 32-bit kernel is built or booted anywhere here. (3) The 'setup too big'
//! and 'init sections too big' limits are setup.ld assertions, unchanged. (4) tools/build.c no longer exists in 6.18: the
//! image is `dd + cat` (arch/x86/boot/Makefile cmd_image), so the field consumers are setup.ld and the boot loader.
// C-HEADERS: linux/pe.h asm/segment.h asm/boot.h asm/page_types.h asm/setup.h asm/bootparam.h "boot.h"

