/// Mirrors `struct insn_field` (little-endian arm): `value` aliases `bytes[4]`.
#[repr(C)]
#[derive(Clone, Copy)]
pub struct InsnField {
    value: i32,
    got: u8,
    nbytes: u8,
}

impl InsnField {
    #[inline(always)]
    fn byte(&self, i: usize) -> u8 {
        ((self.value as u32) >> (8 * i)) as u8
    }
    /// `insn_set_byte()`.
    #[inline(always)]
    fn set_byte(&mut self, i: usize, v: u8) {
        let sh = 8 * i as u32;
        self.value = (((self.value as u32) & !(0xffu32 << sh)) | ((v as u32) << sh)) as i32;
    }
    /// `insn_field_set()`.
    #[inline(always)]
    fn set(&mut self, v: i32, n: u8) {
        self.value = v;
        self.nbytes = n;
    }
}

/// Mirrors `struct insn`.
#[repr(C)]
pub struct Insn {
    prefixes: InsnField,
    rex_prefix: InsnField,
    /// `vex_prefix` / `xop_prefix` (same storage).
    vex_prefix: InsnField,
    opcode: InsnField,
    modrm: InsnField,
    sib: InsnField,
    displacement: InsnField,
    /// `immediate` / `moffset1` / `immediate1`.
    immediate1: InsnField,
    /// `moffset2` / `immediate2`.
    immediate2: InsnField,
    emulate_prefix_size: c_int,
    attr: InsnAttr,
    opnd_bytes: u8,
    addr_bytes: u8,
    length: u8,
    x86_64: u8,
    kaddr: *const u8,
    end_kaddr: *const u8,
    next_byte: *const u8,
}

