// ---- arch/x86/lib/inat.c --------------------------------------------------

/// `table[i][j]` of a `[[*const InsnAttr; 4]; N]` generated table, unchecked like the C
/// (the callers keep `j` <= 3; a bounds-check panic path has no place in a decoder).
#[inline(always)]
unsafe fn tab4<const N: usize>(t: &[[*const InsnAttr; 4]; N], i: usize, j: usize) -> *const InsnAttr {
    unsafe { *(t.as_ptr() as *const *const InsnAttr).add(i * 4 + j) }
}

/// `inat_get_opcode_attribute()`.
#[no_mangle]
pub extern "C" fn inat_get_opcode_attribute(opcode: u8) -> InsnAttr {
    unsafe { inat_primary_table[opcode as usize] }
}

/// `inat_get_last_prefix_id()`.
#[no_mangle]
pub extern "C" fn inat_get_last_prefix_id(last_pfx: u8) -> c_int {
    inat_last_prefix_id(inat_get_opcode_attribute(last_pfx))
}

/// `inat_get_escape_attribute()`.
#[no_mangle]
pub extern "C" fn inat_get_escape_attribute(opcode: u8, lpfx_id: c_int, esc_attr: InsnAttr) -> InsnAttr {
    let n = inat_escape_id(esc_attr);
    unsafe {
        let mut table = tab4(&inat_escape_tables, n, 0);
        if table.is_null() {
            return 0;
        }
        if inat_has_variant(*table.add(opcode as usize)) && lpfx_id != 0 {
            table = tab4(&inat_escape_tables, n, lpfx_id as usize);
            if table.is_null() {
                return 0;
            }
        }
        *table.add(opcode as usize)
    }
}

/// `inat_get_group_attribute()`.
#[no_mangle]
pub extern "C" fn inat_get_group_attribute(modrm: u8, lpfx_id: c_int, grp_attr: InsnAttr) -> InsnAttr {
    let n = inat_group_id(grp_attr);
    let reg = ((modrm & 0x38) >> 3) as usize;
    unsafe {
        let mut table = tab4(&inat_group_tables, n, 0);
        if table.is_null() {
            return inat_group_common_attribute(grp_attr);
        }
        if inat_has_variant(*table.add(reg)) && lpfx_id != 0 {
            table = tab4(&inat_group_tables, n, lpfx_id as usize);
            if table.is_null() {
                return inat_group_common_attribute(grp_attr);
            }
        }
        *table.add(reg) | inat_group_common_attribute(grp_attr)
    }
}

/// `inat_get_avx_attribute()`.
#[no_mangle]
pub extern "C" fn inat_get_avx_attribute(opcode: u8, vex_m: u8, vex_p: u8) -> InsnAttr {
    if vex_m > X86_VEX_M_MAX || vex_p as u32 > INAT_LSTPFX_MAX {
        return 0;
    }
    unsafe {
        /* At first, this checks the master table */
        let mut table = tab4(&inat_avx_tables, vex_m as usize, 0);
        if table.is_null() {
            return 0;
        }
        if !inat_is_group(*table.add(opcode as usize)) && vex_p != 0 {
            /* If this is not a group, get attribute directly */
            table = tab4(&inat_avx_tables, vex_m as usize, vex_p as usize);
            if table.is_null() {
                return 0;
            }
        }
        *table.add(opcode as usize)
    }
}

/// `inat_get_xop_attribute()`.
#[no_mangle]
pub extern "C" fn inat_get_xop_attribute(opcode: u8, map_select: u8) -> InsnAttr {
    if map_select < X86_XOP_M_MIN || map_select > X86_XOP_M_MAX {
        return 0;
    }
    let map_select = map_select - X86_XOP_M_MIN;
    unsafe {
        /* At first, this checks the master table */
        let table = inat_xop_tables[map_select as usize];
        if table.is_null() {
            return 0;
        }
        *table.add(opcode as usize)
    }
}

