#[inline(always)]
fn x86_modrm_mod(m: u8) -> u8 {
    (m & 0xc0) >> 6
}
#[inline(always)]
fn x86_modrm_reg(m: u8) -> u8 {
    (m & 0x38) >> 3
}
#[inline(always)]
fn x86_modrm_rm(m: u8) -> u8 {
    m & 0x07
}
#[inline(always)]
fn x86_sib_base(s: u8) -> u8 {
    s & 0x07
}

impl Insn {
    /// `insn_is_rex2()`.
    #[inline(always)]
    unsafe fn is_rex2(&mut self) -> bool {
        if self.prefixes.got == 0 {
            unsafe { insn_get_prefixes(self) };
        }
        self.rex_prefix.nbytes == 2
    }
    /// `insn_rex2_m_bit()`: `X86_REX2_M(rex_prefix.bytes[1])`.
    #[inline(always)]
    fn rex2_m_bit(&self) -> u8 {
        self.rex_prefix.byte(1) & 0x80
    }
    /// `insn_is_avx_or_xop()`.
    #[inline(always)]
    unsafe fn is_avx_or_xop(&mut self) -> bool {
        if self.prefixes.got == 0 {
            unsafe { insn_get_prefixes(self) };
        }
        self.vex_prefix.value != 0
    }
    /// `insn_is_evex()`.
    #[inline(always)]
    fn is_evex(&mut self) -> bool {
        if self.prefixes.got == 0 {
            unsafe { insn_get_prefixes(self) };
        }
        self.vex_prefix.nbytes == 4
    }
    /// `avx_insn_is_xop()`.
    #[inline(always)]
    fn avx_insn_is_xop(&self) -> bool {
        inat_is_xop_prefix(inat_get_opcode_attribute(self.vex_prefix.byte(0)))
    }
    /// `insn_vex_m_bits()`.
    #[inline(always)]
    fn vex_m_bits(&self) -> u8 {
        if self.vex_prefix.nbytes == 2 {
            1 /* X86_VEX2_M */
        } else if self.vex_prefix.nbytes == 3 {
            self.vex_prefix.byte(1) & 0x1f /* X86_VEX3_M */
        } else {
            self.vex_prefix.byte(1) & 0x07 /* X86_EVEX_M */
        }
    }
    /// `insn_vex_p_bits()`.
    #[inline(always)]
    fn vex_p_bits(&self) -> u8 {
        if self.vex_prefix.nbytes == 2 {
            self.vex_prefix.byte(1) & 0x03
        } else {
            self.vex_prefix.byte(2) & 0x03
        }
    }
    /// `insn_vex_w_bit()`.
    #[inline(always)]
    fn vex_w_bit(&self) -> u8 {
        if self.vex_prefix.nbytes < 3 {
            return 0;
        }
        self.vex_prefix.byte(2) & 0x80
    }
    /// `insn_xop_map_bits()`.
    #[inline(always)]
    fn xop_map_bits(&self) -> u8 {
        if self.vex_prefix.nbytes < 3 {
            return 0;
        }
        self.vex_prefix.byte(1) & 0x1f
    }
    /// `insn_xop_p_bits()`.
    #[inline(always)]
    fn xop_p_bits(&self) -> u8 {
        self.vex_prefix.byte(2) & 0x03
    }
    /// `insn_last_prefix_id()`.
    #[inline(always)]
    unsafe fn last_prefix_id(&mut self) -> c_int {
        if unsafe { self.is_avx_or_xop() } {
            if self.avx_insn_is_xop() {
                return self.xop_p_bits() as c_int;
            }
            return self.vex_p_bits() as c_int;
        }
        if self.prefixes.byte(3) != 0 {
            return inat_get_last_prefix_id(self.prefixes.byte(3));
        }
        0
    }

    // ---- the get_next()/peek_*() macros of insn.c ----

    /// `validate_next(t, insn, n)`.
    #[inline(always)]
    fn validate(&self, size: usize, n: usize) -> bool {
        (self.next_byte as usize).wrapping_add(size + n) <= self.end_kaddr as usize
    }
    /// `peek_nbyte_next(insn_byte_t, insn, n)`.
    #[inline(always)]
    unsafe fn peek(&self, n: usize) -> Option<u8> {
        if !self.validate(1, n) {
            return None;
        }
        Some(unsafe { *self.next_byte.add(n) })
    }
    /// `get_next(t, insn)` for an `N`-byte little-endian value.
    #[inline(always)]
    unsafe fn get_bytes<const N: usize>(&mut self) -> Option<u32> {
        if !self.validate(N, 0) {
            return None;
        }
        let mut v: u32 = 0;
        for i in 0..N {
            v |= (unsafe { *self.next_byte.add(i) } as u32) << (8 * i);
        }
        self.next_byte = self.next_byte.wrapping_add(N);
        Some(v)
    }
    /// `get_next(insn_byte_t, ...)` / `unsigned char`.
    #[inline(always)]
    unsafe fn get_u8(&mut self) -> Option<u8> {
        unsafe { self.get_bytes::<1>() }.map(|v| v as u8)
    }
    /// `get_next(signed char, ...)`, sign-extended to `insn_value_t`.
    #[inline(always)]
    unsafe fn get_i8(&mut self) -> Option<i32> {
        unsafe { self.get_bytes::<1>() }.map(|v| v as u8 as i8 as i32)
    }
    /// `get_next(short, ...)`.
    #[inline(always)]
    unsafe fn get_i16(&mut self) -> Option<i32> {
        unsafe { self.get_bytes::<2>() }.map(|v| v as u16 as i16 as i32)
    }
    /// `get_next(unsigned short, ...)`.
    #[inline(always)]
    unsafe fn get_u16(&mut self) -> Option<i32> {
        unsafe { self.get_bytes::<2>() }.map(|v| v as u16 as i32)
    }
    /// `get_next(int, ...)`.
    #[inline(always)]
    unsafe fn get_i32(&mut self) -> Option<i32> {
        unsafe { self.get_bytes::<4>() }.map(|v| v as i32)
    }
}

/// Evaluate an `Option`; on `None` do the C `goto err_out; return -ENODATA`.
macro_rules! need {
    ($e:expr) => {
        match $e {
            Some(v) => v,
            None => return -ENODATA,
        }
    };
}

