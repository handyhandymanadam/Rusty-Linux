/// `insn_init()`: initialize `struct insn`.
///
/// # Safety
/// `insn` writable; `kaddr` readable for `buf_len` bytes (clamped to 15).
#[no_mangle]
pub unsafe extern "C" fn insn_init(insn: *mut Insn, kaddr: *const c_void, buf_len: c_int, x86_64: c_int) {
    let mut buf_len = buf_len;
    /*
     * Instructions longer than MAX_INSN_SIZE (15 bytes) are invalid
     * even if the input buffer is long enough to hold them.
     */
    if buf_len > MAX_INSN_SIZE {
        buf_len = MAX_INSN_SIZE;
    }

    unsafe { core::ptr::write_bytes(insn as *mut u8, 0, core::mem::size_of::<Insn>()) };
    let insn = unsafe { &mut *insn };
    let kaddr = kaddr as *const u8;
    insn.kaddr = kaddr;
    insn.end_kaddr = kaddr.wrapping_offset(buf_len as isize);
    insn.next_byte = kaddr;
    insn.x86_64 = x86_64 as u8;
    insn.opnd_bytes = 4;
    if x86_64 != 0 {
        insn.addr_bytes = 8;
    } else {
        insn.addr_bytes = 4;
    }
}

/// `__insn_get_emulate_prefix()`: 1 if the prefix matched (and was consumed).
unsafe fn __insn_get_emulate_prefix(insn: &mut Insn, prefix: &[u8; 5]) -> bool {
    for i in 0..prefix.len() {
        match unsafe { insn.peek(i) } {
            Some(b) if b == prefix[i] => {}
            _ => return false,
        }
    }

    insn.emulate_prefix_size = prefix.len() as c_int;
    insn.next_byte = insn.next_byte.wrapping_add(prefix.len());

    true
}

unsafe fn insn_get_emulate_prefix(insn: &mut Insn) {
    if unsafe { __insn_get_emulate_prefix(insn, &XEN_PREFIX) } {
        return;
    }

    unsafe { __insn_get_emulate_prefix(insn, &KVM_PREFIX) };
}

/// `insn_get_prefixes()`: scan x86 instruction prefix bytes.
///
/// # Safety
/// `insn` must have been initialised by `insn_init()`.
#[no_mangle]
pub unsafe extern "C" fn insn_get_prefixes(insn: *mut Insn) -> c_int {
    let insn = unsafe { &mut *insn };

    if insn.prefixes.got != 0 {
        return 0;
    }

    unsafe { insn_get_emulate_prefix(insn) };

    let mut nb: usize = 0;
    let mut lb: u8 = 0;
    let mut b = need!(unsafe { insn.peek(0) });
    let mut attr = inat_get_opcode_attribute(b);
    while inat_is_legacy_prefix(attr) {
        /* Skip if same prefix */
        let mut dup = false;
        for i in 0..nb {
            if insn.prefixes.byte(i) == b {
                dup = true;
                break;
            }
        }
        if !dup {
            if nb == 4 {
                /* Invalid instruction */
                break;
            }
            insn.prefixes.set_byte(nb, b);
            nb += 1;
            if inat_is_address_size_prefix(attr) {
                /* address size switches 2/4 or 4/8 */
                if insn.x86_64 != 0 {
                    insn.addr_bytes ^= 12;
                } else {
                    insn.addr_bytes ^= 6;
                }
            } else if inat_is_operand_size_prefix(attr) {
                /* oprand size switches 2/4 */
                insn.opnd_bytes ^= 6;
            }
        }
        insn.prefixes.nbytes = insn.prefixes.nbytes.wrapping_add(1);
        insn.next_byte = insn.next_byte.wrapping_add(1);
        lb = b;
        b = need!(unsafe { insn.peek(0) });
        attr = inat_get_opcode_attribute(b);
    }
    /* Set the last prefix */
    if lb != 0 && lb != insn.prefixes.byte(3) {
        if insn.prefixes.byte(3) != 0 {
            /* Swap the last prefix */
            b = insn.prefixes.byte(3);
            for i in 0..nb {
                if insn.prefixes.byte(i) == lb {
                    insn.prefixes.set_byte(i, b);
                }
            }
        }
        insn.prefixes.set_byte(3, lb);
    }

    'vex_end: {
        /* Decode REX prefix */
        if insn.x86_64 != 0 {
            b = need!(unsafe { insn.peek(0) });
            attr = inat_get_opcode_attribute(b);
            if inat_is_rex_prefix(attr) {
                insn.rex_prefix.set(b as i32, 1);
                insn.next_byte = insn.next_byte.wrapping_add(1);
                if b & 8 != 0 {
                    /* REX.W overrides opnd_size */
                    insn.opnd_bytes = 8;
                }
            } else if inat_is_rex2_prefix(attr) {
                insn.rex_prefix.set_byte(0, b);
                b = need!(unsafe { insn.peek(1) });
                insn.rex_prefix.set_byte(1, b);
                insn.rex_prefix.nbytes = 2;
                insn.next_byte = insn.next_byte.wrapping_add(2);
                if b & 8 != 0 {
                    /* REX.W overrides opnd_size */
                    insn.opnd_bytes = 8;
                }
                insn.rex_prefix.got = 1;
                break 'vex_end;
            }
        }
        insn.rex_prefix.got = 1;

        /* Decode VEX/XOP prefix */
        b = need!(unsafe { insn.peek(0) });
        if inat_is_vex_prefix(attr) || inat_is_xop_prefix(attr) {
            let mut b2 = need!(unsafe { insn.peek(1) });

            if inat_is_xop_prefix(attr) && x86_modrm_reg(b2) == 0 {
                /* Grp1A.0 is always POP Ev */
                break 'vex_end;
            } else if insn.x86_64 == 0 {
                /*
                 * In 32-bits mode, if the [7:6] bits (mod bits of
                 * ModRM) on the second byte are not 11b, it is
                 * LDS or LES or BOUND.
                 */
                if x86_modrm_mod(b2) != 3 {
                    break 'vex_end;
                }
            }
            insn.vex_prefix.set_byte(0, b);
            insn.vex_prefix.set_byte(1, b2);
            if inat_is_evex_prefix(attr) {
                b2 = need!(unsafe { insn.peek(2) });
                insn.vex_prefix.set_byte(2, b2);
                b2 = need!(unsafe { insn.peek(3) });
                insn.vex_prefix.set_byte(3, b2);
                insn.vex_prefix.nbytes = 4;
                insn.next_byte = insn.next_byte.wrapping_add(4);
                if insn.x86_64 != 0 && b2 & 0x80 != 0 {
                    /* VEX.W overrides opnd_size */
                    insn.opnd_bytes = 8;
                }
            } else if inat_is_vex3_prefix(attr) || inat_is_xop_prefix(attr) {
                b2 = need!(unsafe { insn.peek(2) });
                insn.vex_prefix.set_byte(2, b2);
                insn.vex_prefix.nbytes = 3;
                insn.next_byte = insn.next_byte.wrapping_add(3);
                if insn.x86_64 != 0 && b2 & 0x80 != 0 {
                    /* VEX.W/XOP.W overrides opnd_size */
                    insn.opnd_bytes = 8;
                }
            } else {
                /*
                 * For VEX2, fake VEX3-like byte#2.
                 * Makes it easier to decode vex.W, vex.vvvv,
                 * vex.L and vex.pp. Masking with 0x7f sets vex.W == 0.
                 */
                insn.vex_prefix.set_byte(2, b2 & 0x7f);
                insn.vex_prefix.nbytes = 2;
                insn.next_byte = insn.next_byte.wrapping_add(2);
            }
        }
    }
    insn.vex_prefix.got = 1;

    insn.prefixes.got = 1;

    0
}

/// `insn_get_opcode()`: collect opcode(s).
///
/// # Safety
/// `insn` must have been initialised by `insn_init()`.
#[no_mangle]
pub unsafe extern "C" fn insn_get_opcode(insn: *mut Insn) -> c_int {
    let insn = unsafe { &mut *insn };

    if insn.opcode.got != 0 {
        return 0;
    }

    let ret = unsafe { insn_get_prefixes(insn) };
    if ret != 0 {
        return ret;
    }

    /* Get first opcode */
    let mut op = need!(unsafe { insn.get_u8() });
    insn.opcode.set_byte(0, op);
    insn.opcode.nbytes = 1;

    'end: {
        /* Check if there is VEX/XOP prefix or not */
        if unsafe { insn.is_avx_or_xop() } {
            /* XOP prefix has different encoding */
            if insn.avx_insn_is_xop() {
                let m = insn.xop_map_bits();
                insn.attr = inat_get_xop_attribute(op, m);
                if !inat_accept_xop(insn.attr) {
                    insn.attr = 0;
                    return -EINVAL;
                }
                /* XOP has only 1 byte for opcode */
                break 'end;
            }

            let m = insn.vex_m_bits();
            let p = insn.vex_p_bits();
            insn.attr = inat_get_avx_attribute(op, m, p);
            /* SCALABLE EVEX uses p bits to encode operand size */
            if inat_evex_scalable(insn.attr) && insn.vex_w_bit() == 0 && p as u32 == INAT_PFX_OPNDSZ {
                insn.opnd_bytes = 2;
            }
            if (inat_must_evex(insn.attr) && !insn.is_evex())
                || (!inat_accept_vex(insn.attr) && !inat_is_group(insn.attr))
            {
                /* This instruction is bad */
                insn.attr = 0;
                return -EINVAL;
            }
            /* VEX has only 1 byte for opcode */
            break 'end;
        }

        /* Check if there is REX2 prefix or not */
        if unsafe { insn.is_rex2() } {
            if insn.rex2_m_bit() != 0 {
                /* map 1 is escape 0x0f */
                let esc_attr = inat_get_opcode_attribute(0x0f);

                let pfx_id = unsafe { insn.last_prefix_id() };
                insn.attr = inat_get_escape_attribute(op, pfx_id, esc_attr);
            } else {
                insn.attr = inat_get_opcode_attribute(op);
            }
            break 'end;
        }

        insn.attr = inat_get_opcode_attribute(op);
        if insn.x86_64 != 0 && inat_is_invalid64(insn.attr) {
            /* This instruction is invalid, like UD2. Stop decoding. */
            insn.attr &= INAT_INV64;
        }

        while inat_is_escape(insn.attr) {
            /* Get escaped opcode */
            op = need!(unsafe { insn.get_u8() });
            let i = insn.opcode.nbytes as usize;
            if i < 4 {
                insn.opcode.set_byte(i, op);
            }
            insn.opcode.nbytes = insn.opcode.nbytes.wrapping_add(1);
            let pfx_id = unsafe { insn.last_prefix_id() };
            insn.attr = inat_get_escape_attribute(op, pfx_id, insn.attr);
        }

        if inat_must_vex(insn.attr) {
            /* This instruction is bad */
            insn.attr = 0;
            return -EINVAL;
        }
    }

    insn.opcode.got = 1;
    0
}

/// `insn_get_modrm()`: collect ModRM byte, if any.
///
/// # Safety
/// `insn` must have been initialised by `insn_init()`.
#[no_mangle]
pub unsafe extern "C" fn insn_get_modrm(insn: *mut Insn) -> c_int {
    let insn = unsafe { &mut *insn };

    if insn.modrm.got != 0 {
        return 0;
    }

    let ret = unsafe { insn_get_opcode(insn) };
    if ret != 0 {
        return ret;
    }

    if inat_has_modrm(insn.attr) {
        let m = need!(unsafe { insn.get_u8() });
        insn.modrm.set(m as i32, 1);
        if inat_is_group(insn.attr) {
            let pfx_id = unsafe { insn.last_prefix_id() } as u8;
            insn.attr = inat_get_group_attribute(m, pfx_id as c_int, insn.attr);
            if unsafe { insn.is_avx_or_xop() } && !inat_accept_vex(insn.attr) && !inat_accept_xop(insn.attr) {
                /* Bad insn */
                insn.attr = 0;
                return -EINVAL;
            }
        }
    }

    if insn.x86_64 != 0 && inat_is_force64(insn.attr) {
        insn.opnd_bytes = 8;
    }

    insn.modrm.got = 1;
    0
}

/// `insn_rip_relative()`: does the instruction use RIP-relative addressing?
///
/// # Safety
/// `insn` must have been initialised by `insn_init()`.
#[no_mangle]
pub unsafe extern "C" fn insn_rip_relative(insn: *mut Insn) -> c_int {
    if unsafe { (*insn).x86_64 } == 0 {
        return 0;
    }

    let ret = unsafe { insn_get_modrm(insn) };
    if ret != 0 {
        return 0;
    }
    /*
     * For rip-relative instructions, the mod field (top 2 bits)
     * is zero and the r/m field (bottom 3 bits) is 0x5.
     */
    let modrm = unsafe { &(*insn).modrm };
    (modrm.nbytes != 0 && (modrm.byte(0) & 0xc7) == 0x5) as c_int
}

/// `insn_get_sib()`: get the SIB byte of the instruction.
///
/// # Safety
/// `insn` must have been initialised by `insn_init()`.
#[no_mangle]
pub unsafe extern "C" fn insn_get_sib(insn: *mut Insn) -> c_int {
    if unsafe { (*insn).sib.got } != 0 {
        return 0;
    }

    let ret = unsafe { insn_get_modrm(insn) };
    if ret != 0 {
        return ret;
    }

    let insn = unsafe { &mut *insn };
    if insn.modrm.nbytes != 0 {
        let modrm = insn.modrm.byte(0);
        if insn.addr_bytes != 2 && x86_modrm_mod(modrm) != 3 && x86_modrm_rm(modrm) == 4 {
            let v = need!(unsafe { insn.get_u8() });
            insn.sib.set(v as i32, 1);
        }
    }
    insn.sib.got = 1;

    0
}

/// `insn_get_displacement()`: get the displacement of the instruction.
///
/// # Safety
/// `insn` must have been initialised by `insn_init()`.
#[no_mangle]
pub unsafe extern "C" fn insn_get_displacement(insn: *mut Insn) -> c_int {
    if unsafe { (*insn).displacement.got } != 0 {
        return 0;
    }

    let ret = unsafe { insn_get_sib(insn) };
    if ret != 0 {
        return ret;
    }

    let insn = unsafe { &mut *insn };
    'out: {
        if insn.modrm.nbytes != 0 {
            /*
             * Interpreting the modrm byte:
             * mod = 00 - no displacement fields (exceptions below)
             * mod = 01 - 1-byte displacement field
             * mod = 10 - displacement field is 4 bytes, or 2 bytes if
             *	address size = 2 (0x67 prefix in 32-bit mode)
             * mod = 11 - no memory operand
             *
             * If address size = 2...
             * mod = 00, r/m = 110 - displacement field is 2 bytes
             *
             * If address size != 2...
             * mod != 11, r/m = 100 - SIB byte exists
             * mod = 00, SIB base = 101 - displacement field is 4 bytes
             * mod = 00, r/m = 101 - rip-relative addressing, displacement
             *	field is 4 bytes
             */
            let m = x86_modrm_mod(insn.modrm.value as u8);
            let rm = x86_modrm_rm(insn.modrm.value as u8);
            let base = x86_sib_base(insn.sib.value as u8);
            if m == 3 {
                break 'out;
            }
            if m == 1 {
                let v = need!(unsafe { insn.get_i8() });
                insn.displacement.set(v, 1);
            } else if insn.addr_bytes == 2 {
                if (m == 0 && rm == 6) || m == 2 {
                    let v = need!(unsafe { insn.get_i16() });
                    insn.displacement.set(v, 2);
                }
            } else if (m == 0 && rm == 5) || m == 2 || (m == 0 && base == 5) {
                let v = need!(unsafe { insn.get_i32() });
                insn.displacement.set(v, 4);
            }
        }
    }
    insn.displacement.got = 1;
    0
}

/// `__get_moffset()`: decode moffset16/32/64. Returns false on failure.
unsafe fn __get_moffset(insn: &mut Insn) -> bool {
    match insn.addr_bytes {
        2 => {
            let Some(v) = (unsafe { insn.get_i16() }) else { return false };
            insn.immediate1.set(v, 2);
        }
        4 => {
            let Some(v) = (unsafe { insn.get_i32() }) else { return false };
            insn.immediate1.set(v, 4);
        }
        8 => {
            let Some(v) = (unsafe { insn.get_i32() }) else { return false };
            insn.immediate1.set(v, 4);
            let Some(v) = (unsafe { insn.get_i32() }) else { return false };
            insn.immediate2.set(v, 4);
        }
        _ => return false, /* opnd_bytes must be modified manually */
    }
    insn.immediate1.got = 1;
    insn.immediate2.got = 1;

    true
}

/// `__get_immv32()`: decode imm v32 (Iz). Returns false on failure.
unsafe fn __get_immv32(insn: &mut Insn) -> bool {
    match insn.opnd_bytes {
        2 => {
            let Some(v) = (unsafe { insn.get_i16() }) else { return false };
            insn.immediate1.set(v, 2);
        }
        4 | 8 => {
            let Some(v) = (unsafe { insn.get_i32() }) else { return false };
            insn.immediate1.set(v, 4);
        }
        _ => return false, /* opnd_bytes must be modified manually */
    }

    true
}

/// `__get_immv()`: decode imm v64 (Iv/Ov). Returns false on failure.
unsafe fn __get_immv(insn: &mut Insn) -> bool {
    match insn.opnd_bytes {
        2 => {
            let Some(v) = (unsafe { insn.get_i16() }) else { return false };
            insn.immediate1.set(v, 2);
        }
        4 => {
            let Some(v) = (unsafe { insn.get_i32() }) else { return false };
            insn.immediate1.set(v, 4);
            insn.immediate1.nbytes = 4;
        }
        8 => {
            let Some(v) = (unsafe { insn.get_i32() }) else { return false };
            insn.immediate1.set(v, 4);
            let Some(v) = (unsafe { insn.get_i32() }) else { return false };
            insn.immediate2.set(v, 4);
        }
        _ => return false, /* opnd_bytes must be modified manually */
    }
    insn.immediate1.got = 1;
    insn.immediate2.got = 1;

    true
}

/// `__get_immptr()`: decode ptr16:16/32 (Ap).
unsafe fn __get_immptr(insn: &mut Insn) -> bool {
    match insn.opnd_bytes {
        2 => {
            let Some(v) = (unsafe { insn.get_i16() }) else { return false };
            insn.immediate1.set(v, 2);
        }
        4 => {
            let Some(v) = (unsafe { insn.get_i32() }) else { return false };
            insn.immediate1.set(v, 4);
        }
        8 => {
            /* ptr16:64 is not exist (no segment) */
            return false;
        }
        _ => return false, /* opnd_bytes must be modified manually */
    }
    let Some(v) = (unsafe { insn.get_u16() }) else { return false };
    insn.immediate2.set(v, 2);
    insn.immediate1.got = 1;
    insn.immediate2.got = 1;

    true
}

/// `insn_get_immediate()`: get the immediate in an instruction.
///
/// # Safety
/// `insn` must have been initialised by `insn_init()`.
#[no_mangle]
pub unsafe extern "C" fn insn_get_immediate(insn: *mut Insn) -> c_int {
    if unsafe { (*insn).immediate1.got } != 0 {
        return 0;
    }

    let ret = unsafe { insn_get_displacement(insn) };
    if ret != 0 {
        return ret;
    }

    let insn = unsafe { &mut *insn };
    'done: {
        if inat_has_moffset(insn.attr) {
            if !unsafe { __get_moffset(insn) } {
                return -ENODATA;
            }
            break 'done;
        }

        if !inat_has_immediate(insn.attr) {
            break 'done;
        }

        match inat_immediate_size(insn.attr) {
            INAT_IMM_BYTE => {
                let v = need!(unsafe { insn.get_i8() });
                insn.immediate1.set(v, 1);
            }
            INAT_IMM_WORD => {
                let v = need!(unsafe { insn.get_i16() });
                insn.immediate1.set(v, 2);
            }
            INAT_IMM_DWORD => {
                let v = need!(unsafe { insn.get_i32() });
                insn.immediate1.set(v, 4);
            }
            INAT_IMM_QWORD => {
                let v = need!(unsafe { insn.get_i32() });
                insn.immediate1.set(v, 4);
                let v = need!(unsafe { insn.get_i32() });
                insn.immediate2.set(v, 4);
            }
            INAT_IMM_PTR => {
                if !unsafe { __get_immptr(insn) } {
                    return -ENODATA;
                }
            }
            INAT_IMM_VWORD32 => {
                if !unsafe { __get_immv32(insn) } {
                    return -ENODATA;
                }
            }
            INAT_IMM_VWORD => {
                if !unsafe { __get_immv(insn) } {
                    return -ENODATA;
                }
            }
            _ => {
                /* Here, insn must have an immediate, but failed */
                return -ENODATA;
            }
        }
        if inat_has_second_immediate(insn.attr) {
            let v = need!(unsafe { insn.get_i8() });
            insn.immediate2.set(v, 1);
        }
    }
    insn.immediate1.got = 1;
    0
}

/// `insn_get_length()`: get the length of the instruction.
///
/// # Safety
/// `insn` must have been initialised by `insn_init()`.
#[no_mangle]
pub unsafe extern "C" fn insn_get_length(insn: *mut Insn) -> c_int {
    if unsafe { (*insn).length } != 0 {
        return 0;
    }

    let ret = unsafe { insn_get_immediate(insn) };
    if ret != 0 {
        return ret;
    }

    let insn = unsafe { &mut *insn };
    insn.length = (insn.next_byte as usize).wrapping_sub(insn.kaddr as usize) as u8;

    0
}

/// `enum insn_mode`.
const INSN_MODE_64: c_int = 1;
const INSN_MODE_KERN: c_int = 2;

/// `insn_decode()`: decode an x86 instruction.
///
/// # Safety
/// `insn` writable; `kaddr` readable for `buf_len` bytes (clamped to 15).
#[no_mangle]
pub unsafe extern "C" fn insn_decode(insn: *mut Insn, kaddr: *const c_void, buf_len: c_int, m: c_int) -> c_int {
    if m == INSN_MODE_KERN {
        /* IS_ENABLED(CONFIG_X86_64) */
        unsafe { insn_init(insn, kaddr, buf_len, cfg!(target_arch = "x86_64") as c_int) };
    } else {
        unsafe { insn_init(insn, kaddr, buf_len, (m == INSN_MODE_64) as c_int) };
    }

    let ret = unsafe { insn_get_length(insn) };
    if ret != 0 {
        return ret;
    }

    /* insn_complete(): ensure this instruction is decoded completely */
    let i = unsafe { &*insn };
    if i.opcode.got != 0 && i.modrm.got != 0 && i.sib.got != 0 && i.displacement.got != 0 && i.immediate1.got != 0 {
        return 0;
    }

    -EINVAL
}
