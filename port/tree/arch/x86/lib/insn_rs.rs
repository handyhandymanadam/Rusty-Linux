//! x86 instruction analysis -- the Rust behind `arch/x86/lib/insn.c` and `inat.c`.
//!
//! Ported from `arch/x86/lib/insn.c` and `arch/x86/lib/inat.c` (6.18.49):
//! "x86 instruction analysis", Copyright (C) IBM Corporation, 2002, 2004, 2009.
//! Every function here is a straight translation of the C, statement by statement
//! (the C is the specification for a decoder: whatever it accepts or rejects, we do).
//!
//! # What is here, what stayed in C
//!
//! Here: `insn_init`, `insn_get_prefixes/opcode/modrm/sib/displacement/immediate/length`,
//! `insn_rip_relative`, `insn_decode` and the six `inat_get_*` lookups. In C: the
//! generated opcode tables (`inat-tables.c`, included by `inat_tables_glue.c`: pure
//! data), the `static inline` helpers in `asm/insn.h` / `asm/inat.h` that OTHER C
//! files use (mirrored here only where this file needs them), and `insn-eval.c`.
//! Neither file carries an `EXPORT_SYMBOL` (checked), so there is no MODVERSIONS
//! contract to keep. Upstream's `insn.c` / `inat.c` stay in the tree untouched
//! because the boot stub (`boot/compressed/sev-handle-vc.c`) `#include`s them.
//!
//! # Layout
//!
//! [`Insn`] mirrors `struct insn` (112 bytes): the Rust never changes a field's
//! position; `rig/layout-check.sh` compares it with the built kernel's DWARF.
//! `struct insn_field` is the little-endian arm (a `value` that aliases
//! `bytes[4]`); `value` is stored as an `i32` and bytes are taken from it with
//! shifts, which is the same memory on a little-endian CPU.
//!
//! # Divergence (benign, UB only)
//!
//! `opcode.bytes[opcode.nbytes++] = op` writes past `bytes[3]` if a table ever
//! chained more than four escape bytes; the C would corrupt the next field, this
//! ignores such a write. The generated tables never chain beyond three bytes
//! (the differential test enumerates the opcode space).
//!
//! Replaces: arch/x86/lib/insn.c, arch/x86/lib/inat.c (CONFIG_RUST build)

use core::ffi::{c_int, c_void};

const ENODATA: c_int = 61;
const EINVAL: c_int = 22;

const MAX_INSN_SIZE: c_int = 15;

type InsnAttr = u32;

