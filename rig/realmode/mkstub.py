#!/usr/bin/env python3
"""mkstub.py <root> <T> -- host stand-in for arch/x86/boot/boot.h (+ io.h's asm/shared/io.h) used by the host differentials of the edd/apm/video
ports (run-edd-diff.sh, run-apm-diff.sh, run-video-diff.sh). The ORIGINAL .c files are compiled UNCHANGED against it. Everything that is data or
pure C in the real boot.h is extracted VERBATIM (struct biosregs, the heap inlines, the cmdline_find_option inlines, STACK_SIZE); what is a machine
instruction (ds(), set_fs(), rdfs8/16, the port functions) is a mock the harness defines (mock_*), and the callees (intcall, initregs, puts,
putchar, getchar, printf, ...) are renamed with -D by the runner so the C side calls mocks while the Rust side links the same mocks."""
import re, sys
root, T = sys.argv[1:3]
B = open(root + '/src/linux/arch/x86/boot/boot.h').read()
def between(s, a, b):
    i = s.index(a); j = s.index(b, i); return s[i:j]
regs = between(B, 'struct biosregs {', 'void intcall(') + 'void intcall(u8 int_no, const struct biosregs *ireg, struct biosregs *oreg);\n'
cmd = between(B, 'int __cmdline_find_option(', '/* cpu.c, cpucheck.c */')
heap = between(B, '/* Heap -- available for dynamic lists. */', '/* copy.S */')
stack = re.search(r'#define STACK_SIZE\s+\d+', B).group(0)
open(T + '/boot.h', 'w').write('''/* generated by mkstub.py: host stand-in for boot.h; data/pure-C parts extracted verbatim from the real header */
#ifndef BOOT_BOOT_H
#define BOOT_BOOT_H
#include <stdint.h>
#include <stddef.h>
#include <string.h>
#include <stdarg.h>
#include <stdbool.h>
typedef uint8_t u8; typedef uint16_t u16; typedef uint32_t u32; typedef uint64_t u64;
#define __section(s) __attribute__((section(HOST_VIDEOCARDS_SECTION)))
#define X86_EFLAGS_CF 0x00000001   /* asm/processor-flags.h (checked by rig/stubh/consts_check.py for the Rust copy) */
#define ARRAY_SIZE(x) (sizeof(x) / sizeof(*(x)))
%(stack)s
#include <asm/bootparam.h>
#include <linux/edd.h>
typedef unsigned int addr_t;
extern struct setup_header hdr;
extern struct boot_params boot_params;
#define cpu_relax() do { } while (0)
%(regs)s
void initregs(struct biosregs *regs);
u16 mock_ds(void); void mock_set_fs(u16 s);
u8 mock_rdfs8(addr_t a); u16 mock_rdfs16(addr_t a);
static inline u16 ds(void) { return mock_ds(); }
static inline void set_fs(u16 seg) { mock_set_fs(seg); }
static inline u8 rdfs8(addr_t addr) { return mock_rdfs8(addr); }
static inline u16 rdfs16(addr_t addr) { return mock_rdfs16(addr); }
%(heap)s
void copy_to_fs(addr_t dst, void *src, size_t len);
void *copy_from_fs(void *dst, addr_t src, size_t len);
%(cmd)s
void query_edd(void);
int query_apm_bios(void);
void __attribute__((noreturn)) die(void);
int sprintf(char *buf, const char *fmt, ...);
int printf(const char *fmt, ...);
void puts(const char *);
void putchar(int);
int getchar(void);
void kbd_flush(void);
int getchar_timeout(void);
void set_video(void);
int set_mode(u16 mode);
int mode_defined(u16 mode);
void probe_cards(int unsafe);
void vesa_store_edid(void);
#include "io.h"
#endif
''' % dict(stack=stack, regs=regs, heap=heap, cmd=cmd))
open(T + '/string.h', 'w').write('/* the real boot "string.h" declarations come from libc here (strcmp, memset, memcpy) */\n#include_next <string.h>\n')
import os
os.makedirs(T + '/inc/asm/shared', exist_ok=True)
open(T + '/inc/asm/shared/io.h', 'w').write('''/* host stand-in for asm/shared/io.h: the port functions are mocks (the real ones are in/out instructions) */
#include <stdint.h>
typedef uint8_t u8; typedef uint16_t u16; typedef uint32_t u32;
u8 mock_inb(u16 port); void mock_outb(u8 v, u16 port); void mock_outw(u16 v, u16 port);
static inline void __outb(u8 v, u16 port) { mock_outb(v, port); }
static inline u8 __inb(u16 port) { return mock_inb(port); }
static inline void __outw(u16 v, u16 port) { mock_outw(v, port); }
#define inb __inb
#define inw __inw
#define inl __inl
#define outb __outb
#define outw __outw
#define outl __outl
''')
