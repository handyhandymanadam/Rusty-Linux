#!/usr/bin/env bash
# run-main-diff.sh [scenarios-per-variant] [seed] -- lockstep differential of port/tree/arch/x86/boot/main_rs.rs against the original arch/x86/boot/main.c, both built for the HOST
# with mocks for every outside effect, in all 8 build-configuration variants (CONFIG_X86_64 x CONFIG_APM x CONFIG_EDD: the conditional compilation main.c has). The C copy is the
# original main.c UNCHANGED (only its global/callee names are renamed with -D: main, boot_params, pio_ops, HEAP, heap_end -> c_*; the callees -> mock_*) compiled against a stand-in
# boot.h that takes the REAL definitions by mechanical extraction: struct biosregs, the cmdline_find_option_bool() inline, STACK_SIZE (arch/x86/boot/boot.h), OLD_CL_MAGIC /
# OLD_CL_ADDRESS (asm/setup.h), struct boot_params/setup_header/CAN_USE_HEAP (uapi asm/bootparam.h), struct port_io_ops + init_default_io_ops (arch/x86/boot/io.h); mocks:
# ds(), the esp register (current_stack_pointer, as u32), absolute_pointer(OLD_CL_ADDRESS) (a host buffer), the port functions, BIOS intcall/initregs, puts, console_init, ...
# The Rust is main_rs.rs as a staticlib with --cfg host_mock and main_gen.rs made by the real C preprocessor for each variant (the Makefile rule). Sabotage: SABOTAGE=sed-expr applies to a
# copy of the Rust. VARIANTS="0 1 ..." restricts the variants (bit0 = X86_64, bit1 = APM, bit2 = EDD).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd); root=$(cd "$here/../.." && pwd)
. "$root/kbuild-env.sh" >/dev/null 2>&1
SRC=$root/src/linux; B=$root/build-fast
KINC="-I$SRC/arch/x86/include/uapi -I$SRC/include/uapi -I$B/arch/x86/include/generated/uapi -I$B/include/generated/uapi"
GINC="-I$SRC/arch/x86/include -I$SRC/include $KINC -I$B/arch/x86/include/generated -I$B/include/generated"
T=$(mktemp -d); trap 'rm -rf $T' EXIT; mkdir -p "$T/inc/asm/shared" "$T/inc/linux"
python3 - "$root" "$T" <<'PY'
import re,sys
root,T=sys.argv[1:3]
B=open(root+'/src/linux/arch/x86/boot/boot.h').read()
def between(s,a,b): i=s.index(a); j=s.index(b,i); return s[i:j]
regs=between(B,'struct biosregs {','void intcall(')+'void intcall(u8 int_no, const struct biosregs *ireg, struct biosregs *oreg);\n'
cmd=between(B,'int __cmdline_find_option(','/* cpu.c, cpucheck.c */')
stack=re.search(r'#define STACK_SIZE\s+\d+',B).group(0)
initregs=re.search(r'void initregs\(struct biosregs \*regs\);',B).group(0)
S=open(root+'/src/linux/arch/x86/include/asm/setup.h').read()
old=''.join(l+'\n' for l in S.split('\n') if re.match(r'#define\s+OLD_CL_(MAGIC|ADDRESS)\b',l))
assert 'OLD_CL_MAGIC' in old and 'OLD_CL_ADDRESS' in old
open(T+'/boot.h','w').write('''/* generated by run-main-diff.sh: host stand-in for boot.h as used by arch/x86/boot/main.c; the definitions below are extracted verbatim from the real headers */
#ifndef BOOT_H
#define BOOT_H
#include <stdint.h>
#include <stddef.h>
#include <string.h>
typedef uint8_t u8; typedef uint16_t u16; typedef uint32_t u32; typedef uint64_t u64;
#include <asm/bootparam.h>
%s
%s
extern struct boot_params boot_params;
extern struct setup_header hdr;
extern char _end[];
extern char *HEAP;
extern char *heap_end;
struct cpu_features { int level; int family; int model; u32 flags[22]; };   /* cpuflags.h: only .level is read by main.c */
extern struct cpu_features cpu;
%s
%s
void puts(const char *s);
void console_init(void);
int validate_cpu(void);
void detect_memory(void);
void set_video(void);
void query_apm_bios(void);
void query_edd(void);
void __attribute__((noreturn)) die(void);
void __attribute__((noreturn)) go_to_protected_mode(void);
u16 mock_ds(void);
unsigned mock_esp(void);
void *mock_oldcmd(void);
static inline u16 ds(void) { return mock_ds(); }
#define current_stack_pointer ((unsigned)mock_esp())   /* unsigned long on the 32-bit target */
#define absolute_pointer(val) ((void *)mock_oldcmd())
%s
#include "io.h"
#endif
''' % (regs, 'extern struct boot_params boot_params;' if False else '', initregs, stack, old))
# the cmdline inline needs boot_params declared first: re-emit with the extracted text after the extern
t=open(T+'/boot.h').read().replace('extern char _end[];', cmd+'\nextern char _end[];',1)
open(T+'/boot.h','w').write(t)
open(T+'/string.h','w').write('/* main.c includes "string.h": memcpy comes from <string.h> on the host */\n')
open(T+'/inc/linux/build_bug.h','w').write('#define BUILD_BUG_ON(c) _Static_assert(!(c), "BUILD_BUG_ON")\n')
open(T+'/inc/asm/shared/io.h','w').write('''/* host stand-in for asm/shared/io.h: the port functions are mocks (the real ones are `in`/`out` instructions) */
#include <stdint.h>
typedef uint8_t u8; typedef uint16_t u16; typedef uint32_t u32;
u8 mock_inb(u16 port); void mock_outb(u8 v, u16 port); void mock_outw(u16 v, u16 port);
static inline void __outb(u8 v, u16 port) { mock_outb(v, port); }
static inline u8 __inb(u16 port) { return mock_inb(port); }
static inline void __outw(u16 v, u16 port) { mock_outw(v, port); }
#define inb __inb
#define inw __inw
#define inl __inl
#define outb __outb
#define outw __outw
#define outl __outl
''')
open(T+'/main_c.c','w').write(open(root+'/src/linux/arch/x86/boot/main.c').read())
PY
cp "$SRC/arch/x86/boot/io.h" "$T/io.h"
cp "$root/port/tree/arch/x86/boot/main_rs.rs" "$T/main_rs.rs"
cp "$root/port/tree/arch/x86/boot/main_gen.rs.in" "$T/main_gen.rs.in"
if [ -n "${SABOTAGE:-}" ]; then
  cp "$T/main_rs.rs" "$T/main_rs.before"; sed -i "$SABOTAGE" "$T/main_rs.rs"
  cmp -s "$T/main_rs.rs" "$T/main_rs.before" && { echo "SABOTAGE did not change the file"; exit 2; }
fi
REN="-Dmain=c_main -Dboot_params=c_boot_params -Dpio_ops=c_pio_ops -DHEAP=c_HEAP -Dheap_end=c_heap_end -Dintcall=mock_intcall -Dinitregs=mock_initregs -Dputs=mock_puts -Dconsole_init=mock_console_init -D__cmdline_find_option_bool=mock_cmdline_find_option_bool -Dvalidate_cpu=mock_validate_cpu -Ddetect_memory=mock_detect_memory -Dset_video=mock_set_video -Dgo_to_protected_mode=mock_go_to_protected_mode -Ddie=mock_die -Dquery_apm_bios=mock_query_apm_bios -Dquery_edd=mock_query_edd"
rc=0
for v in ${VARIANTS:-0 1 2 3 4 5 6 7}; do
  X=$((v&1)); A=$(((v>>1)&1)); E=$(((v>>2)&1)); D=$T/v$v; mkdir -p $D
  CFG=""; [ $X = 1 ] && CFG="$CFG -DCONFIG_X86_64=1"; [ $A = 1 ] && CFG="$CFG -DCONFIG_APM=1"; [ $E = 1 ] && CFG="$CFG -DCONFIG_EDD=1"
  # main_gen.rs for this variant: the same C-preprocessor rule as the Makefile (cpucheck_gen), configuration switches given by -D instead of autoconf.h
  clang -I$T/inc $GINC $CFG -D__KERNEL__ -E -P -x c "$T/main_gen.rs.in" | sed -n -e 's/\(0x[0-9a-fA-F]*\|[0-9][0-9]*\)\(ULL\|UL\|U\|L\)\b/\1/g' -e '/^pub const/p' > $D/main_gen.rs
  if [ $v = 1 ]; then cmp <(grep -v '^$' $B/arch/x86/boot/main_gen.rs) <(grep -v '^$' $D/main_gen.rs) && echo "variant 1 main_gen.rs == the build's real main_gen.rs"; fi
  clang -O1 -w -fwrapv -I$T/inc -I$SRC/arch/x86/boot $KINC $CFG $REN -D_SETUP -c "$T/main_c.c" -o "$D/c_main.o"
  RM_GEN_DIR=$D RUSTC_BOOTSTRAP=1 "$KB_RUSTC" --edition=2021 --crate-type=staticlib -C opt-level=2 -C panic=abort --cfg host_mock \
      --crate-name=main_rs -o "$D/libmain_rs.a" "$T/main_rs.rs" 2>"$D/rustc.log" || { cat "$D/rustc.log"; exit 3; }
  clang -O2 -w -I$T/inc $KINC -DV_X64=$X -DV_APM=$A -DV_EDD=$E "$here/main-diff.c" -o "$D/h" "$D/c_main.o" "$D/libmain_rs.a" -lpthread -ldl -lm
  echo "== variant $v: X86_64=$X APM=$A EDD=$E"
  "$D/h" "${1:-300000}" "${2:-1}" || rc=1
done
exit $rc
