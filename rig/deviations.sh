#!/usr/bin/env bash
# deviations.sh [--keep]
#
# EVERY WAY THIS TREE DIFFERS FROM THE TARBALL, and whether each difference is
# accounted for.
#
# WHY THIS EXISTS. src/ is gitignored -- the kernel tree is not ours to version
# -- so a change made there is invisible to git, is not reapplied by
# rig/apply.sh, and vanishes on a fresh extract. Until 2026-09-04 the only
# things tracked were files under port/tree/ (lib/ plus four arch/x86 files)
# and a one-line exception list. Anything edited anywhere else was untracked by
# construction. Adam asked for this when we started contemplating a kbuild
# change for Rust-in-LTO: a deliberate deviation we cannot see is one we cannot
# reapply after a rebase.
#
# WHAT IT DOES. Extracts the sha256-verified tarball to a scratch directory and
# diffs the whole tree against it, then sorts every difference into:
#
#   managed     -- the file is under port/tree/, so rig/apply.sh owns it and
#                  git versions it. This is the port itself; expected.
#   declared    -- listed in the registry block of logs/deviations.md, with a
#                  reason and a REBASE instruction. Expected.
#   *** UNDECLARED -- neither. Exits 1. This is the case the tool exists for.
#   stale       -- declared, but the file no longer differs. Either upstream
#                  adopted it or we lost the change. Warned, not failed: at
#                  rebase time this is the most useful line in the output.
#
# COST. A full extract plus diff over ~91,000 files; a couple of minutes and
# about 1.5 GB of scratch, removed on exit unless --keep. This is a
# before-a-rebase / end-of-session tool, not a per-build one.
set -uo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
tar_file="$root/src/linux-6.18.49.tar.xz"
top=linux-6.18.49
reg="$root/logs/deviations.md"
keep=0
[ "${1:-}" = "--keep" ] && keep=1

work="$root/rig/cache/pristine-tree"
if [ ! -d "$work/$top" ]; then
    echo "extracting the pristine tarball (a few minutes, ~1.5 GB)..."
    mkdir -p "$work"
    tar -xf "$tar_file" -C "$work" || { echo "extract failed" >&2; exit 2; }
fi
pris="$work/$top"
# src/linux is a SYMLINK to src/linux-6.18.49. The first version of this script
# passed it to diff with --no-dereference, so diff compared the symlink itself
# instead of recursing, produced ZERO lines, and cheerfully reported
# "0 UNDECLARED" having examined nothing. Resolve it.
tree=$(readlink -f "$root/src/linux")
[ -d "$tree" ] || { echo "src/linux does not resolve to a directory" >&2; exit 2; }

# The registry: a TSV fenced block in logs/deviations.md. Prose for humans
# above it, machine-readable inside it, one file per line:
#   <kernel-relative path>\t<upstream?>\t<rebase action>\t<one-line reason>
declared=$(mktemp); trap 'rm -f "$declared"' EXIT
awk '/^```registry$/{f=1;next} /^```$/{f=0} f' "$reg" 2>/dev/null \
    | grep -v '^[[:space:]]*#' | grep -v '^[[:space:]]*$' > "$declared"

n_managed=0; n_declared=0; n_undecl=0; n_stale=0; n_generated=0; fail=0
seen=$(mktemp); : > "$seen"; trap 'rm -f "$declared" "$seen"' EXIT

echo
printf '%-58s %s\n' "FILE" "STATUS"
while IFS= read -r rel; do
    [ -n "$rel" ] || continue
    echo "$rel" >> "$seen"
    line=$(grep -P "^\Q$rel\E\t" "$declared")
    if [ -f "$root/port/tree/$rel" ]; then
        n_managed=$((n_managed + 1))
        # A managed file can ALSO be declared: port/tree owns it, and it
        # additionally carries a deliberate divergence from upstream that a
        # rebase has to decide about. lib/zlib_inflate/inflate.c is both. Print
        # it, or the rebase instruction is invisible in the common case.
        if [ -n "$line" ]; then
            printf '%-58s managed + declared -- at rebase: %s\n' "$rel" "$(echo "$line" | cut -f3)"
            n_declared=$((n_declared + 1))
        fi
        continue
    fi
    if [ -n "$line" ]; then
        printf '%-58s declared -- at rebase: %s\n' "$rel" "$(echo "$line" | cut -f3)"
        n_declared=$((n_declared + 1)); continue
    fi
    # THE CONFIG_RUST=n ARM. rig/apply.sh writes <base>_norust.c beside every
    # port/pristine/ body, so those files are in the tree, are not under
    # port/tree/, and are not divergences: each one IS upstream, byte for
    # byte, at a second filename. They were reported UNDECLARED -- 66 of them
    # on 2026-09-04 -- which is a false alarm loud enough to hide a real one.
    #
    # "Generated by apply.sh" is NOT what is checked here. THE BYTES ARE. A
    # _norust.c that has drifted from its pristine source is exactly the
    # failure RAISE 2 rests on not happening, so it must still report.
    case "$rel" in
      *_norust.c)
        src="$root/port/pristine/${rel%_norust.c}.c"
        if [ -f "$src" ] && cmp -s "$src" "$tree/$rel"; then
            n_generated=$((n_generated + 1)); continue
        fi
        printf '%-58s *** _norust.c DIFFERS FROM ITS PRISTINE SOURCE\n' "$rel"
        n_undecl=$((n_undecl + 1)); fail=1; continue;;
    esac
    printf '%-58s *** UNDECLARED\n' "$rel"
    n_undecl=$((n_undecl + 1)); fail=1
done < <(
    diff -rq "$pris" "$tree" 2>/dev/null \
      | sed -n "s|^Files $pris/\(.*\) and .* differ$|\1|p;
                s|^Only in $tree\(.*\): \(.*\)$|\1/\2|p" \
      | sed 's|^/||' | sort -u
)

# Declared but no longer differing: the rebase signal.
while IFS=$'\t' read -r rel up act why; do
    [ -n "$rel" ] || continue
    grep -qxF "$rel" "$seen" && continue
    printf '%-58s stale -- declared but identical to the tarball now\n' "$rel"
    n_stale=$((n_stale + 1))
done < "$declared"

n_port=$(find "$root/port/tree" -type f \( -name '*.c' -o -name '*.rs' -o -name Makefile \) | wc -l)
echo
echo "$n_managed managed by port/tree, $n_generated generated _norust.c" \
     "(byte-identical to port/pristine), $n_declared declared, $n_stale stale," \
     "$n_undecl UNDECLARED"

# STATUS.md lesson 9. This script's whole output is a negative result, so a
# clean run with an implausible volume is the dangerous case -- and it is not
# hypothetical: the first version passed src/linux (a SYMLINK) to diff with
# --no-dereference, compared nothing, and reported 0 UNDECLARED.
if [ "$n_managed" -lt 10 ] && [ "$n_port" -gt 10 ]; then
    echo "*** IMPLAUSIBLE: $n_port files under port/tree but only $n_managed" >&2
    echo "    differences attributed to it. The comparison did not happen." >&2
    exit 2
fi
if [ "$n_undecl" != 0 ]; then
    echo "*** an undeclared difference from the tarball: it is invisible to git," >&2
    echo "    will not be reapplied by rig/apply.sh, and will be lost on a fresh" >&2
    echo "    extract. Put it under port/tree/ or declare it in logs/deviations.md." >&2
fi
[ "$keep" = 1 ] || { echo "(removing the scratch extract; --keep to reuse it)"; rm -rf "$work"; }
exit $fail
